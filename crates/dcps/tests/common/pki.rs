//! Minting a test identity CA and its leaves, once.
//!
//! Three security tests need the same thing before they can start: an
//! identity CA and one or more leaf certificates signed by it, in the
//! shape DDS-Security 1.2 §10.3.1 describes. The recipe stood three
//! times, copied — and when the X.509 version stopped being left to the
//! local OpenSSL default, it had to be corrected in all three. The
//! copy-paste gate reported the growth, which is the right report: the
//! recipe carries a rule, and a rule in three places is a rule that
//! will be fixed in two of them.
//!
//! # The rule
//!
//! DDS-Security 1.2 §10.3.1.3 requires an X.509 **v3** identity
//! certificate, and `crates/security-pki` enforces it — the documented
//! deviation for v1 is opt-in and stays opt-in.
//!
//! A certificate is v3 exactly when it carries at least one extension
//! (RFC 5280 §4.1.2.1), and whether `openssl x509 -req -CA` adds one on
//! its own differs between OpenSSL releases. On a workstation with
//! OpenSSL 3.6.3 the leaf comes out `Version: 3` with Subject Key
//! Identifier and Authority Key Identifier; in the CI image
//! (`rust:1.88-bookworm`) the same command produced `Version: 1`, and
//! these tests failed with `AuthenticationFailed` while every other
//! security test in the same run passed.
//!
//! So the extensions are named rather than inherited. The ones below
//! are exactly what the newer OpenSSL adds by itself, which makes this
//! the certificate these tests have been passing with — on every
//! OpenSSL version. No `keyUsage` and no `extendedKeyUsage`: both would
//! change what is validated, and the point here is the version.

// Not every file that includes this uses every part of it — the
// GUID-wiring test mints and throws the paths away, because it reads
// them back off disk by name.
#![allow(dead_code)]

use std::path::{Path, PathBuf};
use std::process::Command;
use std::sync::Mutex;

/// `openssl` is not re-entrant enough for a parallel test binary: the
/// CA serial file is shared state, and a storm of sub-processes is its
/// own kind of flake.
pub static OPENSSL_LOCK: Mutex<()> = Mutex::new(());

/// Whether `openssl` is on this machine at all.
pub fn openssl_available() -> bool {
    Command::new("openssl")
        .arg("version")
        .output()
        .map(|o| o.status.success())
        .unwrap_or(false)
}

/// Runs one `openssl` step, and says which one failed if one does.
pub fn must_run(label: &str, mut cmd: Command) {
    let out = cmd
        .output()
        .unwrap_or_else(|e| panic!("openssl {label}: spawn failed: {e}"));
    if !out.status.success() {
        panic!(
            "openssl {label}: exit={:?}\nstdout: {}\nstderr: {}",
            out.status,
            String::from_utf8_lossy(&out.stdout),
            String::from_utf8_lossy(&out.stderr),
        );
    }
}

/// A directory of this run's own, under the system temporary directory.
pub fn tempdir_unique(prefix: &str) -> PathBuf {
    let now = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_nanos())
        .unwrap_or(0);
    let p = std::env::temp_dir().join(format!("{prefix}{now}_{}", std::process::id()));
    std::fs::create_dir_all(&p).unwrap();
    p
}

/// One minted leaf: its certificate and its PKCS#8 private key.
pub struct Identity {
    pub cert: PathBuf,
    pub key: PathBuf,
}

/// An identity CA in `<dir>/certs`, and one leaf per name signed by it.
///
/// `ca_subject` and `leaf_subject` are whole `-subj` strings; the leaf
/// one takes the name through `{name}`, so a caller writes
/// `"/CN=zerodds-guid-{name}"`.
///
/// The keys are ECDSA P-256 and the leaf key is generated by
/// `openssl genpkey`, which writes PKCS#8 — the format the ZeroDDS PKI
/// plugin and the DDS-Security 1.2 model both expect, not traditional
/// EC.
pub fn mint_ca_and_leaves(
    dir: &Path,
    ca_subject: &str,
    leaf_subject: &str,
    names: &[&str],
) -> Vec<Identity> {
    let certs = dir.join("certs");
    std::fs::create_dir_all(&certs).unwrap();

    let leaf_ext = certs.join("leaf_ext.cnf");
    std::fs::write(
        &leaf_ext,
        "subjectKeyIdentifier=hash\nauthorityKeyIdentifier=keyid\n",
    )
    .unwrap();

    let ca_key = certs.join("identity_ca_key.pem");
    let ca_cert = certs.join("identity_ca.pem");
    let mut c = Command::new("openssl");
    c.args([
        "ecparam",
        "-name",
        "prime256v1",
        "-genkey",
        "-noout",
        "-out",
    ])
    .arg(&ca_key);
    must_run("ecparam ca-key", c);

    let mut c = Command::new("openssl");
    c.args(["req", "-x509", "-new", "-nodes", "-key"])
        .arg(&ca_key)
        // Same reason as the leaf: name the extensions rather than
        // depend on `x509_extensions` in the local openssl.cnf. These
        // two are what the default `v3_ca` section produces.
        .args([
            "-addext",
            "basicConstraints=critical,CA:TRUE",
            "-addext",
            "subjectKeyIdentifier=hash",
        ])
        .args(["-days", "30", "-subj", ca_subject, "-out"])
        .arg(&ca_cert);
    must_run("ca self-sign", c);

    names
        .iter()
        .map(|name| {
            let key = certs.join(format!("{name}_key.pem"));
            let csr = certs.join(format!("{name}.csr"));
            let cert = certs.join(format!("{name}_cert.pem"));

            let mut c = Command::new("openssl");
            c.args([
                "genpkey",
                "-algorithm",
                "EC",
                "-pkeyopt",
                "ec_paramgen_curve:P-256",
                "-out",
            ])
            .arg(&key);
            must_run("genpkey leaf-key", c);

            let mut c = Command::new("openssl");
            c.args(["req", "-new", "-key"])
                .arg(&key)
                .args(["-subj", &leaf_subject.replace("{name}", name), "-out"])
                .arg(&csr);
            must_run("leaf csr", c);

            let mut c = Command::new("openssl");
            c.args(["x509", "-req", "-in"])
                .arg(&csr)
                .args(["-CA"])
                .arg(&ca_cert)
                .args(["-CAkey"])
                .arg(&ca_key)
                .args(["-CAcreateserial", "-days", "30", "-extfile"])
                .arg(&leaf_ext)
                .args(["-out"])
                .arg(&cert);
            must_run("leaf ca-sign", c);
            Identity { cert, key }
        })
        .collect()
}
