//! The codegen marks of DDS-TS 1.0 Annex B, §B.1.
//!
//! Sixteen of them, B.1.1 through B.1.16, and they are what the
//! IDL-Codegen Profile is measured by. Numbered here as the annex
//! numbers them so that a failure names the mark.
//!
//! Two halves, and both are needed. The text assertions below say that
//! the generator wrote what the clause asks for; [`the_generated_types_
//! type_check`] runs `tsc --strict` over every one of those files beside
//! the real runtime, which is the other half — §2.1 item 4 asks for
//! output that compiles under `--strict` without
//! `experimentalDecorators`, and a descriptor whose `fields` array does
//! not satisfy `DdsMemberDescriptor` is a defect no substring check
//! finds.
//!
//! The runtime is imported by relative path rather than by package name,
//! for the reason `typescript_reader_generates.rs` gives: a package name
//! would need an install step, and this checks the tree as it stands.
// `print_stdout`: a missing compiler has to be said on the harness's own
// channel, never passed over quietly.
#![allow(clippy::expect_used, clippy::panic, clippy::print_stdout)]

use zerodds_ast::Ast;
use zerodds_lang_rules::{ModelGraph, apply};

mod typescript_toolchain;

use typescript_toolchain::compiler_or_note;

/// One IDL source, lowered and resolved.
fn model(source: &str) -> Ast {
    let parsed = zerodds_idl_parse::parse(source);
    assert!(
        parsed.diagnostics().is_empty(),
        "the source does not parse: {:?}",
        parsed.diagnostics()
    );
    let lowered = zerodds_idl_lower::lower(&parsed.syntax(), "test.idl");
    assert!(
        lowered.diagnostics.is_empty(),
        "the source does not lower: {:?}",
        lowered.diagnostics
    );
    let mut ast = lowered.ast;
    ast.resolve_all_by_name().expect("the model resolves");
    ast
}

/// One IDL source as the whole TypeScript file: the runtime import, the
/// prelude, the types, and the descriptor side-tables.
fn generated(source: &str) -> String {
    let ast = model(source);
    let graph = ModelGraph::of(&ast);
    let applied =
        apply(&graph, &zerodds_lang_rules::rule::typescript::catalogue()).expect("the rules apply");
    let mut decls = zerodds_lang_rules::adapter::typescript::prelude();
    decls.extend(
        zerodds_lang_rules::adapter::typescript::ts_items_with_descriptors(&ast, &applied)
            .expect("the model materialises"),
    );
    zerodds_lang_render::typescript::file(&zerodds_lang_cst::typescript::File {
        doc: zerodds_lang_cst::common::Doc::line(
            "Generated by zerodds-lang-rules for DDS-TS 1.0 Annex B. Do not edit.",
        ),
        imports: vec![zerodds_lang_rules::adapter::typescript::descriptor_import(
            "../src/index.js",
        )],
        decls,
    })
}

/// That every one of `wanted` is in the generated source.
fn holds(name: &str, source: &str, wanted: &[&str]) -> String {
    let text = generated(source);
    for expected in wanted {
        assert!(
            text.contains(expected),
            "{name}: `{expected}` is not in the output:\n{text}"
        );
    }
    text
}

/// That none of `forbidden` is in the generated source.
fn absent(name: &str, text: &str, forbidden: &[&str]) {
    for token in forbidden {
        assert!(
            !text.contains(token),
            "{name}: `{token}` reached the output:\n{text}"
        );
    }
}

/// The generated source with its documentation removed.
///
/// B.1.2 forbids the `class` **keyword** in the output for any IDL data
/// type, and a doc comment that explains why there is none is not one.
fn without_comments(text: &str) -> String {
    let mut out = String::new();
    let mut rest = text;
    while let Some(open) = rest.find("/*") {
        out.push_str(&rest[..open]);
        match rest[open..].find("*/") {
            Some(close) => rest = &rest[open + close + 2..],
            None => return out,
        }
    }
    out.push_str(rest);
    out.lines()
        .filter(|line| !line.trim_start().starts_with("//"))
        .collect::<Vec<_>>()
        .join("\n")
}

