/// The other half of B.1.2: no `class` keyword in the generator output
/// for any IDL data type. §7.4 states the same rule — "this PSM does not
/// emit any TypeScript class for IDL data types" — and what produces a
/// value instead is a factory function.
#[test]
fn b_1_2_no_class_reaches_the_output_for_any_idl_data_type() {
    let shapes: &[&str] = &[
        "@final struct P { long x; string s; };",
        "@mutable struct P { @key @id(1) long x; @optional @id(2) long y; };",
        "bitset Packed { bitfield<3> low; bitfield<40> wide; };",
        "enum Colour { RED, GREEN };",
        "@bit_bound(40) bitmask Wide { a, b };",
        "@final union U switch (long) { case 1: long a; default: octet raw; };",
        "exception E { string what; };",
        "typedef sequence<long, 4> Row; @final struct S { Row r; };",
        "@final struct Inner { long v; }; @final struct Outer { Inner one; long grid[2]; };",
        "module m { @final struct Deep { long v; }; };",
        MIXED,
    ];
    for source in shapes {
        let text = generated(source);
        assert!(
            !without_comments(&text).contains("class"),
            "B.1.2: a class reached the output for `{source}`:\n{text}"
        );
        // What replaced it, so the absence is not simply an empty file.
        // Only the property bags had a class: an enumeration is a
        // `number`, a bitmask a `number` or a `bigint`, and a union an
        // object literal its own defaulter writes.
        let bag =
            source.contains("struct") || source.contains("bitset") || source.contains("exception");
        assert!(
            !bag || text.contains("export function new"),
            "B.1.2: nothing produces a value for `{source}`:\n{text}"
        );
    }
}

