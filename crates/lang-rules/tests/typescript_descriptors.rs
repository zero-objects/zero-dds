/// A bitset wider than its anchor is named, not totalled anyway.
///
/// XTypes 1.3 §7.3.1.2.1.11 bounds a bitset by the sixty-four bits of
/// the integer holding it. Nothing between the parser and the descriptor
/// carries that rule — `lower::bitfield` checks each width against
/// sixteen bits and `Ast::add_bitfield` holds no invariant about the sum
/// — so a wider declaration arrives, and both halves of what it produced
/// were wrong: `bitfield<40> a; bitfield<40> b;` stated `bitBound: 80`,
/// a width no anchor holds, and two fields of forty thousand bits each
/// stated `bitBound: 65535`, a number the declaration never wrote and
/// the `u16` counter's saturation point. The codec walks refuse the same
/// declaration by name (`emit::decode`, `zerodds_wire_codec::encode`'s
/// `write_bitset`), so the three failure sets stay comparable.
#[test]
fn b_1_5a_a_bitset_wider_than_its_anchor_is_refused_by_name() {
    // A second case — `bitfield<40000>` twice, for `bitBound: 65535`,
    // the `u16` counter's saturation point — stood here and left: IDL
    // 4.2 §7.4.13.4.3.2 puts a single bitfield's maximum at 64 and the
    // front end reports it, so the declaration no longer lowers and the
    // adapter never sees it. The saturating counter it exercised is out
    // of reach through valid IDL. What remains is the case the rule is
    // about: two bitfields the clause admits one by one, summing past
    // the sixty-four bits of any anchor.
    let source = "bitset Wide { bitfield<40> a; bitfield<40> b; }; @final struct S { Wide w; };";
    let width = "80";
    let ast = model(source);
    let graph = ModelGraph::of(&ast);
    let applied =
        apply(&graph, &zerodds_lang_rules::rule::typescript::catalogue()).expect("the rules apply");
    let error = zerodds_lang_rules::adapter::typescript::ts_items_with_descriptors(&ast, &applied)
        .err()
        .unwrap_or_else(|| panic!("the bitset is refused, not stated: {source}"));
    let said = format!("{error}");
    assert!(
        said.contains(&format!("a bitset of {width} bits")),
        "the refusal names the width it could not hold: {said}"
    );
}

