// -- the compiler --------------------------------------------------------

/// Every shape above, through `tsc --strict`, against the real runtime.
///
/// §2.1 item 4 and §B.1.14. One test and not one per shape, because
/// `tsc` costs seconds and the failure names the file it came from.
/// No `experimentalDecorators` and no `emitDecoratorMetadata`: the flags
/// are not passed, and this PSM emits no decorator for anything.
#[test]
fn the_generated_types_type_check() {
    let shapes: &[(&str, &str)] = &[
        (
            "descriptors-primitives",
            "@final struct P { boolean b; octet o; short s; long l; long long ll; \
             float f; double d; string t; char c; wchar w; long double q; };",
        ),
        (
            "descriptors-annotated",
            "@mutable @topic(\"Pose\") struct Pose { @key @id(1) long x; \
             @optional @id(2) long y; @must_understand @id(3) long z; };",
        ),
        (
            "descriptors-union",
            "enum Tag { TAG_A, TAG_B }; \
             @final union Variant switch (Tag) { case TAG_A: long i; case TAG_B: string s; \
             default: octet raw; };",
        ),
        (
            "descriptors-collections",
            "@final struct S { sequence<long> many; long grid[2][3]; \
             map<long, string> by_id; sequence<string, 4> few; };",
        ),
        (
            "descriptors-nested",
            "@final struct Inner { long v; }; \
             @final struct Outer { Inner one; sequence<Inner> more; };",
        ),
        (
            "descriptors-any",
            "@final struct Envelope { long id; any payload; };",
        ),
        (
            "descriptors-exception",
            "exception NotFound { string what; }; exception Denied { long code; };",
        ),
        ("descriptors-mixed", MIXED),
        (
            "descriptors-typedef",
            "typedef long Counter; @bit_bound(40) typedef long long Counter40; \
             typedef sequence<long, 4> Row; @final struct S { Counter c; Row r; };",
        ),
    ];
    let Some(tsc) = compiler_or_note("the TypeScript column") else {
        // No toolchain here, and said so. The corpus sweep runs the same
        // compiler, and a test that failed for the absence of one would
        // say nothing about the generator.
        return;
    };
    let mut reported: Vec<String> = Vec::new();
    for (name, source) in shapes {
        let text = generated(source);
        let report = typescript_toolchain::typecheck(&tsc, name, &text, &[]);
        if !report.trim().is_empty() {
            reported.push(format!("{name}:\n{report}"));
        }
    }
    assert!(
        reported.is_empty(),
        "the generated descriptors do not typecheck:\n{}",
        reported.join("\n")
    );
}

/// XTypes 1.3 §7.5.1.4.1.3: a derived structure has its base as the first member `parent`, and
/// the descriptor lists it as a member of the base's type that a consumer descends into.
#[test]
fn a_derived_struct_holds_its_base_as_the_member_parent() {
    let text = holds(
        "parent",
        "@final struct Base { long a; };\n\
         @final struct Derived : Base { long b; };",
        &["parent: Base", "base: true", "name: \"parent\""],
    );
    // The members of the base are not repeated in the descriptor of the derived type.
    let derived = text
        .split("export const DerivedType")
        .nth(1)
        .expect("the descriptor of Derived");
    assert!(
        !derived.contains("name: \"a\""),
        "the base member is listed twice:\n{derived}"
    );
}
