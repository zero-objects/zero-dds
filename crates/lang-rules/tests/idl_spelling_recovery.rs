// -- the case ------------------------------------------------------------

fn repository_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("..")
        .join("..")
        .canonicalize()
        .expect("the repository root")
}

fn corpus_case() -> String {
    let path = repository_root()
        .join("tests")
        .join("interop-corpus")
        .join("identifier-target-keywords")
        .join("type.idl");
    std::fs::read_to_string(&path).expect("the corpus case")
}

fn model(source: &str) -> Ast {
    let parsed = zerodds_idl_parse::parse(source);
    assert!(!parsed.has_errors(), "parse: {:?}", parsed.diagnostics());
    let lowered = zerodds_idl_lower::lower(&parsed.syntax(), "type.idl");
    assert!(lowered.diagnostics.is_empty(), "lower");
    let mut ast = lowered.ast;
    let report = ast.resolve_all_by_name().expect("resolve");
    assert!(report.is_clean(), "unresolved: {:?}", report.broken);
    ast
}

/// The corpus case as a C translation unit.
fn c_header() -> String {
    let source = corpus_case();
    let ast = model(&source);
    let graph = ModelGraph::of(&ast);
    let applied = apply(&graph, &rule::c::catalogue()).expect("apply the C catalogue");
    let decls = adapter::c::c_items(&ast, &applied).expect("materialise C");
    zerodds_lang_render::c::file(&c::File {
        doc: Doc::line("Generated by zerodds-lang-rules. Do not edit."),
        guard: Some(Ident::new("ZD_IDENTIFIER_TARGET_KEYWORDS_H")),
        includes: vec![
            c::Include::system("stdbool.h"),
            c::Include::system("stddef.h"),
            c::Include::system("stdint.h"),
        ],
        decls,
    })
}

/// The corpus case as a C++ header.
fn cpp_header() -> String {
    let _native = zerodds_lang_rules::adapter::cpp::CppMappingScope::enter(
        zerodds_lang_rules::adapter::cpp::CppMapping::Native,
    );
    let source = corpus_case();
    let ast = model(&source);
    let graph = ModelGraph::of(&ast);
    let applied = apply(&graph, &rule::cpp::catalogue()).expect("apply the C++ catalogue");
    let decls = adapter::cpp::cpp_items(&ast, &applied).expect("materialise C++");
    zerodds_lang_render::cpp::file(&cpp::File {
        doc: Doc::line("Generated by zerodds-lang-rules. Do not edit."),
        pragma_once: true,
        includes: adapter::cpp::includes(),
        decls,
    })
}

// -- reading the mapping back out of the text ----------------------------

/// The quoted runs of a line, in order.
///
/// No escape handling: an IDL identifier is `[A-Za-z][A-Za-z0-9_]*`
/// (IDL 4.2 §7.2.3), so neither half of an entry can contain a quote or
/// a backslash.
fn quoted(line: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut rest = line;
    while let Some(open) = rest.find('"') {
        let after = &rest[open + 1..];
        let Some(close) = after.find('"') else { break };
        out.push(after[..close].to_string());
        rest = &after[close + 1..];
    }
    out
}

/// The pairs of a line, `(the C or C++ spelling, the IDL spelling)`.
fn pairs(line: &str) -> Vec<(String, String)> {
    let quotes = quoted(line);
    assert_eq!(quotes.len() % 2, 0, "an entry with one half: {line}");
    quotes
        .chunks(2)
        .map(|pair| (pair[0].clone(), pair[1].clone()))
        .collect()
}

/// The member tables of a rendered C file, by the type's C name.
///
/// Reads `#define ZD_IDL_MEMBERS_<type> { { "<c>", "<idl>" }, … }` and
/// nothing else — the shape `adapter::c`'s module documentation states.
fn recover_c(text: &str) -> BTreeMap<String, Vec<(String, String)>> {
    let mut out = BTreeMap::new();
    for line in text.lines() {
        let Some(rest) = line.strip_prefix("#define ZD_IDL_MEMBERS_") else {
            continue;
        };
        let Some((name, body)) = rest.split_once(' ') else {
            continue;
        };
        out.insert(name.to_string(), pairs(body));
    }
    out
}

/// The member tables of a rendered C++ file, by the type's C++ name.
///
/// Reads `inline constexpr std::array<…> <type>_idl_names = {{…}};`.
fn recover_cpp(text: &str) -> BTreeMap<String, Vec<(String, String)>> {
    let mut out = BTreeMap::new();
    for line in text.lines() {
        if !line.starts_with("inline constexpr std::array<") {
            continue;
        }
        let Some((declarator, body)) = line.split_once(" = ") else {
            continue;
        };
        let Some(name) = declarator.rsplit(' ').next() else {
            continue;
        };
        let Some(type_name) = name.strip_suffix("_idl_names") else {
            continue;
        };
        out.insert(type_name.to_string(), pairs(body));
    }
    out
}

/// What the corpus case declares, as the generator is expected to have
/// escaped it. Written out here rather than computed, so a change to
/// the escape shows up as a failure and not as two functions agreeing.
const C_SAMPLE: &[(&str, &str)] = &[
    ("impl", "impl"),
    ("lambda", "lambda"),
    ("static_", "static"),
    ("def", "def"),
    ("async", "async"),
];

/// DDS-RPC 1.0 §7.11.1.1.2 rule 8: a member that is a C++ reserved word
/// is prefixed by `cxx_`.
const CPP_SAMPLE: &[(&str, &str)] = &[
    ("impl", "impl"),
    ("lambda", "lambda"),
    ("cxx_static", "static"),
    ("def", "def"),
    ("async", "async"),
];

const CPP_TYPE: &[(&str, &str)] = &[
    ("cxx_new", "new"),
    ("cxx_delete", "delete"),
    ("cxx_operator", "operator"),
];

fn expected(rows: &[(&str, &str)]) -> Vec<(String, String)> {
    rows.iter()
        .map(|(spelling, idl)| ((*spelling).to_string(), (*idl).to_string()))
        .collect()
}

// -- the mapping is in the text ------------------------------------------

#[test]
fn the_c_column_carries_every_member_of_every_aggregate() {
    let text = c_header();
    let tables = recover_c(&text);

    assert_eq!(
        tables.get("package_Sample"),
        Some(&expected(C_SAMPLE)),
        "{text}"
    );
    // The enumeration's constants carry the module prefix the header
    // gives them, which is the name a caller writes.
    assert_eq!(
        tables.get("package_class"),
        Some(&expected(&[
            ("package_template", "template"),
            ("package_virtual", "virtual"),
            ("package_friend", "friend"),
        ])),
        "{text}"
    );
    // `new`, `delete` and `operator` are C++ keywords and not C ones, so
    // the C column does not move them — and still records them, because
    // a member ID is computed for every member and not only for a moved
    // one.
    assert_eq!(
        tables.get("package_type"),
        Some(&expected(&[
            ("new", "new"),
            ("delete", "delete"),
            ("operator", "operator"),
        ])),
        "{text}"
    );
}

#[test]
fn the_cpp_column_carries_every_member_of_every_aggregate() {
    let text = cpp_header();
    let tables = recover_cpp(&text);

    assert_eq!(tables.get("Sample"), Some(&expected(CPP_SAMPLE)), "{text}");
    assert_eq!(tables.get("type"), Some(&expected(CPP_TYPE)), "{text}");
    assert_eq!(
        tables.get("cxx_class"),
        Some(&expected(&[
            ("cxx_template", "template"),
            ("cxx_virtual", "virtual"),
            ("cxx_friend", "friend"),
        ])),
        "{text}"
    );
}

#[test]
fn a_moved_name_maps_back_to_the_idl_spelling_and_not_to_itself() {
    // The property the whole mechanism exists for. An implementation
    // that wrote the escaped name on both sides of an entry would pass
    // every "the table is there" assertion and answer `cxx_static` where
    // XTypes 1.3 §7.3.1.2.1.1 wants `static` — the member ID would then
    // be the MD5 of a name no peer computes.
    for (column, text, table) in [
        ("C", c_header(), "package_Sample".to_string()),
        ("C++", cpp_header(), "Sample".to_string()),
    ] {
        let tables = if column == "C" {
            recover_c(&text)
        } else {
            recover_cpp(&text)
        };
        let members = tables
            .get(&table)
            .unwrap_or_else(|| panic!("{column}: no table for {table}\n{text}"));
        let moved: Vec<&(String, String)> = members
            .iter()
            .filter(|(spelling, idl)| spelling != idl)
            .collect();
        let moved_to = if column == "C" {
            "static_"
        } else {
            "cxx_static"
        };
        assert_eq!(
            moved,
            vec![&(moved_to.to_string(), "static".to_string())],
            "{column}: the escape did not survive as a mapping\n{text}"
        );
    }
}

#[test]
fn every_declared_field_of_the_aggregate_appears_in_its_table() {
    // The table has to be total over the members the header declares:
    // one that listed some of them would leave a member whose ID cannot
    // be computed, which is the state this closes and not a smaller one.
    let text = c_header();
    let tables = recover_c(&text);
    let members = tables.get("package_Sample").expect("the Sample table");

    let body = text
        .split_once("struct package_Sample {")
        .expect("the Sample declaration")
        .1
        .split_once('}')
        .expect("the end of the declaration")
        .0;
    for line in body.lines().map(str::trim).filter(|line| !line.is_empty()) {
        let field = line
            .trim_end_matches(';')
            .rsplit(' ')
            .next()
            .expect("a declarator")
            // An `@optional` or `@external` member is a pointer: `T *x;`.
            .trim_start_matches('*');
        assert!(
            members.iter().any(|(spelling, _)| spelling == field),
            "the field `{field}` is in no table\n{text}"
        );
    }
}

#[test]
fn a_declarations_own_idl_name_survives_the_escape() {
    // The neighbour of the member case, and a wider one: a type's name
    // reaches the wire as `TypeObject`'s `type_name` and as the topic
    // type name a peer matches on. `class` is a C++ keyword and not a C
    // one, so only the C++ column had to move it.
    let cpp = cpp_header();
    assert!(
        cpp.contains(r#"inline constexpr const char* cxx_class_idl_name = "class";"#),
        "{cpp}"
    );
    let c = c_header();
    assert!(
        c.contains(r#"#define ZD_IDL_NAME_package_class "class""#),
        "{c}"
    );
}

// -- a program reads it back ---------------------------------------------

/// A compiler, or [`None`] and a loud skip.
fn compiler(variable: &str, candidates: &[&str]) -> Option<String> {
    if let Ok(chosen) = std::env::var(variable) {
        return Some(chosen);
    }
    candidates
        .iter()
        .find(|candidate| {
            Command::new(candidate)
                .arg("--version")
                .output()
                .is_ok_and(|out| out.status.success())
        })
        .map(|found| (*found).to_string())
}

fn work_directory(name: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!("zd-idl-spelling-{}-{name}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).expect("the work directory");
    dir
}

/// The C program below reads the mapping out of the generated header and
/// prints it. Nothing else is on the include path.
const C_READER: &str = r#"#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#include <stdio.h>
#include "generated.h"

static const zd_member_name members[] = ZD_IDL_MEMBERS_package_Sample;

int main(void) {
    for (size_t i = 0; i < sizeof members / sizeof members[0]; ++i) {
        printf("%s=%s\n", members[i].field, members[i].idl);
    }
    printf("type=%s\n", ZD_IDL_NAME_package_Sample);
    return 0;
}
"#;

#[test]
fn a_c_program_reads_the_idl_spelling_out_of_the_header_alone() {
    let Some(cc) = compiler("CC", &["cc", "gcc", "clang"]) else {
        eprintln!(
            "skip a_c_program_reads_the_idl_spelling_out_of_the_header_alone: \
             no C compiler on PATH"
        );
        return;
    };
    let dir = work_directory("c");
    std::fs::write(dir.join("generated.h"), c_header()).expect("the header");
    std::fs::write(dir.join("reader.c"), C_READER).expect("the reader");

    // The flag set `tools/wireprobe/wireprobe-zerodds-c` compiles the
    // measured C column with, so a mapping that costs a diagnostic is a
    // failure here rather than in the probe.
    let compiled = Command::new(&cc)
        .args([
            "-std=c99",
            "-Wall",
            "-Wextra",
            "-Wpedantic",
            "-Wconversion",
            "-Wsign-conversion",
            "-Werror",
        ])
        .arg("-o")
        .arg(dir.join("reader"))
        .arg(dir.join("reader.c"))
        .arg(format!("-I{}", dir.display()))
        // The header declares the three maps of every type beside it
        // (XTypes 1.3 §7.5.1.3.2.1) and includes the runtime's `zerodds_map.h` for them.
        .arg(format!(
            "-I{}",
            std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
                .join("../../runtime/c/include")
                .display()
        ))
        .output()
        .expect("invoke the C compiler");
    assert!(
        compiled.status.success(),
        "the reader did not compile: {}",
        String::from_utf8_lossy(&compiled.stderr)
    );

    let run = Command::new(dir.join("reader"))
        .output()
        .expect("run the reader");
    assert!(run.status.success(), "the reader did not run");
    let printed = String::from_utf8_lossy(&run.stdout);
    assert!(
        printed.contains("static_=static"),
        "the C spelling did not map back: {printed}"
    );
    assert!(
        printed.contains("type=Sample"),
        "the declaration's own name did not map back: {printed}"
    );
    assert_eq!(
        printed.lines().count(),
        C_SAMPLE.len() + 1,
        "the reader saw a different number of members: {printed}"
    );
}

/// The C++ program below resolves the mapping twice: once in a
/// `constexpr` function the compiler evaluates, and once at run time.
const CPP_READER: &str = r#"#include <cstdio>
#include <string_view>
#include "generated.hpp"

constexpr const char *idl_name_of(std::string_view spelling) {
    for (const auto &entry : package::Sample_idl_names) {
        if (spelling == entry.first) {
            return entry.second;
        }
    }
    return nullptr;
}

static_assert(package::Sample_idl_names.size() == 5,
              "the table does not cover the members");
static_assert(std::string_view{idl_name_of("cxx_static")} == "static",
              "the IDL spelling is not recoverable at compile time");

int main() {
    for (const auto &entry : package::Sample_idl_names) {
        std::printf("%s=%s\n", entry.first, entry.second);
    }
    std::printf("type=%s\n", package::cxx_class_idl_name);
    return 0;
}
"#;

#[test]
fn a_cpp_program_reads_the_idl_spelling_out_of_the_header_alone() {
    let Some(cxx) = compiler("CXX", &["c++", "g++", "clang++"]) else {
        eprintln!(
            "skip a_cpp_program_reads_the_idl_spelling_out_of_the_header_alone: \
             no C++ compiler on PATH"
        );
        return;
    };
    let dir = work_directory("cpp");
    std::fs::write(dir.join("generated.hpp"), cpp_header()).expect("the header");
    std::fs::write(dir.join("reader.cpp"), CPP_READER).expect("the reader");
    let runtime = repository_root()
        .join("runtime")
        .join("cpp")
        .join("include");

    // The flag set `tools/wireprobe/wireprobe-zerodds-cpp` compiles the
    // measured C++ column with.
    let compiled = Command::new(&cxx)
        .args(["-std=c++20", "-Wall", "-Wextra", "-Werror"])
        .arg("-o")
        .arg(dir.join("reader"))
        .arg(dir.join("reader.cpp"))
        .arg(format!("-I{}", dir.display()))
        .arg(format!("-I{}", runtime.display()))
        .output()
        .expect("invoke the C++ compiler");
    assert!(
        compiled.status.success(),
        "the reader did not compile: {}",
        String::from_utf8_lossy(&compiled.stderr)
    );

    let run = Command::new(dir.join("reader"))
        .output()
        .expect("run the reader");
    assert!(run.status.success(), "the reader did not run");
    let printed = String::from_utf8_lossy(&run.stdout);
    assert!(
        printed.contains("cxx_static=static"),
        "the C++ spelling did not map back: {printed}"
    );
    assert!(
        printed.contains("type=class"),
        "the declaration's own name did not map back: {printed}"
    );
    assert_eq!(
        printed.lines().count(),
        CPP_SAMPLE.len() + 1,
        "the reader saw a different number of members: {printed}"
    );
}
