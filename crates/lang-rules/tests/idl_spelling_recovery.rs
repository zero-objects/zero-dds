//! The IDL spelling of a member, read back out of the generated C and
//! C++.
//!
//! `docs/structural-reviews/2026-08-16-first-pass.md` finding 3: the C#
//! column carries `[IdlName("a")]`, Python carries the name in
//! `dataclasses.field(metadata=…)`, TypeScript keeps the IDL spelling
//! outright — and the C and C++ columns escaped a colliding identifier
//! and recorded nothing. XTypes 1.3 §7.3.1.2.1.1 computes a member's ID
//! under `@autoid(HASH)` and under `@hashid` from the first four octets
//! of the MD5 of the **IDL** name, so a column that cannot recover
//! `static` from `cxx_static` cannot compute the ID of that member.
//!
//! What is asserted here is recovery and not presence. A test that
//! looked for a comment would pass on a column that carried the spelling
//! nowhere a program could reach, which is the state this closes. So:
//!
//! - `recover_c` and `recover_cpp` read the mapping out of the rendered
//!   text knowing only the shape the module documentation of
//!   `adapter::c` and `adapter::cpp` states — no generator function is
//!   called to interpret the generator's own output;
//! - `a_c_program_reads_the_idl_spelling_out_of_the_header_alone` and
//!   its C++ counterpart hand the generated file to a compiler with
//!   nothing else and make a program print the mapping, which is the
//!   claim in its strongest form. The C++ one also resolves the mapping
//!   in a `constexpr` function, so the recovery is checked by the
//!   compiler and not only by the run.
//!
//! `tests/interop-corpus/identifier-target-keywords` is the case: every
//! identifier in it is legal IDL and reserved in at least one target.
#![allow(
    clippy::expect_used,
    clippy::panic,
    clippy::print_stderr,
    clippy::unwrap_used,
    missing_docs
)]

