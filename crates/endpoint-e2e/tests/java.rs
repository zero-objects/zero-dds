//! Java endpoint ping-pong: the generated codec marshals the `Ping` and decodes
//! the `Pong`, the endpoint SDK (`ZdwEndpoint`) does the XRCE `WRITE_DATA`
//! framing, and a real `java.net.DatagramSocket` carries the bytes to the Rust
//! peer. `sync` = the caller owns the receive loop; `async` = a reader thread
//! drains the socket into a `LinkedBlockingQueue` the consumer blocks on (the
//! idiomatic `java.util.concurrent` model). Gated on `javac`.
//!
//! Generated code is compiled against the **real** Java wire runtime,
//! `runtime/java` (`org.zerodds.wire.*`), never stubs. The former
//! `crates/java-omgdds` + `crates/idl-java/runtime` classpath went with the
//! IDL transplant, along with the `idl-java` generator that emitted against it.
//!
//! `java_endpoint_golden` is the third case: it runs
//! `endpoints/java/EndpointTest.java` against goldens generated by
//! `zerodds-endpoint-golden`, which is what puts that file under `cargo test`
//! instead of leaving it a manual run.

#![allow(clippy::expect_used, clippy::panic, clippy::print_stderr)]

use std::path::{Path, PathBuf};
use std::process::{Child, Command, Stdio};
use std::sync::OnceLock;

use zerodds_endpoint_e2e::codegen::{
    Language, endpoints_dir, runtime_dir, scratch_dir, source, tool_available,
};
use zerodds_endpoint_e2e::{Peer, bind_peer, ping_pong};

const CP_SEP: &str = if cfg!(windows) { ";" } else { ":" };

fn javac_available() -> bool {
    tool_available("javac", "-version")
}

/// Recursively collects every `.java` file under `dir`.
fn collect_java(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect_java(&path, out);
        } else if path.extension().is_some_and(|e| e == "java") {
            out.push(path);
        }
    }
}

/// Compiles `runtime/java`'s main sources once into a classes dir; returns its
/// path. `None` when `javac` is unavailable or the runtime fails to compile.
///
/// `src/main/java` only: `src/test/java` holds the runtime's own self-tests,
/// which are not what an app links.
fn runtime_classes() -> Option<&'static Path> {
    static CELL: OnceLock<Option<PathBuf>> = OnceLock::new();
    CELL.get_or_init(|| {
        if !javac_available() {
            return None;
        }
        let out = scratch_dir("java_rt");
        let mut srcs = Vec::new();
        // `org/zerodds/wire` and not all of `src/main/java`: the tree also
        // carries `org/omg/dds/rpc`, whose imports of `org.omg.dds.core`
        // live in `crates/java-omgdds/java`. Compiling everything pulled
        // those in, failed, and the failure used to return `None` — which
        // reads as "no toolchain" and turned every test in this file green
        // without running one of them. `wireprobe-zerodds-java` narrows the
        // same way for the same reason.
        collect_java(
            &runtime_dir("java").join("src/main/java/org/zerodds/wire"),
            &mut srcs,
        );
        assert!(
            !srcs.is_empty(),
            "no runtime sources under runtime/java/src/main/java/org/zerodds/wire — \
             the runtime this file measures is not there"
        );
        let output = Command::new("javac")
            .arg("-encoding")
            .arg("UTF-8")
            .arg("-nowarn")
            .arg("-d")
            .arg(&out)
            .args(&srcs)
            .output()
            .expect("javac reported available, then would not run");
        // A missing toolchain skips, above. A toolchain that will not
        // compile our own runtime is a failure and says so: anything else
        // reports a green test over code no compiler read.
        assert!(
            output.status.success(),
            "javac is present and runtime/java does not compile:\n{}",
            String::from_utf8_lossy(&output.stderr)
        );
        Some(out)
    })
    .as_deref()
}

/// Splits the generated Java into `(ZdTypes.java, the codec's members)`.
///
/// The generator emits two public top-level classes, `ZdTypes` and `ZdCodec`,
/// and Java allows one public class per file. `ZdTypes` becomes its own file;
/// `ZdCodec`'s members are inlined into `Main` — its methods are
/// `private static`, so a caller outside the class could not reach them. This
/// is what `wireprobe-zerodds-java-gen` does with the same text, for the same
/// reason.
fn split_generated() -> (String, String) {
    let text = source(Language::Java);
    let at = text
        .find("public class ZdCodec {")
        .expect("generated Java declares `public class ZdCodec`");
    let types = text[..at].trim_end().to_string();
    let body = &text[at..];
    let open = body.find('\n').expect("class opens a line");
    let members = body[open + 1..]
        .trim_end()
        .strip_suffix('}')
        .expect("class closes with `}`")
        .to_string();
    (types, members)
}

/// The app driver, wrapped around the inlined codec members.
const MAIN_JAVA_HEAD: &str = r#"
import java.net.DatagramPacket;
import java.net.DatagramSocket;
import java.net.InetAddress;
import java.util.Arrays;
import java.util.concurrent.LinkedBlockingQueue;

import org.zerodds.wire.Endianness;
import org.zerodds.wire.PlCdr1Framing;
import org.zerodds.wire.Reader;
import org.zerodds.wire.TryConstruct;
import org.zerodds.wire.Writer;

public final class Main {
"#;

const MAIN_JAVA_TAIL: &str = r#"
    public static void main(String[] args) throws Exception {
        String mode = args[0];
        int port = Integer.parseInt(args[1]);
        InetAddress host = InetAddress.getByName("127.0.0.1");
        DatagramSocket sock = new DatagramSocket();
        sock.setSoTimeout(60000);

        // Marshal the Ping with the generated codec (XCDR2 little-endian:
        // MAXALIGN four), frame it with the endpoint SDK, send it over UDP.
        ZdTypes.Ping ping = new ZdTypes.Ping();
        ping.seq = 1;
        ping.msg = "hello from app";
        Writer w = new Writer(Endianness.LITTLE, 4, PlCdr1Framing.defaults(), false);
        zd_enc_Ping(w, ping);
        byte[] sample = w.finish();

        byte[] frame = ZdwEndpoint.xrceWriteFrame(
            ZdwEndpoint.SESSION_NOKEY, ZdwEndpoint.STREAM_BEST_EFFORT, 1,
            ZdwEndpoint.objectId(0x001, ZdwEndpoint.OBJK_DATAWRITER), sample);
        sock.send(new DatagramPacket(frame, frame.length, host, port));

        byte[] body;
        if (mode.equals("async")) {
            // Async: a reader thread drains the socket; the consumer blocks on take().
            final LinkedBlockingQueue<byte[]> inbox = new LinkedBlockingQueue<byte[]>();
            final DatagramSocket rsock = sock;
            Thread reader = new Thread(new Runnable() {
                @Override
                public void run() {
                    try {
                        byte[] buf = new byte[4096];
                        DatagramPacket pkt = new DatagramPacket(buf, buf.length);
                        rsock.receive(pkt);
                        byte[] f = Arrays.copyOf(pkt.getData(), pkt.getLength());
                        inbox.add(ZdwEndpoint.xrceReadBody(f));
                    } catch (Exception e) {
                        // Leave the inbox empty; the consumer's take() would then block
                        // and the test's process timeout catches the failure.
                    }
                }
            });
            reader.setDaemon(true);
            reader.start();
            body = inbox.take();
        } else {
            // Sync: the caller owns the run-loop and blocks on receive().
            byte[] buf = new byte[4096];
            DatagramPacket pkt = new DatagramPacket(buf, buf.length);
            sock.receive(pkt);
            byte[] f = Arrays.copyOf(pkt.getData(), pkt.getLength());
            body = ZdwEndpoint.xrceReadBody(f);
        }

        Reader r = new Reader(body, Endianness.LITTLE, 4, PlCdr1Framing.defaults());
        ZdTypes.Pong pong = zd_dec_Pong(r, TryConstruct.DISCARD);
        System.out.println("PONG seq=" + pong.seq + " reply=" + pong.reply);
        sock.close();
    }
}
"#;

/// Generates + compiles the Java app for `mode`, then spawns it pointed at
/// `port`. `None` if the runtime is unavailable (skip).
fn build_java(mode: &str, port: u16) -> Option<Child> {
    let classes = runtime_classes()?;
    let (types, members) = split_generated();

    let src_dir = scratch_dir(&format!("java_{mode}"));
    let out_dir = src_dir.join("out");
    std::fs::create_dir_all(&out_dir).expect("mkdir out");

    let mut paths = Vec::new();
    let types_path = src_dir.join("ZdTypes.java");
    std::fs::write(&types_path, format!("{types}\n")).expect("write ZdTypes.java");
    paths.push(types_path);

    // The endpoint SDK (XRCE framing) + the app driver, both default-package.
    let ep_dst = src_dir.join("ZdwEndpoint.java");
    std::fs::copy(endpoints_dir("java").join("ZdwEndpoint.java"), &ep_dst)
        .expect("copy ZdwEndpoint.java");
    paths.push(ep_dst);

    let main_path = src_dir.join("Main.java");
    std::fs::write(
        &main_path,
        format!("{MAIN_JAVA_HEAD}{members}\n{MAIN_JAVA_TAIL}"),
    )
    .expect("write Main.java");
    paths.push(main_path);

    let javac = Command::new("javac")
        .arg("-encoding")
        .arg("UTF-8")
        .arg("-nowarn")
        .arg("-classpath")
        .arg(classes)
        .arg("-d")
        .arg(&out_dir)
        .args(&paths)
        .output()
        .expect("javac");
    assert!(
        javac.status.success(),
        "javac failed:\n{}",
        String::from_utf8_lossy(&javac.stderr)
    );

    let cp = format!("{}{CP_SEP}{}", classes.display(), out_dir.display());
    let child = Command::new("java")
        .arg("-cp")
        .arg(cp)
        .arg("Main")
        .arg(mode)
        .arg(port.to_string())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .expect("spawn java");
    Some(child)
}

fn endpoint_case(mode: &str) {
    if !javac_available() {
        eprintln!("SKIP java endpoint {mode}: `javac` not on PATH");
        return;
    }
    let peer: Peer = bind_peer().expect("bind peer");
    let Some(child) = build_java(mode, peer.port) else {
        eprintln!("SKIP java endpoint {mode}: runtime unavailable");
        return;
    };
    ping_pong(&peer, child, &format!("java/{mode}"));
}

#[test]
fn java_endpoint_sync() {
    endpoint_case("sync");
}

#[test]
fn java_endpoint_async() {
    endpoint_case("async");
}

/// `endpoints/java/EndpointTest.java` under `cargo test`: the Java XRCE and
/// serial framing against the byte goldens the Rust core writes.
///
/// This is the Java counterpart to `endpoints/c/Makefile`'s
/// `make test GOLDEN_DIR=…`. `EndpointTest` needs five golden files and, unlike
/// `ReliableSelfTest`, carries no hardcoded fallback — so the goldens are
/// generated first and a failure to generate them fails the test rather than
/// quietly skipping the comparison.
#[test]
fn java_endpoint_golden() {
    if !javac_available() {
        eprintln!("SKIP java_endpoint_golden: `javac` not on PATH");
        return;
    }
    let dir = scratch_dir("java_golden");
    let gold = dir.join("gold");
    std::fs::create_dir_all(&gold).expect("mkdir gold");

    let golden = Command::new(env!("CARGO"))
        .args(["run", "-q", "-p", "zerodds-endpoint-golden", "--"])
        .arg(&gold)
        .current_dir(zerodds_endpoint_e2e::codegen::workspace_root())
        .output()
        .expect("spawn zerodds-endpoint-golden");
    assert!(
        golden.status.success(),
        "zerodds-endpoint-golden failed:\n{}",
        String::from_utf8_lossy(&golden.stderr)
    );
    for name in [
        "golden_xrce_le.bin",
        "golden_serial_le.bin",
        "golden_data_le.bin",
        "golden_heartbeat_le.bin",
        "golden_acknack_le.bin",
    ] {
        assert!(gold.join(name).exists(), "golden {name} was not written");
    }

    // `EndpointTest` needs `Zdw` (the wire-core it builds the sample with) and
    // `ZdwEndpoint` (the framing under test), both from `endpoints/java`.
    let java = endpoints_dir("java");
    let out = dir.join("out");
    std::fs::create_dir_all(&out).expect("mkdir out");
    let javac = Command::new("javac")
        .arg("-encoding")
        .arg("UTF-8")
        .arg("-nowarn")
        .arg("-d")
        .arg(&out)
        .arg(java.join("EndpointTest.java"))
        .arg(java.join("Zdw.java"))
        .arg(java.join("ZdwEndpoint.java"))
        .output()
        .expect("javac EndpointTest");
    assert!(
        javac.status.success(),
        "javac EndpointTest failed:\n{}",
        String::from_utf8_lossy(&javac.stderr)
    );

    let run = Command::new("java")
        .arg("-cp")
        .arg(&out)
        .arg("EndpointTest")
        .arg(&gold)
        .output()
        .expect("run EndpointTest");
    let stdout = String::from_utf8_lossy(&run.stdout);
    assert!(
        run.status.success() && stdout.contains("ALL OK"),
        "EndpointTest failed:\nstdout: {stdout}\nstderr: {}",
        String::from_utf8_lossy(&run.stderr)
    );
}
