//! The DDS-DLRL extended ports and connectors (DDS4CCM 1.1 §8) over the
//! DLRL entities of `zerodds-dlrl` (`zerodds_dlrl::cache`).
//!
//! # Ports (§8.2)
//!
//! "Due to its essential variable composition, it is not possible to
//! define one normative DLRL extended port. In return, the definition of
//! their basic ports as well as the extended port composition rule are
//! normative."
//!
//! - [`CacheOperation`] is the interface of the receptacle that uses the
//!   Cache (§8.2.1.1): the operative part of `DDS::Cache`, with the
//!   signatures of [`Cache`].
//! - A home receptacle (§8.2.1.2) stands for "a receptacle of type the
//!   related home inheriting from DDS::ObjectHome", generated by the DLRL
//!   tooling. There is no generated home type in Rust (`zerodds-dlrl`
//!   generates the object model and its mapping, `zerodds-dlrl-codegen`
//!   writes classes for C++, Java, C#, TypeScript and IDL): the receptacle
//!   is the generic [`ObjectHome`] of its class, declared by the name of
//!   the class and looked up by the name of the receptacle
//!   ([`DlrlPort::home`]).
//! - A [`DlrlPortType`] is a `porttype` of the composition rule (§8.2.2):
//!   one `CacheOperation` receptacle and one home receptacle per class the
//!   component uses, over one object model.
//! - A [`DlrlPort`] is such a port of a component, its receptacles
//!   connected to the Cache and the homes of its connector fragment.
//!
//! # Connectors (§8.3)
//!
//! A [`DlrlConnector`] is a `DDS_Base` (`error_listener`, `domain_id`,
//! `qos_profile`) with "as many mirror ports as there exist DLRL extended
//! ports to share the related set of topics". The mirror ports are
//! declared when the connector is made; the attributes are set and
//! `configuration_complete` reads the QoS profile, as for the DCPS
//! connectors. [`DlrlConnector::connect`] connects a port of a component
//! to a mirror port: the fragment does what §8.2.2 says it does "under
//! the scene".
//!
//! 1. "Create the cache according to the specified
//!    CacheOperation::cache_usage." `cache_usage` is a readonly attribute
//!    of the interface the component uses; the fragment is given it, as
//!    the `observable` mirror port of `DDS_State` is given the readonly
//!    attribute `is_global_scope` of its `Updater`.
//! 2. "Instantiate and register the specified ObjectHome": one home per
//!    home receptacle, registered with the Cache in the order of the
//!    receptacles. `register_all_for_pubsub` creates "the DCPS entities
//!    according to the DLRL DCPS mapping".
//! 3. "Apply the QoS profile to modify underlying DCPS entities (if
//!    specified in the connector)": the `topic_qos` of each topic before
//!    `register_all_for_pubsub`, as the QoS of a Topic the Cache creates
//!    (`Cache::set_new_topic_qos`), since a Topic is enabled when it is
//!    created. A topic the DomainParticipant has already when the Cache
//!    creates its topics (of another port, also one connected at the same
//!    time, or of the application) keeps its QoS and serves the port when
//!    every policy the `topic_qos` of the profile sets has that value
//!    there, as for a DCPS connector; otherwise the port is refused with
//!    [`ConnectorError::TopicQos`]. The `publisher_qos`, `subscriber_qos`,
//!    `datawriter_qos` and
//!    `datareader_qos` after it, on the entities that are not yet enabled.
//!    A policy the profile does not set keeps the value the Cache gave it
//!    (the DataReaders of a Cache are RELIABLE). `topic_filter` selects
//!    the containers of a topic, by its name in the mapping, as for a DCPS
//!    connector (§7.4.3, §8.4.2): the `topic_qos`, `datawriter_qos` and
//!    `datareader_qos` of each topic. The DomainParticipant, the Publisher
//!    and the Subscriber of the port serve all its topics: each takes the
//!    container of its kind that is selected for every topic of the port
//!    (a container without `topic_filter`, or one whose filter matches
//!    all of them), none when none is selected for any topic. Topics that
//!    select different containers of one kind refuse the port with
//!    [`ConnectorError::TopicFilter`]; the profile does not say which of
//!    them the one entity takes. A container whose filter matches no
//!    topic of the port does not apply to it.
//! 4. "Enable the infrastructure so that DLRL objects can be created and
//!    used the DLRL way": `enable_all_for_pubsub`.
//!
//! # DCPS entities (§8.4.1)
//!
//! "As a DLRL port corresponds to one Cache, it must be given its own
//! Publisher and/or Subscriber (depending on the cache usage). In
//! addition, it will get as many DataReaders and/or DataWriters as there
//! are topics used by the DLRL objects." The Cache creates them: a
//! Publisher with usage `WRITE_ONLY` or `READ_WRITE`, a Subscriber with
//! `READ_ONLY` or `READ_WRITE`, and per topic of the classes of the port a
//! DataWriter in the one and a DataReader in the other. The
//! DomainParticipant is allocated as for a DCPS port (§7.4.1, §7.4.3,
//! [`crate::entities`]): the container's default, else the component's,
//! if it has what the `domainparticipant_qos` of the connector's profile
//! sets, else one dedicated to the port. The default Publishers and
//! Subscribers of container and component serve no DLRL port.
//!
//! # Statuses
//!
//! `error_listener` gets the statuses of the DCPS entities of the ports as
//! for a DCPS connector ([`crate::status`]): INCONSISTENT_TOPIC of the
//! topics, the statuses of the DataWriters, and those of the DataReaders
//! but `DATA_AVAILABLE`, which the Cache takes; a DLRL port has no
//! `PortStatusListener`, so `REQUESTED_DEADLINE_MISSED` and `SAMPLE_LOST`
//! are reported with `on_unexpected_status`.

