/// Local interface `CacheOperation` of module `CCM_DDS` (§8.2.1.1,
/// Annex B): the type of the receptacle "dedicated to using the Cache once
/// initialized by the infrastructure", "only the operative subset of the
/// DDS::Cache functions and attributes".
///
/// "All the retained functions mimic exactly the DDS::Cache ones, and
/// therefore request the same parameters and return the same result.
/// Similarly, all the retained attributes are identical to the DDS::Cache
/// ones." Each method has the signature of the method of [`Cache`] of the
/// same name, and [`Cache`] implements the interface by them. The
/// exceptions of DDS-DLRL are the variants of [`DlrlException`]:
/// `refresh` raises `DCPSError`, `create_access` and `delete_access`
/// raise `PreconditionNotMet`; `AlreadyDeleted` is in no `raises` clause
/// and comes from every operation once the Cache is deleted (DDS 1.2
/// §8.2.1.1), as after the removal of the connector.
///
/// The IDL is `idl/ccm_dds_dlrl.idl` (Annex B). It maps to Rust as
/// follows: an attribute is a getter of its value; an operation is a
/// method with the parameters of the IDL, in their order, that returns
/// `Result` with [`DlrlException`], since `AlreadyDeleted` may come from
/// every operation. A sequence is a `Vec`; an `in` `DDS::CacheUsage` is
/// passed by value, an `in` `DDS::CacheAccess` is borrowed; a
/// `DDS::CacheListener` is an `Arc<dyn CacheListener>`, which
/// `attach_listener` keeps and `detach_listener` borrows (it finds the
/// listener by identity, `Arc::ptr_eq`).
///
/// ```text
/// local interface CacheOperation {
///     readonly attribute DDS::CacheUsage      cache_usage;
///     readonly attribute DDS::ObjectRootSeq   objects;
///     readonly attribute boolean              updates_enabled;
///     readonly attribute DDS::ObjectHomeSeq   homes;
///     readonly attribute DDS::CacheAccessSeq  sub_accesses;
///     readonly attribute DDS::CacheListenerSeq listeners;
///     void refresh() raises (DDS::DCPSError);
///     void attach_listener(in DDS::CacheListener listener);
///     void detach_listener(in DDS::CacheListener listener);
///     void enable_updates();
///     void disable_updates();
///     DDS::CacheAccess create_access(in DDS::CacheUsage purpose)
///         raises (DDS::PreconditionNotMet);
///     void delete_access(in DDS::CacheAccess access)
///         raises (DDS::PreconditionNotMet);
/// };
/// ```
pub trait CacheOperation: Send + Sync {
    /// `readonly attribute DDS::CacheUsage cache_usage`.
    fn cache_usage(&self) -> CacheUsage;

    /// `readonly attribute DDS::ObjectRootSeq objects`.
    fn objects(&self) -> Vec<ObjectRoot>;

    /// `readonly attribute boolean updates_enabled`.
    fn updates_enabled(&self) -> bool;

    /// `readonly attribute DDS::ObjectHomeSeq homes`.
    fn homes(&self) -> Vec<ObjectHome>;

    /// `readonly attribute DDS::CacheAccessSeq sub_accesses`.
    fn sub_accesses(&self) -> Vec<CacheAccess>;

    /// `readonly attribute DDS::CacheListenerSeq listeners`.
    fn listeners(&self) -> Vec<Arc<dyn CacheListener>>;

    /// `void refresh() raises (DDS::DCPSError)`.
    ///
    /// # Errors
    /// As [`Cache::refresh`].
    fn refresh(&self) -> Result<(), DlrlException>;

    /// `void attach_listener(in DDS::CacheListener listener)`.
    ///
    /// # Errors
    /// As [`Cache::attach_listener`].
    fn attach_listener(&self, listener: Arc<dyn CacheListener>) -> Result<(), DlrlException>;

    /// `void detach_listener(in DDS::CacheListener listener)`.
    ///
    /// # Errors
    /// As [`Cache::detach_listener`].
    fn detach_listener(&self, listener: &Arc<dyn CacheListener>) -> Result<(), DlrlException>;

    /// `void enable_updates()`.
    ///
    /// # Errors
    /// As [`Cache::enable_updates`].
    fn enable_updates(&self) -> Result<(), DlrlException>;

    /// `void disable_updates()`.
    ///
    /// # Errors
    /// As [`Cache::disable_updates`].
    fn disable_updates(&self) -> Result<(), DlrlException>;

    /// `DDS::CacheAccess create_access(in DDS::CacheUsage purpose) raises
    /// (DDS::PreconditionNotMet)`.
    ///
    /// # Errors
    /// As [`Cache::create_access`].
    fn create_access(&self, purpose: CacheUsage) -> Result<CacheAccess, DlrlException>;

    /// `void delete_access(in DDS::CacheAccess access) raises
    /// (DDS::PreconditionNotMet)`.
    ///
    /// # Errors
    /// As [`Cache::delete_access`].
    fn delete_access(&self, access: &CacheAccess) -> Result<(), DlrlException>;
}

