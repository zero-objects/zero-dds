/// Why a DLRL port type or a DLRL connector was not declared (§8.2.2,
/// §8.3).
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum DeclarationError {
    /// A name is not an IDL identifier (IDL 4.2 §7.2.3: a letter, then
    /// letters, digits and underscores), or it collides with an IDL
    /// keyword, also when it differs from it only in case (§7.2.4).
    Name(String),
    /// Two receptacles of a port type, or two mirror ports of a
    /// connector, have one name. IDL identifiers that differ only in case
    /// collide (IDL 4.2 §7.2.3).
    DuplicateName(String),
    /// The port type has no home receptacle: its Cache would have no home
    /// to register and no DCPS entity.
    NoHome,
    /// Two home receptacles of a port type have the home of one class: a
    /// Cache registers one home per class.
    DuplicateClass(String),
    /// The object model of the port type has no class of that name.
    UnknownClass(String),
    /// The connector has no mirror port.
    NoMirrorPort,
}

impl std::fmt::Display for DeclarationError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Name(name) => write!(f, "`{name}` is not an IDL identifier"),
            Self::DuplicateName(name) => write!(f, "the name `{name}` is declared twice"),
            Self::NoHome => f.write_str("the port type has no home receptacle"),
            Self::DuplicateClass(class) => {
                write!(f, "two home receptacles have the home of class `{class}`")
            }
            Self::UnknownClass(class) => write!(f, "the object model has no class `{class}`"),
            Self::NoMirrorPort => f.write_str("the connector has no mirror port"),
        }
    }
}

impl std::error::Error for DeclarationError {}

/// Checks that `name` is an IDL identifier: a letter, then letters, digits
/// and underscores (IDL 4.2 §7.2.3), that does not collide with a keyword
/// of Table 7-6. "Identifiers that collide with keywords (see 7.2.3,
/// Identifiers) are illegal" (§7.2.4), and identifiers collide when they
/// differ only in case (§7.2.3): `home`, `Uses` and `PORTTYPE` are not
/// names.
fn identifier(name: &str) -> Result<(), DeclarationError> {
    let mut chars = name.chars();
    let starts = chars.next().is_some_and(|c| c.is_ascii_alphabetic());
    let spelled = starts && chars.all(|c| c.is_ascii_alphanumeric() || c == '_');
    let keyword = KEYWORDS
        .iter()
        .any(|(keyword, _)| keyword.eq_ignore_ascii_case(name));
    if spelled && !keyword {
        Ok(())
    } else {
        Err(DeclarationError::Name(name.to_owned()))
    }
}

/// Checks that `names` are identifiers, distinct also in case.
fn distinct<'a>(names: impl IntoIterator<Item = &'a str>) -> Result<(), DeclarationError> {
    let mut seen: Vec<String> = Vec::new();
    for name in names {
        identifier(name)?;
        let folded = name.to_ascii_lowercase();
        if seen.contains(&folded) {
            return Err(DeclarationError::DuplicateName(name.to_owned()));
        }
        seen.push(folded);
    }
    Ok(())
}

/// A home receptacle of a DLRL port type (§8.2.1.2), for `uses FooHome
/// foo_home`, "a receptacle of type the related home inheriting from
/// DDS::ObjectHome": the class names the home; the receptacle is the
/// generic [`ObjectHome`] of that class, since Rust has no generated
/// `FooHome` (see the module documentation).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HomeReceptacle {
    /// The name of the receptacle.
    pub name: String,
    /// The class whose home types the receptacle.
    pub class: String,
}

/// A DLRL extended port type (§8.2.2), as an application declares it:
///
/// ```text
/// porttype MyDlrlPort_1 {
///     uses CCM_DDS::CacheOperation cache;
///     uses FooHome                 foo_home;
///     uses BarHome                 bar_home;
/// };
/// ```
///
/// "A CacheOperation receptacle" and "As many DDS:ObjectHome-derived
/// receptacles as DLRL object types that will be used by the component
/// using that DLRL port", over one object model with its mapping (a DLRL
/// object model "is specific to one participant").
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DlrlPortType {
    name: String,
    mapping: Arc<Mapping>,
    cache: String,
    homes: Vec<HomeReceptacle>,
}

impl DlrlPortType {
    /// The port type `name` over the object model of `mapping`, with the
    /// `CacheOperation` receptacle `cache` and a home receptacle per
    /// `(name, class)` of `homes`, in that order.
    ///
    /// # Errors
    /// [`DeclarationError`]: a name that is not an identifier, two
    /// receptacles of one name, no home receptacle, two of one class, a
    /// class the object model does not have.
    pub fn new(
        name: &str,
        mapping: Arc<Mapping>,
        cache: &str,
        homes: &[(&str, &str)],
    ) -> Result<Self, DeclarationError> {
        identifier(name)?;
        distinct(std::iter::once(cache).chain(homes.iter().map(|(receptacle, _)| *receptacle)))?;
        if homes.is_empty() {
            return Err(DeclarationError::NoHome);
        }
        let mut receptacles: Vec<HomeReceptacle> = Vec::with_capacity(homes.len());
        for (receptacle, class) in homes {
            if mapping.class(class).is_none() {
                return Err(DeclarationError::UnknownClass((*class).to_owned()));
            }
            if receptacles.iter().any(|r| r.class == *class) {
                return Err(DeclarationError::DuplicateClass((*class).to_owned()));
            }
            receptacles.push(HomeReceptacle {
                name: (*receptacle).to_owned(),
                class: (*class).to_owned(),
            });
        }
        Ok(Self {
            name: name.to_owned(),
            mapping,
            cache: cache.to_owned(),
            homes: receptacles,
        })
    }

    /// The name of the port type.
    #[must_use]
    pub fn name(&self) -> &str {
        &self.name
    }

    /// The object model and its mapping.
    #[must_use]
    pub fn mapping(&self) -> &Arc<Mapping> {
        &self.mapping
    }

    /// The name of the `CacheOperation` receptacle.
    #[must_use]
    pub fn cache_receptacle(&self) -> &str {
        &self.cache
    }

    /// The home receptacles, in the order of the declaration.
    #[must_use]
    pub fn homes(&self) -> &[HomeReceptacle] {
        &self.homes
    }

    /// The topics in which the classes of the home receptacles have rows,
    /// each once, in the order of the receptacles.
    #[must_use]
    pub fn topic_names(&self) -> Vec<String> {
        let mut names: Vec<String> = Vec::new();
        for receptacle in &self.homes {
            for topic in self.mapping.topics_of_class(&receptacle.class) {
                if !names.contains(&topic) {
                    names.push(topic);
                }
            }
        }
        names
    }
}

/// A DLRL extended port of a component (§8.2.2), connected to a mirror
/// port of a [`DlrlConnector`]: its `CacheOperation` receptacle is
/// connected to the Cache of the connector fragment, each home receptacle
/// to the home of its class registered with that Cache.
pub struct DlrlPort {
    port_type: DlrlPortType,
    mirror_port: String,
    cache: Cache,
    operation: Arc<dyn CacheOperation>,
    homes: Vec<ObjectHome>,
}

impl std::fmt::Debug for DlrlPort {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("DlrlPort")
            .field("port_type", &self.port_type.name)
            .field("mirror_port", &self.mirror_port)
            .field("cache", &self.cache)
            .finish_non_exhaustive()
    }
}

impl DlrlPort {
    /// `uses CCM_DDS::CacheOperation <cache>`: the Cache of the port, as
    /// its operative part (§8.2.1.1).
    #[must_use]
    pub fn cache(&self) -> Arc<dyn CacheOperation> {
        Arc::clone(&self.operation)
    }

    /// `uses <Class>Home <receptacle>`: the home of the receptacle named
    /// `receptacle`, the entry point to the objects of its class
    /// (§8.2.1.2); `None` for a name the port type does not declare.
    #[must_use]
    pub fn home(&self, receptacle: &str) -> Option<&ObjectHome> {
        let at = self
            .port_type
            .homes
            .iter()
            .position(|r| r.name == receptacle)?;
        self.homes.get(at)
    }

    /// The port type.
    #[must_use]
    pub fn port_type(&self) -> &DlrlPortType {
        &self.port_type
    }

    /// The name of the mirror port the port is connected to.
    #[must_use]
    pub fn mirror_port(&self) -> &str {
        &self.mirror_port
    }
}

/// What the fragment of one port created.
struct Fragment {
    /// `None` once deleted.
    cache: Option<Cache>,
    /// The DomainParticipant dedicated to the port; `None` for a default
    /// one, or once deleted.
    participant: Option<DomainParticipant>,
    /// Gives back the shares of the `TopicListener`s of the topics.
    topic_shares: Vec<Box<dyn FnOnce() + Send>>,
}

/// Caches are named per process; each fragment names its own.
static CACHE_NAMES: AtomicU64 = AtomicU64::new(0);

/// The return code of a DLRL exception, for the removal.
fn internal(error: &DlrlException) -> InternalError {
    let code = match error {
        DlrlException::PreconditionNotMet { .. } => return_code::PRECONDITION_NOT_MET,
        DlrlException::AlreadyDeleted { .. } => return_code::ALREADY_DELETED,
        DlrlException::BadParameter { .. } => return_code::BAD_PARAMETER,
        _ => return_code::ERROR,
    };
    InternalError::code(code)
}

/// A DDS-DLRL connector (§8.3): "A DLRL connector should inherit from the
/// connector DDS_Base, to be given a ConnectorStatusListener port, a
/// domain id and a QoS profile attribute, and add as many mirror ports as
/// there exist DLRL extended ports to share the related set of topics."
///
/// ```text
/// connector MyDlrlConnector : CCM_DDS::DDS_Base {
///     mirrorport MyDlrlPort_1 p1;
///     mirrorport MyDlrlPort_2 p2;
/// };
/// ```
///
/// The connector dereferences to [`DdsBase`]. One connector of a design is
/// deployed as one connector object per process, with the same
/// attributes; the fragments meet through DDS.
pub struct DlrlConnector {
    base: DdsBase,
    mirror_ports: Vec<(String, DlrlPortType)>,
    fragments: Mutex<Vec<Fragment>>,
    /// Held while a fragment is created and while the fragments are
    /// removed.
    changing: Mutex<()>,
}

impl std::ops::Deref for DlrlConnector {
    type Target = DdsBase;

    fn deref(&self) -> &DdsBase {
        &self.base
    }
}

impl DlrlConnector {
    /// A connector with a mirror port per `(name, port type)` of
    /// `mirror_ports`, `domain_id` 0 and no QoS profile.
    ///
    /// # Errors
    /// [`DeclarationError::NoMirrorPort`] without a mirror port;
    /// [`DeclarationError::Name`] and [`DeclarationError::DuplicateName`]
    /// for the names of the mirror ports.
    pub fn new(mirror_ports: Vec<(&str, DlrlPortType)>) -> Result<Self, DeclarationError> {
        if mirror_ports.is_empty() {
            return Err(DeclarationError::NoMirrorPort);
        }
        distinct(mirror_ports.iter().map(|(name, _)| *name))?;
        Ok(Self {
            base: DdsBase::new(),
            mirror_ports: mirror_ports
                .into_iter()
                .map(|(name, port_type)| (name.to_owned(), port_type))
                .collect(),
            fragments: Mutex::new(Vec::new()),
            changing: Mutex::new(()),
        })
    }

    /// The mirror ports, `mirrorport <port type> <name>`, in the order of
    /// the declaration.
    #[must_use]
    pub fn mirror_ports(&self) -> Vec<(&str, &DlrlPortType)> {
        self.mirror_ports
            .iter()
            .map(|(name, port_type)| (name.as_str(), port_type))
            .collect()
    }

    /// Connects a DLRL port of `component` to the mirror port
    /// `mirror_port`: the fragment creates the Cache for `cache_usage` in
    /// the DomainParticipant of the port, registers the home of each home
    /// receptacle, applies the QoS profile and enables the DCPS entities
    /// (§8.2.2; see the module documentation). The DataWriters and the
    /// Subscriber report to `error_listener`, as do the topics.
    ///
    /// # Errors
    /// [`ConnectorError::NotConfigured`] before `configuration_complete`;
    /// [`ConnectorError::UnknownMirrorPort`]; [`ConnectorError::Dlrl`]
    /// when the DLRL entities refuse (a class whose parent or relation
    /// target has no home receptacle is `BadHomeDefinition`);
    /// [`ConnectorError::TopicQos`] for a topic the DomainParticipant has
    /// with another value of a policy the `topic_qos` of the profile sets;
    /// [`ConnectorError::TopicFilter`] when the profile selects different
    /// containers for two topics of the port where one entity serves both
    /// (the DomainParticipant, the Publisher, the Subscriber);
    /// [`ConnectorError::Dds`] when DDS refuses an entity or a QoS of the
    /// profile. What the fragment created is deleted again.
    pub fn connect(
        &self,
        mirror_port: &str,
        component: &Component,
        cache_usage: CacheUsage,
    ) -> Result<DlrlPort, ConnectorError> {
        let profile = self.base.profile()?;
        let port_type = self
            .mirror_ports
            .iter()
            .find(|(name, _)| name == mirror_port)
            .map(|(_, port_type)| port_type)
            .ok_or_else(|| ConnectorError::UnknownMirrorPort(mirror_port.to_owned()))?;
        let topics = port_type.topic_names();
        let wanted = profile
            .participant_of_topics(&topics)
            .map_err(|topic_names| ConnectorError::TopicFilter {
                container: "domainparticipant_qos",
                topic_names,
            })?;
        let _changing = lock(&self.changing);
        let (participant, dedicated) =
            component.place_participant(self.base.domain_id(), wanted)?;
        let release_participant = || {
            if dedicated {
                // The error of the fragment is the one to report.
                let _ = delete_participant(&participant);
            }
        };
        let name = format!(
            "dds4ccm.{}.{mirror_port}.{}",
            component.name(),
            CACHE_NAMES.fetch_add(1, Ordering::Relaxed)
        );
        let factory = CacheFactory::get_instance();
        let description = CacheDescription {
            name,
            domain: participant.clone(),
        };
        let cache = match factory.create_cache(cache_usage, description) {
            Ok(cache) => cache,
            Err(error) => {
                release_participant();
                return Err(error.into());
            }
        };
        let mut topic_shares: Vec<Box<dyn FnOnce() + Send>> = Vec::new();
        match self.complete(&cache, port_type, profile, &participant, &mut topic_shares) {
            Ok(homes) => {
                lock(&self.fragments).push(Fragment {
                    cache: Some(cache.clone()),
                    participant: dedicated.then(|| participant.clone()),
                    topic_shares,
                });
                Ok(DlrlPort {
                    port_type: port_type.clone(),
                    mirror_port: mirror_port.to_owned(),
                    operation: Arc::new(cache.clone()),
                    cache,
                    homes,
                })
            }
            Err(error) => {
                for share in topic_shares {
                    share();
                }
                let _ = factory.delete_cache(&cache);
                release_participant();
                Err(error)
            }
        }
    }

    /// Steps 2 to 4 of §8.2.2 on `cache`: the homes, the QoS profile, the
    /// DCPS entities. Returns the homes in the order of the receptacles.
    fn complete(
        &self,
        cache: &Cache,
        port_type: &DlrlPortType,
        profile: &Profile,
        participant: &DomainParticipant,
        topic_shares: &mut Vec<Box<dyn FnOnce() + Send>>,
    ) -> Result<Vec<ObjectHome>, ConnectorError> {
        let mut homes = Vec::with_capacity(port_type.homes.len());
        for receptacle in &port_type.homes {
            let home = ObjectHome::new(Arc::clone(&port_type.mapping), &receptacle.class)?;
            cache.register_home(&home)?;
            homes.push(home);
        }
        let topics = port_type.topic_names();
        for topic in &topics {
            // A topic the Cache creates gets the `topic_qos` of the
            // profile. One the DomainParticipant has when the Cache asks
            // for it, also one another connector or the application
            // creates while this fragment is made, is used with its QoS
            // and held to the profile below: there is no window between a
            // look for the topic and its creation.
            cache.set_new_topic_qos(topic, profile.topic_qos(topic))?;
        }
        cache.register_all_for_pubsub()?;
        let error_listener = self.base.error_listener();
        let publisher = cache.the_publisher();
        let subscriber = cache.the_subscriber();
        let differing = |container: &'static str| {
            move |topic_names: [String; 2]| ConnectorError::TopicFilter {
                container,
                topic_names,
            }
        };
        if let Some(publisher) = &publisher {
            let qos = profile
                .publisher_qos_over(&topics, publisher.get_qos())
                .map_err(differing("publisher_qos"))?;
            publisher.set_qos(qos)?;
        }
        if let Some(subscriber) = &subscriber {
            let qos = profile
                .subscriber_qos_over(&topics, subscriber.get_qos())
                .map_err(differing("subscriber_qos"))?;
            subscriber.set_qos(qos)?;
            let listener = SubscriberStatusListener::new(Arc::clone(&error_listener));
            let mask = listener.mask();
            subscriber.set_listener(Some(Arc::new(listener) as ArcSubscriberListener), mask);
        }
        for topic in &topics {
            let writer = publisher
                .as_ref()
                .and_then(|p| p.lookup_datawriter::<DynamicSample>(topic));
            let reader = subscriber
                .as_ref()
                .and_then(|s| s.lookup_datareader::<DynamicSample>(topic));
            if let Some(writer) = &writer {
                writer.set_qos(profile.datawriter_qos_over(topic, writer.get_qos()))?;
                let listener = WriterStatusListener::new(Arc::clone(&error_listener));
                let mask = listener.mask();
                writer.set_listener(Some(Arc::new(listener) as ArcDataWriterListener), mask);
            }
            if let Some(reader) = &reader {
                reader.set_qos(profile.datareader_qos_over(topic, reader.get_qos()))?;
            }
            let of_topic = match (&writer, &reader) {
                (Some(writer), _) => writer.topic().clone(),
                (None, Some(reader)) => reader.topic().clone(),
                // Not reached: a Cache has a Publisher or a Subscriber,
                // and an entity of it per topic of its classes.
                (None, None) => {
                    return Err(ConnectorError::Dds(InternalError::code(
                        return_code::PRECONDITION_NOT_MET,
                    )));
                }
            };
            // As for a DCPS connector (§7.4.3): a topic serves the port
            // when every policy the `topic_qos` of the profile sets has
            // that value in it.
            let policies = profile.topic_qos_differences(topic, &of_topic.qos());
            if !policies.is_empty() {
                return Err(ConnectorError::TopicQos {
                    topic_name: topic.clone(),
                    policies,
                });
            }
            topic_shares.push(Box::new(share_topic_listener(
                participant,
                &of_topic,
                &error_listener,
            )));
        }
        cache.enable_all_for_pubsub()?;
        Ok(homes)
    }

    /// The Cache the fragment created for `port`, a port of this
    /// connector: what the connector configured, with the operations of
    /// `DDS::Cache` the port does not give the component (the
    /// configuration, the DCPS entities). `None` for a port of another
    /// connector, or after `remove`.
    #[must_use]
    pub fn cache_of(&self, port: &DlrlPort) -> Option<Cache> {
        lock(&self.fragments)
            .iter()
            .filter_map(|fragment| fragment.cache.as_ref())
            .find(|cache| **cache == port.cache)
            .cloned()
    }

    /// Removes the fragments of the connector: deletes the Cache of each
    /// port, with its DataWriters, DataReaders, Topics, Publisher and
    /// Subscriber, and the DomainParticipants dedicated to a port. From
    /// then on the operations of the `CacheOperation` of a port raise
    /// `AlreadyDeleted`. The attributes stay fixed.
    ///
    /// # Errors
    /// `InternalError` with the code of the first error. What could not
    /// be deleted stays with the connector, and the next removal tries it
    /// again.
    pub fn remove(&self) -> Result<(), InternalError> {
        let _changing = lock(&self.changing);
        let fragments = std::mem::take(&mut *lock(&self.fragments));
        let factory = CacheFactory::get_instance();
        let mut first = Ok(());
        let mut left = Vec::new();
        for mut fragment in fragments.into_iter().rev() {
            for share in fragment.topic_shares.drain(..) {
                share();
            }
            if let Some(cache) = fragment.cache.take() {
                match factory.delete_cache(&cache) {
                    Ok(()) | Err(DlrlException::AlreadyDeleted { .. }) => {}
                    Err(error) => {
                        if first.is_ok() {
                            first = Err(internal(&error));
                        }
                        fragment.cache = Some(cache);
                        left.push(fragment);
                        continue;
                    }
                }
            }
            if let Some(participant) = fragment.participant.take()
                && let Err(error) = delete_participant(&participant)
            {
                if first.is_ok() {
                    first = Err(error.into());
                }
                fragment.participant = Some(participant);
                left.push(fragment);
            }
        }
        left.reverse();
        *lock(&self.fragments) = left;
        first
    }
}
