//! Contract of `zerodds-build` with `zerodds-lang-render`
//! (internal/release/rc8-test-suite.md, "Crate tier").
//!
//! What this crate uses of `zerodds-lang-render` (`src/lib.rs`): `rust::file`
//! over the `zerodds-lang-cst` file the build assembles (its doc lines, its
//! `use` lines, the items of `zerodds-lang-rules`), whose text the build
//! script writes to `OUT_DIR` for a `include!`. The build relies on that text
//! being one Rust source a crate can include: the doc lines as comments,
//! every `use` before the items, a nested module per `mod`.
//!
//! Oracle: the Rust reference ("Comments": a `///` line is an outer doc
//! comment of the item after it, an empty one is `///`; an inner `//!` may
//! not follow an item, and the file is `include!`d after other items;
//! "Use declarations").
#![allow(clippy::unwrap_used)]

use zerodds_lang_cst::common::{Doc, Ident, Path, Visibility};
use zerodds_lang_cst::rust::{File, Use};

#[test]
fn an_included_file_carries_its_header_as_doc_lines_and_its_uses_after_it() {
    let text = zerodds_lang_render::rust::file(&File {
        inner_attrs: Vec::new(),
        doc: Doc::lines(&["Generated by zerodds-build.", "", "Do not edit."]),
        uses: vec![Use {
            path: Path::single("zerodds_wire"),
            names: vec![Ident::new("Reader"), Ident::new("Writer")],
            visibility: Visibility::Private,
        }],
        items: Vec::new(),
    });
    assert!(
        !text.contains("//!"),
        "an included file has no inner doc comment: {text}"
    );
    let lines: Vec<&str> = text.lines().collect();
    assert_eq!(
        lines[..4],
        [
            "/// Generated by zerodds-build.",
            "///",
            "/// Do not edit.",
            "use zerodds_wire::{Reader, Writer};",
        ],
        "{text}"
    );
}
