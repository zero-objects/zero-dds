//! IDL `component` / `home` → Rust trait + servant.
//!
//! CCM 4.0 §6. A `component` and a `home` are interface nodes with a
//! different keyword — [`InterfaceKind::Component`] and
//! [`InterfaceKind::Home`] — which is what the model calls them, and
//! the previous version matched on two parse-tree node kinds of its
//! own.
//!
//! What is emitted is the lifecycle trait and the repository
//! identifier. The container lifecycle beyond `configuration_complete`
//! and `ccm_remove`, and the receptacle, facet and event bindings, are
//! `zerodds-ccm`'s, which has the CIF and the container.
//!
//! [`InterfaceKind::Component`]: zerodds_ast::InterfaceKind::Component
//! [`InterfaceKind::Home`]: zerodds_ast::InterfaceKind::Home

use zerodds_ast::{AnyId, InterfaceNode};
use zerodds_ast_core::Id;

use crate::emitter::Ctx;
use crate::error::Result;
use crate::interface_emit::interface_of;

/// The repository identifier the model holds for an interface node.
///
/// zerodds-lint: recursion-depth 1 — this does not recurse. The callee
/// is `zerodds_corba_codegen::repository_id_of`, a different function
/// in another crate; `dds_bounded_recursion` compares only the last
/// segment of a call path, so the delegation reads as a self-call.
fn repository_id_of(ctx: &Ctx<'_>, id: Id<InterfaceNode>, node: &InterfaceNode) -> String {
    zerodds_corba_codegen::repository_id_of(ctx.ast, AnyId::Interface(id, node.node_id))
        .map(|resolved| resolved.id)
        .unwrap_or_else(|| zerodds_corba_codegen::build_repository_id(&[], &node.name, 1, 0))
}

/// Emits an IDL `component` as a Rust trait plus its servant marker.
pub fn emit_component(out: &mut String, ctx: &Ctx<'_>, id: Id<InterfaceNode>) -> Result<()> {
    let node = interface_of(ctx, id)?;
    let name = &node.name;
    let repo_id = repository_id_of(ctx, id, node);
    let repo_const = name.to_ascii_uppercase();
    out.push_str("/// Generated by `zerodds-corba-rust` from IDL component (CCM 4.0 §6).\n");
    out.push_str(&format!(
        "/// CORBA Repository-ID for component `{name}`.\npub const {repo_const}_REPOSITORY_ID: &str = \"{repo_id}\";\n"
    ));
    out.push_str(&format!(
        "pub trait {name}: zerodds_corba_rust::ComponentServant {{\n"
    ));
    out.push_str("    /// CCM lifecycle: called by the container after the config phase.\n");
    out.push_str("    /// # Errors\n    /// Whatever the component reports.\n");
    out.push_str("    fn configuration_complete(&mut self) -> ::core::result::Result<(), zerodds_corba_rust::CorbaException> {\n");
    out.push_str("        ::core::result::Result::Ok(())\n");
    out.push_str("    }\n");
    out.push_str("    /// CCM lifecycle: called by the container before removal.\n");
    out.push_str("    /// # Errors\n    /// Whatever the component reports.\n");
    out.push_str("    fn ccm_remove(&mut self) -> ::core::result::Result<(), zerodds_corba_rust::CorbaException> {\n");
    out.push_str("        ::core::result::Result::Ok(())\n");
    out.push_str("    }\n");
    out.push_str("}\n");
    Ok(())
}

/// Emits an IDL `home` as a Rust home trait.
pub fn emit_home(out: &mut String, ctx: &Ctx<'_>, id: Id<InterfaceNode>) -> Result<()> {
    let node = interface_of(ctx, id)?;
    let name = &node.name;
    let repo_id = repository_id_of(ctx, id, node);
    let repo_const = name.to_ascii_uppercase();
    out.push_str("/// Generated by `zerodds-corba-rust` from IDL home (CCM 4.0 §6.5).\n");
    out.push_str(&format!(
        "/// CORBA Repository-ID for home `{name}`.\npub const {repo_const}_REPOSITORY_ID: &str = \"{repo_id}\";\n"
    ));
    out.push_str(&format!(
        "pub trait {name}: zerodds_corba_rust::ComponentHome {{\n"
    ));
    out.push_str("}\n");
    Ok(())
}
