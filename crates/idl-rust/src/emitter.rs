//! Top-level emitter: AST → Rust string.

use zerodds_idl::ast::Annotation;
use zerodds_idl::ast::types::{
    ConstDecl, ConstExpr, ConstType, ConstrTypeDecl, Declarator, Definition, ExceptDecl, Export,
    FloatingType, InterfaceDcl, Literal, LiteralKind, ModuleDef, Specification, StructDcl,
    TypeDecl, UnionDcl,
};
use zerodds_idl::semantics::annotations::PlacementKind;

use crate::error::Result;
use crate::type_map::{escape_keyword, rust_integer_type, rust_type_for};
