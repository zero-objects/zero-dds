    #[test]
    fn all_ts_keyword_struct_names_compile_to_escaped_declarations() {
        // Sweep: every reserved TS word used as a struct name must
        // escape. A handful of these words (e.g. `case`, `default`,
        // `enum`, `switch`, `true`) are *also* IDL-level reserved
        // words and cannot be used as an IDL identifier at all — that
        // is a wholly separate, pre-existing IDL-grammar restriction,
        // unrelated to target-language keyword escaping, so such
        // words are skipped here rather than asserted on.
        let mut exercised = 0;
        for kw in crate::keywords::TS_RESERVED {
            let idl = alloc::format!("struct {kw} {{ long x; }};");
            let Ok(ast) = zerodds_idl::parse(&idl, &ParserConfig::default()) else {
                continue;
            };
            let ts = generate_ts_source(&ast).expect("gen");
            let expected = alloc::format!("export interface {kw}_");
            assert!(
                ts.contains(&expected),
                "keyword `{kw}` must escape to `{kw}_`, got:\n{ts}"
            );
            exercised += 1;
        }
        // Sanity: most of the 46-word list must actually be valid IDL
        // identifiers (this must not silently degrade to a no-op sweep).
        assert!(
            exercised >= 30,
            "expected at least 30 TS keywords usable as IDL identifiers, got {exercised}"
        );
    }
