/// Emits `<Name>TypeSupport: DdsTopicType<<Name>>` const for an
/// IDL `struct`. Implements encode/decode/keyHash against
/// `Xcdr2Writer`/`Xcdr2Reader` from `@zerodds/cdr`.
fn emit_struct_typesupport(
    out: &mut String,
    s: &zerodds_idl::ast::StructDef,
    module_path: &[String],
) -> Result<(), IdlTsError> {
    let name = escape_ts_ident(&s.name.text);
    let name = &name;
    // `typeName` is runtime reflection/cross-language type identity, not TS
    // syntax — keep the original (unescaped) module path + struct name.
    let mut full = module_path.to_vec();
    full.push(s.name.text.clone());
    let type_name = full.join("::");

    let extensibility = struct_extensibility(&s.annotations);
    let has_key = struct_has_any_key(s);

    out.push_str(&alloc::format!(
        "export const {name}TypeSupport: DdsTopicType<{name}> = {{\n"
    ));
    out.push_str(&alloc::format!("    typeName: \"{type_name}\",\n"));
    out.push_str(&alloc::format!("    isKeyed: {has_key},\n"));
    out.push_str(&alloc::format!("    extensibility: \"{extensibility}\",\n"));

    // === encodeInto (shared writer; nested-member entry point) ===
    out.push_str(&alloc::format!(
        "    encodeInto(w: Xcdr2Writer, s: {name}): void {{\n"
    ));
    emit_struct_encode_body(out, s, "        ")?;
    out.push_str("    },\n");

    // === encode (fresh writer) ===
    out.push_str(&alloc::format!(
        "    encode(s: {name}, endian: EndianMode = \"le\", representation = 1): Uint8Array {{\n"
    ));
    // representation: 1 = XCDR2 (alignment cap 4), 0 = XCDR1 / classic CDR (cap 8,
    // no DHEADER, PL_CDR1 @mutable).
    out.push_str("        const w = new Xcdr2Writer(endian, representation === 0 ? 8 : 4);\n");
    out.push_str("        this.encodeInto(w, s);\n");
    out.push_str("        return w.toBytes();\n");
    out.push_str("    },\n");

    // === decodeFrom (shared reader; nested-member entry point) ===
    out.push_str(&alloc::format!(
        "    decodeFrom(r: Xcdr2Reader): {name} {{\n"
    ));
    emit_struct_decode_body(out, s, "        ")?;
    out.push_str("    },\n");

    // === decode (fresh reader) ===
    // `endian` is trailing-optional (default "le") so existing positional
    // callers are unaffected; a big-endian payload decodes with decode(bytes,
    // 0, len, "be"). The reader threads it through every read, incl. @mutable
    // member bodies and wstring units.
    out.push_str(&alloc::format!(
        "    decode(bytes: Uint8Array, offset = 0, length: number = bytes.length - offset, endian: EndianMode = \"le\", representation = 1): {name} {{\n"
    ));
    // representation: 1 = XCDR2 (alignment cap 4), 0 = XCDR1 / classic CDR (cap 8,
    // no DHEADER, PL_CDR1 @mutable).
    out.push_str("        const r = new Xcdr2Reader(bytes, offset, length, endian, representation === 0 ? 8 : 4);\n");
    out.push_str("        return this.decodeFrom(r);\n");
    out.push_str("    },\n");

    // === keyHash ===
    out.push_str(&alloc::format!("    keyHash(s: {name}): Uint8Array {{\n"));
    if has_key {
        // PlainCdr2BeKeyHolder: big-endian encode of the @key fields (XTypes §7.6.8).
        out.push_str("        const w = new Xcdr2Writer(\"be\");\n");
        emit_struct_keyhash_body(out, s, "        ")?;
        // XTypes 1.3 §7.6.8.4: holder ≤ 16 octets -> zero-pad; otherwise MD5.
        out.push_str("        const __holder = w.toBytes();\n");
        out.push_str("        if (__holder.length <= 16) {\n");
        out.push_str("            const __h = new Uint8Array(16);\n");
        out.push_str("            __h.set(__holder);\n");
        out.push_str("            return __h;\n");
        out.push_str("        }\n");
        out.push_str("        return md5(__holder);\n");
    } else {
        out.push_str("        return new Uint8Array(16);\n");
    }
    out.push_str("    },\n");
    out.push_str("};\n\n");

    let _ = s; // marker
    Ok(())
}

fn struct_has_any_key(s: &zerodds_idl::ast::StructDef) -> bool {
    // Includes inherited @key members: a derived struct is keyed when its base
    // carries a @key, even if the derived adds none (XTypes §7.4.3.4.1 + §7.6.8).
    resolved_wire_members(s)
        .iter()
        .any(|m| has_annotation(&m.annotations, "key"))
}

/// Whether any struct anywhere in the spec (including nested modules) has
/// an `@key` member — unions are never keyed (see `emit_union_descriptor`'s
/// `keyHash`), so only the struct arm needs a recursive check. Drives
/// whether the `md5` runtime import is needed.
///
/// zerodds-lint: recursion-depth 32 (IDL-Module-Nesting)
fn spec_uses_key(definitions: &[Definition]) -> bool {
    use zerodds_idl::ast::{ConstrTypeDecl, StructDcl, TypeDecl};
    definitions.iter().any(|def| match def {
        Definition::Type(TypeDecl::Constr(ConstrTypeDecl::Struct(StructDcl::Def(s)))) => {
            struct_has_any_key(s)
        }
        Definition::Module(m) => spec_uses_key(&m.definitions),
        _ => false,
    })
}

/// Whether the spec declares any `interface` (RPC service) anywhere,
/// including nested modules. Drives whether the `ServiceDescriptor` /
/// `OperationDescriptor` / `OperationParameterDescriptor` /
/// `AttributeDescriptor` / `ParameterMode` imports are needed.
///
/// zerodds-lint: recursion-depth 32 (IDL-Module-Nesting)
fn spec_uses_interface(definitions: &[Definition]) -> bool {
    definitions.iter().any(|def| match def {
        Definition::Interface(_) => true,
        Definition::Module(m) => spec_uses_interface(&m.definitions),
        _ => false,
    })
}

/// Generates the encode body. Handles final/appendable/mutable.
fn emit_struct_encode_body(
    out: &mut String,
    s: &zerodds_idl::ast::StructDef,
    indent: &str,
) -> Result<(), IdlTsError> {
    let extensibility = struct_extensibility(&s.annotations);
    // Base-class members precede own members on the wire (XTypes §7.4.3.4.1).
    let zd_members = resolved_wire_members(s);
    match extensibility {
        "final" => {
            for m in &zd_members {
                emit_member_encode(out, m, indent, "s.")?;
            }
        }
        "appendable" => {
            out.push_str(&alloc::format!(
                "{indent}const _tok = w.beginAppendable();\n"
            ));
            for m in &zd_members {
                emit_member_encode(out, m, indent, "s.")?;
            }
            out.push_str(&alloc::format!("{indent}w.endAppendable(_tok);\n"));
        }
        "mutable" => {
            // XCDR1 (classic CDR): @mutable is PL_CDR1 — a [PID][length] list with
            // no outer DHEADER, each member body member-relative. Emit it next to
            // the XCDR2 PL_CDR2 EMHEADER path, gated on the writer representation.
            out.push_str(&alloc::format!("{indent}if (w.isXcdr1) {{\n"));
            out.push_str(&alloc::format!("{indent}const _plOuter = w;\n"));
            let mut next_id1: i64 = 0;
            for m in &zd_members {
                let id_override = ts_member_id_override(s, m);
                let optional = has_annotation(&m.annotations, "optional");
                for d in &m.declarators {
                    let id = id_override.unwrap_or(next_id1);
                    next_id1 = id + 1;
                    let field = d.name().text.clone();
                    if optional {
                        out.push_str(&alloc::format!(
                            "{indent}if (s.{field} !== undefined && s.{field} !== null) {{\n"
                        ));
                    }
                    // Build the member body in a fresh member-relative XCDR1
                    // sub-writer (shadowing `w` so the emitted body writes into it),
                    // then frame it as a PL_CDR1 member.
                    out.push_str(&alloc::format!("{indent}{{\n"));
                    out.push_str(&alloc::format!(
                        "{indent}    const _sub = new Xcdr2Writer(_plOuter.endian, 8);\n"
                    ));
                    out.push_str(&alloc::format!("{indent}    {{ const w = _sub;\n"));
                    emit_declarator_encode(
                        out,
                        &m.type_spec,
                        d,
                        &alloc::format!("s.{field}"),
                        &alloc::format!("{indent}        "),
                        0,
                    )?;
                    out.push_str(&alloc::format!("{indent}    }}\n"));
                    out.push_str(&alloc::format!(
                        "{indent}    _plOuter.writePlCdr1Member({id}, _sub.toBytes());\n"
                    ));
                    out.push_str(&alloc::format!("{indent}}}\n"));
                    if optional {
                        out.push_str(&alloc::format!("{indent}}}\n"));
                    }
                }
            }
            out.push_str(&alloc::format!("{indent}_plOuter.writePlCdr1Sentinel();\n"));
            out.push_str(&alloc::format!("{indent}}} else {{\n"));
            out.push_str(&alloc::format!("{indent}const _tok = w.beginMutable();\n"));
            let mut next_id: i64 = 0;
            for m in &zd_members {
                let id_override = ts_member_id_override(s, m);
                let must = has_annotation(&m.annotations, "must_understand");
                let optional = has_annotation(&m.annotations, "optional");
                for d in &m.declarators {
                    let id = id_override.unwrap_or(next_id);
                    next_id = id + 1;
                    let field = d.name().text.clone();
                    if optional {
                        out.push_str(&alloc::format!(
                            "{indent}if (s.{field} !== undefined && s.{field} !== null) {{\n"
                        ));
                    }
                    let inner_indent_owned = alloc::format!("{indent}    ");
                    let inner_indent: &str = if optional {
                        inner_indent_owned.as_str()
                    } else {
                        indent
                    };
                    emit_mutable_member_encode(
                        out,
                        &m.type_spec,
                        d,
                        &field,
                        id as u32,
                        must,
                        optional,
                        inner_indent,
                    )?;
                    if optional {
                        out.push_str(&alloc::format!("{indent}}}\n"));
                    }
                }
            }
            out.push_str(&alloc::format!("{indent}w.endMutable(_tok);\n"));
            out.push_str(&alloc::format!("{indent}}}\n"));
        }
        // struct_extensibility() is exhaustive over Final/Appendable/Mutable;
        // unknown variants are treated as Final (no DHEADER wrap).
        _ => {}
    }
    Ok(())
}

/// Produces a single member-encode call (final / appendable).
fn emit_member_encode(
    out: &mut String,
    m: &zerodds_idl::ast::Member,
    indent: &str,
    prefix: &str,
) -> Result<(), IdlTsError> {
    let optional = has_annotation(&m.annotations, "optional");
    for d in &m.declarators {
        let field = d.name().text.clone();
        let target = alloc::format!("{prefix}{field}");
        if optional {
            // present-byte for final/appendable per §4.
            out.push_str(&alloc::format!(
                "{indent}if ({target} !== undefined && {target} !== null) {{\n"
            ));
            out.push_str(&alloc::format!("{indent}    w.writeOctet(1);\n"));
            emit_declarator_encode(out, &m.type_spec, d, &target, &format!("{indent}    "), 0)?;
            out.push_str(&alloc::format!("{indent}}} else {{\n"));
            out.push_str(&alloc::format!("{indent}    w.writeOctet(0);\n"));
            out.push_str(&alloc::format!("{indent}}}\n"));
        } else {
            emit_declarator_encode(out, &m.type_spec, d, &target, indent, 0)?;
        }
    }
    Ok(())
}

/// Encodes a struct member honouring the declarator's fixed-array dimensions
/// (TS-cluster #2). A fixed-size array `T name[N]` (or multi-dim `T grid[R][C]`)
/// has no length prefix on the wire (XCDR2 §7.4.3.4): each dimension is a fixed
/// count, so emit one `for` loop per dimension iterating exactly the declared
/// bound, then encode the element. `Declarator::Simple` falls straight through
/// to `emit_typespec_encode`.
///
/// zerodds-lint: recursion-depth 16 (array dimension count)
fn emit_declarator_encode(
    out: &mut String,
    t: &TypeSpec,
    d: &zerodds_idl::ast::Declarator,
    expr: &str,
    indent: &str,
    dim: usize,
) -> Result<(), IdlTsError> {
    use zerodds_idl::ast::Declarator;
    match d {
        Declarator::Simple(_) => emit_typespec_encode(out, t, expr, indent),
        Declarator::Array(arr) => emit_array_dim_encode(out, t, &arr.sizes, expr, indent, dim),
    }
}

/// `true` if a TS type maps to an XCDR `IS_PRIMITIVE` scalar (integers,
/// floats, bool, octet, char, wchar). Strings, enums, bitmask/bitset, structs,
/// unions, sequences and maps are NON-primitive. Typedefs resolve to their
/// target. Mirrors cdr-core `CdrEncode::IS_PRIMITIVE` (only scalar numerics
/// set it `true`; the default is `false`).
/// zerodds-lint: recursion-depth 64 (codegen AST walk; bounded by IDL nesting).
fn typespec_is_primitive(t: &TypeSpec) -> bool {
    match t {
        // Every IDL scalar primitive (integers, floats, bool, octet, char,
        // wchar) is XCDR `IS_PRIMITIVE`. (LongDouble has no wire codec and is
        // gated upstream, so it never reaches an array element here.)
        TypeSpec::Primitive(_) => true,
        TypeSpec::Scoped(s) => match lookup_scoped_kind(s) {
            Some(ScopedKind::Typedef(inner)) => typespec_is_primitive(&inner),
            // enum / bitmask / bitset / struct / union → non-primitive.
            _ => false,
        },
        // string / wstring / sequence / array / map / any / fixed → non-primitive.
        _ => false,
    }
}

/// `true` if a fixed array needs an XCDR2 collection DHEADER, decided ONCE at
/// the outermost dimension from the leaf element type (XTypes 1.3 §7.4.3.5 r8;
/// cdr-core `composite.rs` PARRAY vs collection DHEADER).
///
/// A multi-dimensional **primitive** array (e.g. `long[2][3]`) is a PARRAY: the
/// whole flattened body is `IS_PRIMITIVE`, so NO DHEADER is emitted on any
/// dimension. Only a leaf element that is itself non-primitive (struct, enum,
/// string, bitmask/bitset, …) frames the collection in a single DHEADER at the
/// outer dimension — e.g. `Pt[2]`. The DHEADER is therefore a property of the
/// leaf type, NOT of multi-dimensionality (the previous rule wrongly emitted a
/// spurious DHEADER for `long[2][3]`).
fn array_dim_needs_dheader(
    t: &TypeSpec,
    _sizes: &[zerodds_idl::ast::ConstExpr],
    dim: usize,
) -> bool {
    // Only the outermost dimension carries the (single) collection DHEADER, and
    // only when the leaf element is non-primitive.
    dim == 0 && !typespec_is_primitive(t)
}

/// Recursively emits the fixed-count loops for `sizes[dim..]`, encoding the
/// scalar/struct element at the innermost level. Wraps each dimension whose
/// element is non-primitive in an XCDR2 DHEADER (`beginAppendable`).
///
/// zerodds-lint: recursion-depth 16 (array dimension count)
fn emit_array_dim_encode(
    out: &mut String,
    t: &TypeSpec,
    sizes: &[zerodds_idl::ast::ConstExpr],
    expr: &str,
    indent: &str,
    dim: usize,
) -> Result<(), IdlTsError> {
    if dim >= sizes.len() {
        // All dimensions consumed → encode the element value.
        return emit_typespec_encode(out, t, expr, indent);
    }
    let n = eval_const_int(&sizes[dim]).ok_or_else(|| {
        IdlTsError::Unsupported(alloc::format!(
            "fixed-array dimension {dim} is not a constant integer"
        ))
    })?;
    // DHEADER before the (flattened) array body when the element is non-prim.
    let dheader = array_dim_needs_dheader(t, sizes, dim);
    let atok = alloc::format!("_atok{}", next_encode_id());
    if dheader {
        out.push_str(&alloc::format!(
            "{indent}const {atok} = w.beginAppendable();\n"
        ));
    }
    let idx = alloc::format!("_a{dim}");
    let elem = alloc::format!("{expr}[{idx}]");
    out.push_str(&alloc::format!(
        "{indent}for (let {idx} = 0; {idx} < {n}; {idx}++) {{\n"
    ));
    emit_array_dim_encode(out, t, sizes, &elem, &format!("{indent}    "), dim + 1)?;
    out.push_str(&alloc::format!("{indent}}}\n"));
    if dheader {
        out.push_str(&alloc::format!("{indent}w.endAppendable({atok});\n"));
    }
    Ok(())
}

/// Selects the compact EMHEADER LengthCode (0..7) for a `@mutable` member,
/// mirroring cdr-core `zerodds_idl_rust::struct_emit::mutable_member_length_code`
/// (XTypes 1.3 §7.4.3.4.2, 2-vendor consensus: CycloneDDS / RTI / FastDDS):
///
///   - array declarator OR `@optional`  → LC4 (universal NEXTINT form)
///   - primitive scalar 1/2/4/8 B       → LC0/LC1/LC2/LC3 (inline, NO NEXTINT)
///   - string / wstring                 → LC5 (the body's own leading uint32
///                                        length word IS reused as the NEXTINT;
///                                        NO separate NEXTINT is serialized)
///   - everything else (struct/union/   → LC4
///     enum/seq/map/bitmask/bitset)
///
/// LC0..3 carry their body inline (the reader length-skips by the LC-implied
/// fixed size). LC5 carries a variable body whose first 4 bytes (the string
/// length prefix) double as the framing length. LC4 emits an explicit NEXTINT
/// = body byte length, patched after the body is written.
fn mutable_member_lc(t: &TypeSpec, d: &zerodds_idl::ast::Declarator, optional: bool) -> u32 {
    use zerodds_idl::ast::Declarator;
    if matches!(d, Declarator::Array(_)) || optional {
        return 4;
    }
    if let Some(lc) = primitive_lc_inline(t) {
        return lc; // 0..3 inline primitive
    }
    // FINDING T1b: a member whose XCDR2 body BEGINS WITH A 4-BYTE LENGTH WORD —
    // a string/wstring length prefix, a non-primitive sequence / map DHEADER, or
    // a nested @appendable/@mutable struct's DHEADER — uses LC5 to REUSE that
    // word as the framing length (NO separate NEXTINT), matching CycloneDDS /
    // RTI / FastDDS and the cdr-core Rust reference. A @final nested struct (no
    // DHEADER) and a sequence<primitive> (bare element count, not a byte length)
    // fall through to the universal LC4. Mirrors cdr-core
    // `type_map::member_body_has_leading_dheader`.
    if member_body_has_leading_dheader(t) {
        return 5;
    }
    4
}

/// `true` if the XCDR2 serialized body of `t` begins with a 4-byte length word
/// (a leading DHEADER or a string length prefix), so a `@mutable` member of this
/// type uses EMHEADER LengthCode 5 (reuse that word as the framing NEXTINT).
///
/// Mirrors cdr-core `zerodds_idl_rust::type_map::member_body_has_leading_dheader`:
///   * `string` / `wstring` — uint32 octet length prefix → true.
///   * `map<K,V>` — always carries a DHEADER → true.
///   * `sequence<E>` — true iff `E` is NON-primitive (a `sequence<primitive>`
///     starts with a bare element count, not a byte length → false).
///   * a nested struct — true iff its extensibility is `@appendable` / `@mutable`
///     (those self-delimit with a leading DHEADER); a `@final` nested struct is
///     tight-packed → false. A typedef inherits its alias' framing.
///   * everything else (primitive / enum / bitmask / bitset / union / array /
///     fixed / any) → false.
///
/// zerodds-lint: recursion-depth 16
fn member_body_has_leading_dheader(t: &TypeSpec) -> bool {
    match t {
        TypeSpec::String(_) => true,
        TypeSpec::Map(_) => true,
        TypeSpec::Sequence(seq) => !typespec_is_primitive(&seq.elem),
        TypeSpec::Scoped(s) => match lookup_scoped_kind(s) {
            // A typedef-to-string/seq/map/struct inherits the alias' framing.
            Some(ScopedKind::Typedef(inner)) => member_body_has_leading_dheader(&inner),
            // A nested struct: leading DHEADER iff @appendable / @mutable.
            Some(ScopedKind::Struct { extensibility, .. }) => extensibility != "final",
            // enum / bitmask / bitset / union → no leading length word.
            _ => false,
        },
        _ => false,
    }
}

/// Produces a mutable-member encode with a compact EMHEADER1
/// (XTypes 1.3 §7.4.3.4.2), byte-identical to the cross-vendor-validated
/// Rust golden through `zerodds_cdr::struct_enc::encode_member_lc`.
///
/// The LengthCode is chosen by [`mutable_member_lc`]:
///   - **LC0..3** (primitive): EMHEADER, then the inline 1/2/4/8-byte body.
///     No NEXTINT, no patch — the LC fixes the body size.
///   - **LC5** (string/wstring): EMHEADER, then the body whose own leading
///     uint32 length word IS the framing length. No separate NEXTINT.
///   - **LC4** (array/optional/aggregate): EMHEADER + a NEXTINT placeholder,
///     then the body, then patch the NEXTINT = body byte length.
///
/// The member body is measured from its OWN alignment origin: cdr-core
/// serialises each member relative to the body start (a fresh per-member
/// writer that inherits XCDR2 max-align 4 but begins at offset 0), so inner
/// 8-byte primitives never get a leading pad inside the EMHEADER frame. We
/// mirror that with `pushAlignmentOrigin()` / `popAlignmentOrigin()`.
#[allow(clippy::too_many_arguments)]
fn emit_mutable_member_encode(
    out: &mut String,
    t: &TypeSpec,
    d: &zerodds_idl::ast::Declarator,
    field: &str,
    id: u32,
    must: bool,
    optional: bool,
    indent: &str,
) -> Result<(), IdlTsError> {
    let mu_str = if must { "true" } else { "false" };
    let lc = mutable_member_lc(t, d, optional);
    out.push_str(&alloc::format!("{indent}{{\n"));
    if lc == 4 {
        // Universal NEXTINT form: EMHEADER(LC4) + NEXTINT(body-len) + body.
        out.push_str(&alloc::format!(
            "{indent}    w.writeEmHeader({id}, 4, {mu_str}, 0);\n"
        ));
        out.push_str(&alloc::format!("{indent}    const _bodyStart = w.pos;\n"));
        out.push_str(&alloc::format!("{indent}    w.pushAlignmentOrigin();\n"));
        emit_declarator_encode(
            out,
            t,
            d,
            &alloc::format!("s.{field}"),
            &format!("{indent}    "),
            0,
        )?;
        out.push_str(&alloc::format!("{indent}    w.popAlignmentOrigin();\n"));
        out.push_str(&alloc::format!(
            "{indent}    w.patchUint32(_bodyStart - 4, w.pos - _bodyStart);\n"
        ));
    } else {
        // Compact form: EMHEADER(LC0..3/5), NO separate NEXTINT. The LC (or,
        // for LC5, the body's own leading length word) frames the body.
        out.push_str(&alloc::format!(
            "{indent}    w.writeEmHeader({id}, {lc}, {mu_str});\n"
        ));
        // Body origin resets so an 8-byte primitive (LC3) needs no leading pad.
        out.push_str(&alloc::format!("{indent}    w.pushAlignmentOrigin();\n"));
        emit_declarator_encode(
            out,
            t,
            d,
            &alloc::format!("s.{field}"),
            &format!("{indent}    "),
            0,
        )?;
        out.push_str(&alloc::format!("{indent}    w.popAlignmentOrigin();\n"));
    }
    out.push_str(&alloc::format!("{indent}}}\n"));
    Ok(())
}

/// Returns the LC value for primitives with a fixed inline size.
/// LC=0 -> 1B, LC=1 -> 2B, LC=2 -> 4B, LC=3 -> 8B. None otherwise.
fn primitive_lc_inline(t: &TypeSpec) -> Option<u32> {
    match t {
        TypeSpec::Primitive(p) => match p {
            PrimitiveType::Boolean | PrimitiveType::Octet | PrimitiveType::Char => Some(0),
            PrimitiveType::WideChar => Some(1),
            PrimitiveType::Integer(i) => match i {
                IntegerType::Short
                | IntegerType::UShort
                | IntegerType::Int16
                | IntegerType::UInt16 => Some(1),
                IntegerType::Long
                | IntegerType::ULong
                | IntegerType::Int32
                | IntegerType::UInt32 => Some(2),
                IntegerType::LongLong
                | IntegerType::ULongLong
                | IntegerType::Int64
                | IntegerType::UInt64 => Some(3),
                IntegerType::Int8 | IntegerType::UInt8 => Some(0),
            },
            PrimitiveType::Floating(f) => match f {
                FloatingType::Float => Some(2),
                FloatingType::Double => Some(3),
                FloatingType::LongDouble => None,
            },
        },
        _ => None,
    }
}
/// zerodds-lint: recursion-depth 64 (emit_typespec_encode bounded by AST depth)
/// Produces an encode call for a `TypeSpec` with the given source
/// expression (TypeScript side).
/// Codec kind of a scoped type reference, for the XCDR2 encode/decode dispatch.
#[derive(Clone)]
enum ScopedKind {
    /// struct — encoded via its nested `TypeSupport.encodeInto`/`decodeFrom`.
    /// Carries the struct's extensibility (`final`/`appendable`/`mutable`) so a
    /// `@mutable` member referencing it can decide whether its body begins with
    /// a leading DHEADER (appendable/mutable → LC5 EMHEADER) or not (final →
    /// LC4). Mirrors cdr-core `member_body_has_leading_dheader`. `def` is the
    /// struct's own definition (members + annotations), needed by the
    /// KeyHash-specific walker (`emit_key_typespec_encode`) to expand a
    /// nested `@key` struct member into that struct's own `@key` subset
    /// instead of delegating to `encodeInto` (which — correctly, for normal
    /// encoding — writes ALL of the nested struct's members).
    Struct {
        extensibility: &'static str,
        def: zerodds_idl::ast::StructDef,
    },
    /// union — encoded via its emitted `TypeSupport.encodeInto`/`decodeFrom`.
    Union,
    /// enum — SIGNED ordinal wire representation routed through the emitted
    /// `<Enum>Ordinal` / `<Enum>FromOrdinal` maps (the TS surface type is a
    /// string-literal union, NOT a number, so a bare numeric cast corrupts it).
    /// `holder_bytes` ∈ {1,2,4} is the @bit_bound-selected wire width (XTypes
    /// §7.4.5.1: N≤8 → 1, N≤16 → 2, else 4) — Cyclone honours it.
    Enum { holder_bytes: u8 },
    /// bitmask/bitset — encoded as an unsigned integer HOLDER whose width is
    /// the smallest of {1,2,4,8} bytes that fits the declared bits (XTypes 1.3
    /// §7.4.5: bitmask holder = smallest unit ≥ bit_bound; bitset holder =
    /// smallest unit ≥ Σ bitfield widths). Mirrors cdr-core
    /// `zerodds_idl_rust::bitset_emit::bitset_storage_type` (≤8→u8, ≤16→u16,
    /// ≤32→u32, else u64). The `u8` payload is the holder width in BYTES, so
    /// the codec picks writeOctet/writeUint16/writeUint32/writeUint64. The TS
    /// surface type stays `number` (≤32-bit holder) / `bigint` (64-bit holder).
    IntLike(u8),
    /// bitset — the TS surface is a STRUCT of named bitfields (`{kind, prio}`),
    /// but the wire is a single packed unsigned holder (XTypes 1.3 §7.4.5 /
    /// IDL §7.4.13). The codec must pack each field at its declared bit offset
    /// on encode and unpack on decode. Carries the holder width in BYTES and
    /// the `(field_name, bit_offset, bit_width)` layout in declaration order.
    /// cf. cdr-core `Flags { storage: u8 }` with `(storage>>off)&mask`.
    Bitset {
        holder_bytes: u8,
        fields: Vec<(String, u32, u32)>,
    },
    /// typedef — resolves to the aliased type.
    Typedef(TypeSpec),
}

thread_local! {
    /// Type-name → kind, built once per `generate_ts_source_with_config` call.
    /// Keyed by simple (last) name. Lets the codec tell a nested composite from
    /// an enum and resolve typedefs (see `build_type_registry`).
    static TYPE_REG: RefCell<BTreeMap<String, ScopedKind>> = const { RefCell::new(BTreeMap::new()) };

    /// Const-name → defining expression, for folding scoped/arithmetic const
    /// references (`const M = N * 2`). Keyed by simple (last) name.
    static CONST_VALUES: RefCell<BTreeMap<String, zerodds_idl::ast::ConstExpr>> =
        const { RefCell::new(BTreeMap::new()) };

    /// Enum-literal-name → ordinal, so a const/case-label expression that
    /// references an enumerator folds to its integer ordinal.
    static ENUM_LITERAL_VALUES: RefCell<BTreeMap<String, i64>> =
        const { RefCell::new(BTreeMap::new()) };

    /// Monotonic counter for encode-loop temporaries. Indentation depth alone is
    /// NOT unique: two SIBLING collection members live in the same function
    /// scope at the same depth, so a depth-keyed `_seqtok` would be `const`
    /// re-declared and the file would not parse. A run-global counter makes
    /// every emitted loop var / token globally unique.
    static ENCODE_LOOP_SEQ: RefCell<u64> = const { RefCell::new(0) };
}

/// Returns a fresh, run-global suffix for an encode-loop temporary, guaranteeing
/// uniqueness across nesting AND sibling collection members in one struct body.
fn next_encode_id() -> u64 {
    ENCODE_LOOP_SEQ.with(|c| {
        let mut c = c.borrow_mut();
        let id = *c;
        *c += 1;
        id
    })
}

/// Returns the holder width in BYTES (1/2/4/8) for the given total bit count,
/// matching cdr-core `zerodds_idl_rust::bitset_emit::bitset_storage_type`
/// (≤8→u8/1B, ≤16→u16/2B, ≤32→u32/4B, else u64/8B). XTypes 1.3 §7.4.5.
fn holder_bytes_for_bits(total_bits: u32) -> u8 {
    match total_bits {
        0..=8 => 1,
        9..=16 => 2,
        17..=32 => 4,
        _ => 8,
    }
}

/// Holder width (bytes) of an IDL `bitmask` = its effective `@bit_bound`
/// rounded up to the smallest unit (XTypes 1.3 §7.3.1.2.1.1). The DEFAULT
/// `@bit_bound` of a bitmask is **32** (→ UInt32/4-byte holder), NOT the count
/// of declared bit values, so `Perm{READ,WRITE,EXEC}` (3 values, unannotated)
/// is a 4-byte holder on the wire. Mirrors cdr-core
/// `bitmask_bit_bound(...).unwrap_or(32)` + `bitset_storage_type`.
fn bitmask_holder_bytes(b: &zerodds_idl::ast::BitmaskDecl) -> u8 {
    let bit_bound = annotation_int_value(&b.annotations, "bit_bound")
        .and_then(|v| u32::try_from(v).ok())
        .unwrap_or(32);
    holder_bytes_for_bits(bit_bound)
}

/// Holder width (bytes) of an IDL `bitset` = smallest unit ≥ Σ bitfield widths.
/// `Flags{bitfield<3> kind; bitfield<5> prio;}` → 8 bits → 1 byte.
fn bitset_holder_bytes(b: &zerodds_idl::ast::BitsetDecl) -> u8 {
    let total: i64 = b
        .bitfields
        .iter()
        .map(|f| eval_const_int(&f.spec.width).unwrap_or(0))
        .sum();
    holder_bytes_for_bits(total.max(0) as u32)
}

/// Computes the `(name, bit_offset, bit_width)` layout of an IDL `bitset`.
/// Bitfields are packed least-significant-bit first in declaration order
/// (IDL §7.4.13.4.3); an anonymous (`None`) padding bitfield still advances
/// the running offset but contributes no named field. Matches cdr-core
/// `set_<field>` shift offsets (e.g. `Flags`: kind@0/w3, prio@3/w5).
fn bitset_field_layout(b: &zerodds_idl::ast::BitsetDecl) -> Vec<(String, u32, u32)> {
    let mut layout = Vec::new();
    let mut offset: u32 = 0;
    for bf in &b.bitfields {
        let width = eval_const_int(&bf.spec.width).unwrap_or(0).max(0) as u32;
        if let Some(name) = &bf.name {
            layout.push((name.text.clone(), offset, width));
        }
        offset += width;
    }
    layout
}

/// Populates [`TYPE_REG`], [`CONST_VALUES`], and [`ENUM_LITERAL_VALUES`] from
/// the spec definitions (recursing modules).
fn build_type_registry(defs: &[Definition]) {
    use zerodds_idl::ast::{ConstrTypeDecl, StructDcl, TypeDecl, UnionDcl};
    /// zerodds-lint: recursion-depth 64 (bounded by IDL nesting)
    fn walk(
        defs: &[Definition],
        reg: &mut BTreeMap<String, ScopedKind>,
        consts: &mut BTreeMap<String, zerodds_idl::ast::ConstExpr>,
        enum_lits: &mut BTreeMap<String, i64>,
    ) {
        for def in defs {
            match def {
                Definition::Module(m) => walk(&m.definitions, reg, consts, enum_lits),
                Definition::Const(c) => {
                    consts.insert(c.name.text.clone(), c.value.clone());
                }
                Definition::Type(TypeDecl::Constr(c)) => match c {
                    ConstrTypeDecl::Struct(StructDcl::Def(s)) => {
                        reg.insert(
                            s.name.text.clone(),
                            ScopedKind::Struct {
                                extensibility: struct_extensibility(&s.annotations),
                                def: s.clone(),
                            },
                        );
                    }
                    ConstrTypeDecl::Union(UnionDcl::Def(u)) => {
                        reg.insert(u.name.text.clone(), ScopedKind::Union);
                    }
                    ConstrTypeDecl::Enum(e) => {
                        let eb = annotation_int_value(&e.annotations, "bit_bound")
                            .filter(|&v| (1..=32).contains(&v))
                            .unwrap_or(32);
                        let holder_bytes: u8 = if eb <= 8 {
                            1
                        } else if eb <= 16 {
                            2
                        } else {
                            4
                        };
                        reg.insert(e.name.text.clone(), ScopedKind::Enum { holder_bytes });
                        // Record each enumerator's ordinal (with @value(N)
                        // override) so a const/case-label can fold to it.
                        let mut next: i64 = 0;
                        for en in &e.enumerators {
                            let val =
                                annotation_int_value(&en.annotations, "value").unwrap_or(next);
                            enum_lits.insert(en.name.text.clone(), val);
                            next = val + 1;
                        }
                    }
                    ConstrTypeDecl::Bitmask(b) => {
                        reg.insert(
                            b.name.text.clone(),
                            ScopedKind::IntLike(bitmask_holder_bytes(b)),
                        );
                    }
                    ConstrTypeDecl::Bitset(b) => {
                        reg.insert(
                            b.name.text.clone(),
                            ScopedKind::Bitset {
                                holder_bytes: bitset_holder_bytes(b),
                                fields: bitset_field_layout(b),
                            },
                        );
                    }
                    _ => {}
                },
                Definition::Type(TypeDecl::Typedef(t)) => {
                    for d in &t.declarators {
                        reg.insert(
                            d.name().text.clone(),
                            ScopedKind::Typedef(t.type_spec.clone()),
                        );
                    }
                }
                _ => {}
            }
        }
    }
    let mut reg = BTreeMap::new();
    let mut consts = BTreeMap::new();
    let mut enum_lits = BTreeMap::new();
    walk(defs, &mut reg, &mut consts, &mut enum_lits);
    TYPE_REG.with(|r| *r.borrow_mut() = reg);
    CONST_VALUES.with(|r| *r.borrow_mut() = consts);
    ENUM_LITERAL_VALUES.with(|r| *r.borrow_mut() = enum_lits);
}

/// Looks up the codec kind of a scoped reference by its simple (last) name.
fn lookup_scoped_kind(s: &ScopedName) -> Option<ScopedKind> {
    let key = &s.parts.last()?.text;
    TYPE_REG.with(|r| r.borrow().get(key).cloned())
}

/// Fully-resolved wire member list for a struct: base-class members FIRST
/// (recursive, multi-level `A <- B <- C` => `A.a, B.b, C.c`), then the struct's
/// own members. XTypes 1.3 §7.4.3.4.1 places base members before derived members
/// on the wire, so the codec (encode/decode/keyHash) must serialize them in that
/// order — the emitted TS interface still declares only own members and inherits
/// the rest via `extends Base`. Base resolution is by simple name through
/// `TYPE_REG`; a seen-list bounds pathological inheritance cycles.
fn resolved_wire_members(s: &zerodds_idl::ast::StructDef) -> Vec<zerodds_idl::ast::Member> {
    let mut chain: Vec<zerodds_idl::ast::StructDef> = Vec::new();
    let mut seen: Vec<String> = Vec::new();
    let mut cur = s.base.clone();
    while let Some(bn) = cur {
        let Some(name) = bn.parts.last().map(|p| p.text.clone()) else {
            break;
        };
        if seen.contains(&name) {
            break;
        }
        seen.push(name.clone());
        let def = TYPE_REG.with(|r| match r.borrow().get(&name) {
            Some(ScopedKind::Struct { def, .. }) => Some(def.clone()),
            _ => None,
        });
        let Some(def) = def else {
            break;
        };
        cur = def.base.clone();
        chain.push(def);
    }
    // `chain` is [parent, grandparent, …]; reverse so the oldest ancestor leads.
    let mut out: Vec<zerodds_idl::ast::Member> = Vec::new();
    for def in chain.into_iter().rev() {
        out.extend(def.members.iter().cloned());
    }
    out.extend(s.members.iter().cloned());
    out
}

/// Dotted TS path for a scoped reference (`Module.Sub.Name`). Each
/// path segment is escaped so a reference to a keyword-named type
/// resolves to the same escaped name its definition emits under.
fn scoped_dotted(s: &ScopedName) -> String {
    s.parts
        .iter()
        .map(|p| escape_ts_ident(&p.text))
        .collect::<Vec<_>>()
        .join(".")
}

/// Dotted TS *value* path for a scoped reference used as a runtime
/// member access (e.g.\ an enum-literal reference `Kind.K_A`). Every
/// segment except the last is a namespace/type name (bare TS
/// identifier -> escaped); the last segment is a property access
/// (`Kind.class` is legal TS even though `class` is a keyword — see
/// `keywords.rs` docs), and must stay unescaped because it has to
/// match the *unescaped* object key the definition emitted it under.
fn scoped_dotted_value_access(s: &ScopedName) -> String {
    let n = s.parts.len();
    s.parts
        .iter()
        .enumerate()
        .map(|(i, p)| {
            if i + 1 == n {
                p.text.clone()
            } else {
                escape_ts_ident(&p.text)
            }
        })
        .collect::<Vec<_>>()
        .join(".")
}

/// `true` if the XCDR2 codec can be generated for this type. `fixed` and `any`
/// have no wire codec in any binding yet (cf. idl-java `typespec_supported`), so
/// a struct/union with such a member gets its data type but **no** TypeSupport —
/// rather than a codec that throws at runtime. (`map` is fully supported here.)
/// zerodds-lint: recursion-depth 64 (bounded by IDL nesting)
fn typespec_xcdr2_codecable(t: &TypeSpec) -> bool {
    match t {
        // fixed<P,S> now has a wire codec (CORBA-BCD via writeFixedBcd/readFixedBcd);
        // `any` still has none.
        TypeSpec::Fixed(_) => true,
        TypeSpec::Any => false,
        TypeSpec::Sequence(s) => typespec_xcdr2_codecable(&s.elem),
        TypeSpec::Map(m) => typespec_xcdr2_codecable(&m.key) && typespec_xcdr2_codecable(&m.value),
        TypeSpec::Scoped(s) => match lookup_scoped_kind(s) {
            Some(ScopedKind::Typedef(inner)) => typespec_xcdr2_codecable(&inner),
            // struct/union/enum/bitmask/bitset all have an XCDR2 codec.
            _ => true,
        },
        _ => true,
    }
}

/// Whether a struct's XCDR2 TypeSupport can be generated (all members codecable).
fn struct_xcdr2_codecable(s: &zerodds_idl::ast::StructDef) -> bool {
    s.members
        .iter()
        .all(|m| typespec_xcdr2_codecable(&m.type_spec))
}

/// Emits the write for a bitmask/bitset HOLDER of the given byte-width.
/// 1→writeOctet (uint8), 2→writeUint16, 4→writeUint32, 8→writeUint64.
/// The ≤4-byte surface type is `number`; the 8-byte holder is `bigint`
/// (so we cast through `bigint`). Matches `int_holder_read_expr`.
fn emit_int_holder_encode(out: &mut String, width: u8, expr: &str, indent: &str) {
    match width {
        1 => out.push_str(&alloc::format!(
            "{indent}w.writeOctet({expr} as unknown as number);\n"
        )),
        2 => out.push_str(&alloc::format!(
            "{indent}w.writeUint16({expr} as unknown as number);\n"
        )),
        8 => out.push_str(&alloc::format!(
            "{indent}w.writeUint64({expr} as unknown as bigint);\n"
        )),
        // width == 4 (default for 17..=32 bits) and any unexpected value.
        _ => out.push_str(&alloc::format!(
            "{indent}w.writeUint32({expr} as unknown as number);\n"
        )),
    }
}

/// Read expression for a bitmask/bitset HOLDER of the given byte-width,
/// symmetric with [`emit_int_holder_encode`].
fn int_holder_read_expr(width: u8) -> String {
    match width {
        1 => "r.readOctet() as unknown as never".into(),
        2 => "r.readUint16() as unknown as never".into(),
        8 => "r.readUint64() as unknown as never".into(),
        _ => "r.readUint32() as unknown as never".into(),
    }
}

/// Emits the write for a bitset member: pack each named bitfield into one
/// unsigned holder, then write the holder of `holder_bytes` width. A holder
/// ≤4 bytes packs with `number` bit-ops (`>>> 0` to stay unsigned); an 8-byte
/// holder packs with `BigInt`. Matches cdr-core `set_<field>` masks/shifts.
fn emit_bitset_encode(
    out: &mut String,
    holder_bytes: u8,
    fields: &[(String, u32, u32)],
    expr: &str,
    indent: &str,
) {
    if holder_bytes >= 8 {
        // 64-bit holder: BigInt arithmetic; fields >32 bits are `bigint`, ≤32
        // are `number` — coerce both via BigInt().
        let mut packed = String::from("0n");
        for (name, off, width) in fields {
            let mask = (1u128 << width) - 1;
            packed =
                alloc::format!("({packed} | ((BigInt(({expr}).{name}) & 0x{mask:x}n) << {off}n))");
        }
        out.push_str(&alloc::format!(
            "{indent}w.writeUint64(({packed}) as unknown as bigint);\n"
        ));
        return;
    }
    // ≤32-bit holder: number arithmetic, unsigned.
    let mut packed = String::from("0");
    for (name, off, width) in fields {
        let mask = (1u64 << width) - 1;
        packed = alloc::format!("({packed} | ((({expr}).{name} & 0x{mask:x}) << {off}))");
    }
    let write = match holder_bytes {
        1 => "writeOctet",
        2 => "writeUint16",
        _ => "writeUint32",
    };
    out.push_str(&alloc::format!("{indent}w.{write}(({packed}) >>> 0);\n"));
}

/// Read expression for a bitset member: read the packed holder, unpack each
/// named bitfield. Symmetric with [`emit_bitset_encode`]; produces an inline
/// IIFE returning the bitset struct literal.
fn bitset_read_expr(holder_bytes: u8, fields: &[(String, u32, u32)]) -> String {
    if holder_bytes >= 8 {
        let read = "r.readUint64()";
        let mut obj = String::new();
        for (i, (name, off, width)) in fields.iter().enumerate() {
            let mask = (1u128 << width) - 1;
            // A ≤32-bit field surfaces as `number`, >32-bit as `bigint`.
            if *width > 32 {
                obj.push_str(&alloc::format!("{name}: ((_h >> {off}n) & 0x{mask:x}n)"));
            } else {
                obj.push_str(&alloc::format!(
                    "{name}: Number((_h >> {off}n) & 0x{mask:x}n)"
                ));
            }
            if i + 1 < fields.len() {
                obj.push_str(", ");
            }
        }
        return alloc::format!(
            "((): never => {{ const _h = {read}; return {{ {obj} }} as unknown as never; }})()"
        );
    }
    let read = match holder_bytes {
        1 => "r.readOctet()",
        2 => "r.readUint16()",
        _ => "r.readUint32()",
    };
    let mut obj = String::new();
    for (i, (name, off, width)) in fields.iter().enumerate() {
        let mask = (1u64 << width) - 1;
        obj.push_str(&alloc::format!("{name}: ((_h >>> {off}) & 0x{mask:x})"));
        if i + 1 < fields.len() {
            obj.push_str(", ");
        }
    }
    alloc::format!(
        "((): never => {{ const _h = {read}; return {{ {obj} }} as unknown as never; }})()"
    )
}

/// zerodds-lint: recursion-depth 64 (bounded by IDL nesting)
fn emit_typespec_encode(
    out: &mut String,
    t: &TypeSpec,
    expr: &str,
    indent: &str,
) -> Result<(), IdlTsError> {
    match t {
        TypeSpec::Primitive(p) => match p {
            PrimitiveType::Boolean => {
                out.push_str(&alloc::format!("{indent}w.writeBool({expr});\n"));
            }
            PrimitiveType::Octet => {
                out.push_str(&alloc::format!("{indent}w.writeOctet({expr});\n"));
            }
            PrimitiveType::Char => {
                out.push_str(&alloc::format!("{indent}w.writeChar({expr});\n"));
            }
            PrimitiveType::WideChar => {
                out.push_str(&alloc::format!("{indent}w.writeWChar({expr});\n"));
            }
            PrimitiveType::Integer(i) => {
                let m = match i {
                    IntegerType::Short | IntegerType::Int16 => "writeInt16",
                    IntegerType::UShort | IntegerType::UInt16 => "writeUint16",
                    IntegerType::Long | IntegerType::Int32 => "writeInt32",
                    IntegerType::ULong | IntegerType::UInt32 => "writeUint32",
                    IntegerType::LongLong | IntegerType::Int64 => "writeInt64",
                    IntegerType::ULongLong | IntegerType::UInt64 => "writeUint64",
                    IntegerType::Int8 => "writeInt8",
                    IntegerType::UInt8 => "writeUint8",
                };
                out.push_str(&alloc::format!("{indent}w.{m}({expr});\n"));
            }
            PrimitiveType::Floating(f) => {
                match f {
                    FloatingType::Float => {
                        out.push_str(&alloc::format!("{indent}w.writeFloat32({expr});\n"));
                    }
                    FloatingType::Double => {
                        out.push_str(&alloc::format!("{indent}w.writeFloat64({expr});\n"));
                    }
                    FloatingType::LongDouble => {
                        // 16-byte opaque carrier — we simply write the
                        // `bytes` member raw (LongDouble.bytes : Uint8Array).
                        out.push_str(&alloc::format!("{indent}w.writeBytes(({expr}).bytes);\n"));
                    }
                };
            }
        },
        TypeSpec::String(StringType { wide, bound, .. }) => {
            // §7.6.2: a bounded string<N> over N chars must error, not corrupt.
            // The bound counts characters (code points), so compare against the
            // string's code-point length, not its UTF-16 `.length`.
            if let Some(n) = bound.as_ref().and_then(eval_const_int) {
                out.push_str(&alloc::format!(
                    "{indent}if ([...{expr}].length > {n}) {{ throw new RangeError(`bounded string over capacity {n}: ${{[...{expr}].length}}`); }}\n"
                ));
            }
            if *wide {
                out.push_str(&alloc::format!("{indent}w.writeWString({expr});\n"));
            } else {
                out.push_str(&alloc::format!("{indent}w.writeString({expr});\n"));
            }
        }
        TypeSpec::Sequence(seq) => {
            // XCDR2 §7.4.3.5: non-primitive elements (string, struct, …)
            // → DHEADER (uint32 = byte length of [count + elements]) in front;
            // primitives not. Cyclone-DDS-verified (V-5 without, V-6 with).
            //
            // Loop var + token names are suffixed by nesting depth (derived from
            // `indent`) so a `sequence<sequence<…>>` (or seq nested in a map
            // value) does NOT reuse `_e`/`_seqtok` — reuse produced
            // `for (const _e of _e)` and corrupted/crashed the encode.
            let d = next_encode_id();
            let elem_var = alloc::format!("_e{d}");
            let tok_var = alloc::format!("_seqtok{d}");
            // §7.6.2: a bounded sequence over its bound must error, not corrupt.
            if let Some(bound) = seq.bound.as_ref().and_then(eval_const_int) {
                out.push_str(&alloc::format!(
                    "{indent}if ({expr}.length > {bound}) {{ throw new RangeError(`bounded sequence over capacity {bound}: ${{{expr}.length}}`); }}\n"
                ));
            }
            let non_primitive = !matches!(&*seq.elem, TypeSpec::Primitive(_));
            if non_primitive {
                out.push_str(&alloc::format!(
                    "{indent}const {tok_var} = w.beginAppendable();\n"
                ));
            }
            out.push_str(&alloc::format!("{indent}w.writeUint32({expr}.length);\n"));
            out.push_str(&alloc::format!(
                "{indent}for (const {elem_var} of {expr}) {{\n"
            ));
            emit_typespec_encode(out, &seq.elem, &elem_var, &format!("{indent}    "))?;
            out.push_str(&alloc::format!("{indent}}}\n"));
            if non_primitive {
                out.push_str(&alloc::format!("{indent}w.endAppendable({tok_var});\n"));
            }
        }
        TypeSpec::Map(map) => {
            // XCDR2 MAP_TYPE (XTypes 1.3 §7.4.3.5.3 rule (15), §7.4.4.6):
            // `DHEADER + u32 count + (key, value)*`. The DHEADER (byte length
            // of [count + pairs]) frames the whole map — same as the cdr-core
            // `BTreeMap` `CdrEncode` impl (`crates/cdr/src/composite.rs`
            // `write_with_dheader` under `max_alignment() == XCDR2_MAX_ALIGNMENT`).
            //
            // Entries are emitted in KEY-SORTED order to match the cdr-core
            // reference (BTreeMap iteration is key-sorted, hence reproducible
            // and cross-PSM byte-identical). String keys sort by UTF-8 bytes
            // (BTreeMap `Ord` on `String`); numeric keys sort numerically.
            //
            // Depth-suffixed loop/sort vars (see Sequence above) keep nested
            // maps / map-in-seq from clobbering `_k`/`_v`.
            let d = next_encode_id();
            let k_var = alloc::format!("_k{d}");
            let v_var = alloc::format!("_v{d}");
            let entries_var = alloc::format!("_ment{d}");
            // §7.6.2: a bounded map over its bound must error, not corrupt.
            if let Some(bound) = map.bound.as_ref().and_then(eval_const_int) {
                out.push_str(&alloc::format!(
                    "{indent}if ({expr}.size > {bound}) {{ throw new RangeError(`bounded map over capacity {bound}: ${{{expr}.size}}`); }}\n"
                ));
            }
            // Key-sorted entry list. For string keys compare by UTF-8 bytes
            // (matches Rust `String` Ord); for numeric keys compare numerically.
            let key_is_string = matches!(&*map.key, TypeSpec::String(_));
            let cmp = if key_is_string {
                // Encode both keys to UTF-8 and compare byte-wise.
                "((a, b) => { const _ea = new TextEncoder().encode(String(a[0])); const _eb = new TextEncoder().encode(String(b[0])); const _m = Math.min(_ea.length, _eb.length); for (let _j = 0; _j < _m; _j++) { if (_ea[_j] !== _eb[_j]) return _ea[_j] - _eb[_j]; } return _ea.length - _eb.length; })"
            } else {
                "((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0))"
            };
            out.push_str(&alloc::format!(
                "{indent}const {entries_var} = [...{expr}].sort({cmp});\n"
            ));
            // XCDR2 §7.4.3.5: a map carries a DHEADER only when its element
            // (key,value pair) is NON-primitive — i.e. at least one of key/value
            // is non-primitive. `map<long,long>` (both primitive) gets NO DHEADER,
            // matching cdr-core `needs_collection_dheader(.., K::IS_PRIMITIVE &&
            // V::IS_PRIMITIVE)` and FastDDS/OpenDDS. (Mirrors arrays above.)
            let map_dheader =
                !(typespec_is_primitive(&map.key) && typespec_is_primitive(&map.value));
            let dtok_var = alloc::format!("_maptok{d}");
            if map_dheader {
                out.push_str(&alloc::format!(
                    "{indent}const {dtok_var} = w.beginAppendable();\n"
                ));
            }
            out.push_str(&alloc::format!(
                "{indent}w.writeUint32({entries_var}.length);\n"
            ));
            out.push_str(&alloc::format!(
                "{indent}for (const [{k_var}, {v_var}] of {entries_var}) {{\n"
            ));
            emit_typespec_encode(out, &map.key, &k_var, &format!("{indent}    "))?;
            emit_typespec_encode(out, &map.value, &v_var, &format!("{indent}    "))?;
            out.push_str(&alloc::format!("{indent}}}\n"));
            if map_dheader {
                out.push_str(&alloc::format!("{indent}w.endAppendable({dtok_var});\n"));
            }
        }
        TypeSpec::Scoped(s) => match lookup_scoped_kind(s) {
            // Nested struct → encode its body into the shared writer
            // (alignment stays relative to the outer CDR stream).
            Some(ScopedKind::Struct { .. }) => {
                out.push_str(&alloc::format!(
                    "{indent}{}TypeSupport.encodeInto(w, {expr});\n",
                    scoped_dotted(s)
                ));
            }
            // Nested union → encode via its emitted TypeSupport (shared writer).
            Some(ScopedKind::Union) => {
                out.push_str(&alloc::format!(
                    "{indent}{}TypeSupport.encodeInto(w, {expr});\n",
                    scoped_dotted(s)
                ));
            }
            // Enum → int32 of the ordinal. The TS surface type is a
            // string-literal union, so write the ordinal from the emitted
            // `<Enum>Ordinal` map, NOT a bare numeric cast (which corrupts it).
            Some(ScopedKind::Enum { holder_bytes }) => {
                let wm = match holder_bytes {
                    1 => "writeInt8",
                    2 => "writeInt16",
                    _ => "writeInt32",
                };
                out.push_str(&alloc::format!(
                    "{indent}w.{wm}({}Ordinal[{expr}]);\n",
                    scoped_dotted(s)
                ));
            }
            // Typedef → encode the aliased type.
            Some(ScopedKind::Typedef(inner)) => {
                emit_typespec_encode(out, &inner, expr, indent)?;
            }
            // bitmask → unsigned holder of the type's width (XTypes §7.4.5).
            // Width comes from the registry (cdr-core sizing), so a 3-value
            // bitmask is 1 byte, not int32. cf. `bits` golden (perm).
            Some(ScopedKind::IntLike(width)) => {
                emit_int_holder_encode(out, width, expr, indent);
            }
            // bitset → pack the named bitfields into one unsigned holder, then
            // write the holder of the type's width. cf. `bits` golden (flags).
            Some(ScopedKind::Bitset {
                holder_bytes,
                fields,
            }) => {
                emit_bitset_encode(out, holder_bytes, &fields, expr, indent);
            }
            // Unresolved ref (forward-declared / external) → 32-bit fallback.
            _ => {
                out.push_str(&alloc::format!(
                    "{indent}w.writeInt32({expr} as unknown as number);\n"
                ));
            }
        },
        // `any`/`fixed` have no XCDR2 wire codec yet; a struct containing one is
        // gated (no TypeSupport emitted), so these arms are unreachable — guard
        // them as a codegen error rather than emitting code that throws at runtime.
        TypeSpec::Any => {
            return Err(IdlTsError::Unsupported(
                "XCDR2 encode for `any` member is not supported".into(),
            ));
        }
        TypeSpec::Fixed(f) => {
            // fixed<P,S>: CORBA/GIOP §9.3.2.7 packed BCD (the decimal `string`
            // field -> (P+2)/2 octets via the runtime helper). No alignment, no
            // length prefix, endian-independent.
            let p = eval_const_int(&f.digits).unwrap_or(0);
            let s = eval_const_int(&f.scale).unwrap_or(0);
            out.push_str(&alloc::format!(
                "{indent}w.writeFixedBcd({expr}, {p}, {s});\n"
            ));
        }
    }
    Ok(())
}

/// Generates the decode body. Returns a type object.
fn emit_struct_decode_body(
    out: &mut String,
    s: &zerodds_idl::ast::StructDef,
    indent: &str,
) -> Result<(), IdlTsError> {
    let extensibility = struct_extensibility(&s.annotations);
    let name = escape_ts_ident(&s.name.text);
    let name = &name;
    // Base-class members precede own members on the wire (XTypes §7.4.3.4.1).
    let zd_members = resolved_wire_members(s);

    match extensibility {
        "final" => {
            // Sequenzielles Lesen.
            for m in &zd_members {
                emit_member_decode_decl(out, m, indent)?;
            }
            emit_decode_return(out, s, indent, name)?;
        }
        "appendable" => {
            out.push_str(&alloc::format!(
                "{indent}const _tok = r.beginAppendable();\n"
            ));
            for m in &zd_members {
                emit_member_decode_decl(out, m, indent)?;
            }
            out.push_str(&alloc::format!("{indent}r.endAppendable(_tok);\n"));
            emit_decode_return(out, s, indent, name)?;
        }
        "mutable" => {
            // Default initialization; fields are set via the EMHEADER loop.
            for m in &zd_members {
                let optional = has_annotation(&m.annotations, "optional");
                let base_ts = typespec_to_ts(&m.type_spec)?;
                for d in &m.declarators {
                    let field = d.name().text.clone();
                    let is_array = matches!(d, zerodds_idl::ast::Declarator::Array(_));
                    let init = if optional {
                        "undefined".into()
                    } else if is_array {
                        // A fixed array defaults to an empty `Array<…>`.
                        "[] as unknown as undefined".into()
                    } else {
                        default_init_for(&m.type_spec)
                    };
                    let ts_ty = wrap_with_array_dimensions(&base_ts, d);
                    out.push_str(&alloc::format!(
                        "{indent}let _f_{field}: {ts_ty} | undefined = {init};\n"
                    ));
                }
            }
            // XCDR1 (classic CDR): @mutable is PL_CDR1 — a [PID][length] list with
            // no outer DHEADER, each member body member-relative aligned. Emit it
            // alongside the XCDR2 EMHEADER loop, gated on the reader representation.
            out.push_str(&alloc::format!("{indent}if (r.isXcdr1) {{\n"));
            out.push_str(&alloc::format!(
                "{indent}    let _plm: {{ memberId: number; bodyEnd: number }} | null;\n"
            ));
            out.push_str(&alloc::format!(
                "{indent}    while ((_plm = r.beginPlCdr1Member()) !== null) {{\n"
            ));
            out.push_str(&alloc::format!(
                "{indent}        switch (_plm.memberId) {{\n"
            ));
            {
                let mut next_id1: i64 = 0;
                for m in &zd_members {
                    let id_override = ts_member_id_override(s, m);
                    let base_ts = typespec_to_ts(&m.type_spec)?;
                    for d in &m.declarators {
                        let id = id_override.unwrap_or(next_id1);
                        next_id1 = id + 1;
                        let field = d.name().text.clone();
                        let ts_ty = wrap_with_array_dimensions(&base_ts, d);
                        out.push_str(&alloc::format!("{indent}        case {id}: {{\n"));
                        out.push_str(&alloc::format!("{indent}            const _v: {ts_ty} = "));
                        let read_expr = read_declarator_expr(&m.type_spec, d, &base_ts)?;
                        out.push_str(&alloc::format!("{read_expr};\n"));
                        out.push_str(&alloc::format!("{indent}            _f_{field} = _v;\n"));
                        out.push_str(&alloc::format!("{indent}            break;\n"));
                        out.push_str(&alloc::format!("{indent}        }}\n"));
                    }
                }
            }
            out.push_str(&alloc::format!("{indent}        default: break;\n"));
            out.push_str(&alloc::format!("{indent}        }}\n"));
            out.push_str(&alloc::format!(
                "{indent}        r.endPlCdr1Member(_plm);\n"
            ));
            out.push_str(&alloc::format!("{indent}    }}\n"));
            out.push_str(&alloc::format!("{indent}}} else {{\n"));
            out.push_str(&alloc::format!("{indent}const _tok = r.beginMutable();\n"));
            out.push_str(&alloc::format!("{indent}while (r.pos < _tok.bodyEnd) {{\n"));
            out.push_str(&alloc::format!(
                "{indent}    const _emh = r.readEmHeader();\n"
            ));
            out.push_str(&alloc::format!("{indent}    switch (_emh.memberId) {{\n"));
            let mut next_id: i64 = 0;
            for m in &zd_members {
                let id_override = ts_member_id_override(s, m);
                let base_ts = typespec_to_ts(&m.type_spec)?;
                for d in &m.declarators {
                    let id = id_override.unwrap_or(next_id);
                    next_id = id + 1;
                    let field = d.name().text.clone();
                    let is_array = matches!(d, zerodds_idl::ast::Declarator::Array(_));
                    out.push_str(&alloc::format!("{indent}        case {id}: {{\n"));
                    // EMHEADER+NEXTINT-Skip:
                    // - Primitives (LC=0..3 inline) need nothing.
                    // - LC=3 for a non-primitive member carries NEXTINT
                    //   after the EMHEADER (zerodds-xcdr2-bindings-
                    //   conformance-1.0 §6 V-10) — we discard it because
                    //   read_typespec_expr reads the body directly.
                    // - A fixed-array member is always written in the LC=3
                    //   NEXTINT form (TS-cluster #2), never inline.
                    // - LC>=4 is already consumed in readEmHeader.
                    if is_array || primitive_lc_inline(&m.type_spec).is_none() {
                        out.push_str(&alloc::format!(
                            "{indent}            if (_emh.lc === 3) {{ r.readUint32(); }}\n"
                        ));
                    }
                    let ts_ty = wrap_with_array_dimensions(&base_ts, d);
                    out.push_str(&alloc::format!("{indent}            const _v: {ts_ty} = "));
                    let read_expr = read_declarator_expr(&m.type_spec, d, &base_ts)?;
                    out.push_str(&alloc::format!("{read_expr};\n"));
                    out.push_str(&alloc::format!("{indent}            _f_{field} = _v;\n"));
                    out.push_str(&alloc::format!("{indent}            break;\n"));
                    out.push_str(&alloc::format!("{indent}        }}\n"));
                }
            }
            out.push_str(&alloc::format!("{indent}        default: {{\n"));
            out.push_str(&alloc::format!(
                "{indent}            // Skip unknown member per XTypes \u{00A7}7.4.2.\n"
            ));
            out.push_str(&alloc::format!(
                "{indent}            if (_emh.nextInt !== null) {{ r.readBytes(_emh.nextInt); }}\n"
            ));
            out.push_str(&alloc::format!(
                "{indent}            else if (_emh.lc >= 5) {{ const _len = r.readUint32(); r.readBytes(_len); }}\n"
            ));
            out.push_str(&alloc::format!(
                "{indent}            else {{ const _sz = Xcdr2Reader.lcInlineSize(_emh.lc); if (_sz > 0) r.readBytes(_sz); }}\n"
            ));
            out.push_str(&alloc::format!("{indent}            break;\n"));
            out.push_str(&alloc::format!("{indent}        }}\n"));
            out.push_str(&alloc::format!("{indent}    }}\n"));
            out.push_str(&alloc::format!("{indent}}}\n"));
            out.push_str(&alloc::format!("{indent}r.endMutable(_tok);\n"));
            out.push_str(&alloc::format!("{indent}}}\n")); // close `else` (XCDR2 path)
            // Build the return object from _f_* variables.
            out.push_str(&alloc::format!("{indent}return {{\n"));
            for m in &zd_members {
                let optional = has_annotation(&m.annotations, "optional");
                let base_ts = typespec_to_ts(&m.type_spec)?;
                for d in &m.declarators {
                    let field = d.name().text.clone();
                    if optional {
                        out.push_str(&alloc::format!("{indent}    {field}: _f_{field},\n"));
                    } else {
                        out.push_str(&alloc::format!(
                            "{indent}    {field}: _f_{field} as {},\n",
                            wrap_with_array_dimensions(&base_ts, d)
                        ));
                    }
                }
            }
            out.push_str(&alloc::format!("{indent}}};\n"));
        }
        // Decoder-Path: extensibility-Variants are exhaustive over
        // Final/Appendable/Mutable. Unknown -> graceful no-op.
        _ => {}
    }
    Ok(())
}

/// Returns the TS default initial value for a TypeSpec.
fn default_init_for(t: &TypeSpec) -> String {
    match t {
        TypeSpec::Primitive(p) => match p {
            PrimitiveType::Boolean => "false".into(),
            PrimitiveType::Integer(i) => match i {
                IntegerType::LongLong
                | IntegerType::ULongLong
                | IntegerType::Int64
                | IntegerType::UInt64 => "0n".into(),
                _ => "0".into(),
            },
            PrimitiveType::Octet
            | PrimitiveType::Floating(_)
            | PrimitiveType::Char
            | PrimitiveType::WideChar => "0 as unknown as undefined".into(),
        },
        TypeSpec::String(_) => "\"\"".into(),
        TypeSpec::Sequence(_) | TypeSpec::Map(_) => "[] as unknown as undefined".into(),
        _ => "undefined".into(),
    }
}

/// Produces a `const _f_<name>: T = <readExpr>;` line for final/appendable.
fn emit_member_decode_decl(
    out: &mut String,
    m: &zerodds_idl::ast::Member,
    indent: &str,
) -> Result<(), IdlTsError> {
    let optional = has_annotation(&m.annotations, "optional");
    let base_ts = typespec_to_ts(&m.type_spec)?;
    for d in &m.declarators {
        let field = d.name().text.clone();
        // TS-cluster #2: a fixed-array declarator widens the member type to
        // `Array<…>` per dimension and reads element-by-element with no length
        // prefix — mirror the declared shape.
        let ts_ty = wrap_with_array_dimensions(&base_ts, d);
        if optional {
            out.push_str(&alloc::format!(
                "{indent}const _present_{field} = r.readOctet();\n"
            ));
            out.push_str(&alloc::format!(
                "{indent}const _f_{field}: {ts_ty} | undefined = _present_{field} === 1 ? "
            ));
            let expr = read_declarator_expr(&m.type_spec, d, &base_ts)?;
            out.push_str(&alloc::format!("{expr} : undefined;\n"));
        } else {
            out.push_str(&alloc::format!("{indent}const _f_{field}: {ts_ty} = "));
            let expr = read_declarator_expr(&m.type_spec, d, &base_ts)?;
            out.push_str(&alloc::format!("{expr};\n"));
        }
    }
    Ok(())
}

/// Returns the read-expression for a struct member honouring the declarator's
/// fixed-array dimensions (TS-cluster #2). `Declarator::Simple` falls through to
/// `read_typespec_expr`; a fixed array builds nested IIFE loops that read
/// exactly the declared count per dimension (no length prefix).
fn read_declarator_expr(
    t: &TypeSpec,
    d: &zerodds_idl::ast::Declarator,
    base_ts: &str,
) -> Result<String, IdlTsError> {
    use zerodds_idl::ast::Declarator;
    match d {
        Declarator::Simple(_) => read_typespec_expr(t),
        Declarator::Array(arr) => read_array_dim_expr(t, &arr.sizes, base_ts, 0),
    }
}

/// Builds the nested fixed-count read IIFE for `sizes[dim..]`.
///
/// zerodds-lint: recursion-depth 16 (array dimension count)
fn read_array_dim_expr(
    t: &TypeSpec,
    sizes: &[zerodds_idl::ast::ConstExpr],
    base_ts: &str,
    dim: usize,
) -> Result<String, IdlTsError> {
    if dim >= sizes.len() {
        return read_typespec_expr(t);
    }
    let n = eval_const_int(&sizes[dim]).ok_or_else(|| {
        IdlTsError::Unsupported(alloc::format!(
            "fixed-array dimension {dim} is not a constant integer"
        ))
    })?;
    // The element TS type at this depth is `base` wrapped by the remaining dims.
    let mut elem_ts = base_ts.to_string();
    for _ in (dim + 1)..sizes.len() {
        elem_ts = alloc::format!("Array<{elem_ts}>");
    }
    let inner = read_array_dim_expr(t, sizes, base_ts, dim + 1)?;
    // Symmetric with the encode side: consume a DHEADER when the element at
    // this dimension is non-primitive (`beginAppendable`/`endAppendable`).
    if array_dim_needs_dheader(t, sizes, dim) {
        Ok(alloc::format!(
            "((): Array<{elem_ts}> => {{ const _adt = r.beginAppendable(); const _o: Array<{elem_ts}> = []; for (let _i = 0; _i < {n}; _i++) {{ _o.push({inner}); }} r.endAppendable(_adt); return _o; }})()"
        ))
    } else {
        Ok(alloc::format!(
            "((): Array<{elem_ts}> => {{ const _o: Array<{elem_ts}> = []; for (let _i = 0; _i < {n}; _i++) {{ _o.push({inner}); }} return _o; }})()"
        ))
    }
}

/// Generates the `return { ... }` statement from the `_f_*` variables.
fn emit_decode_return(
    out: &mut String,
    s: &zerodds_idl::ast::StructDef,
    indent: &str,
    name: &str,
) -> Result<(), IdlTsError> {
    // Inherited (base-class) fields ARE decoded now — `resolved_wire_members`
    // walks `s.base`, and the final/appendable decode declares `_f_<field>` for
    // each base member before this return (XTypes §7.4.3.4.1). The object literal
    // therefore carries every field of `<Name>` (own + inherited via `extends`),
    // so no `as unknown as <Name>` cast is required.
    let _ = name;
    out.push_str(&alloc::format!("{indent}return {{\n"));
    for m in &resolved_wire_members(s) {
        for d in &m.declarators {
            let field = d.name().text.clone();
            out.push_str(&alloc::format!("{indent}    {field}: _f_{field},\n"));
        }
    }
    out.push_str(&alloc::format!("{indent}}};\n"));
    Ok(())
}
/// zerodds-lint: recursion-depth 64 (read_typespec_expr bounded by AST depth)
/// Returns the TS read-expression string for a TypeSpec.
fn read_typespec_expr(t: &TypeSpec) -> Result<String, IdlTsError> {
    Ok(match t {
        TypeSpec::Primitive(p) => match p {
            PrimitiveType::Boolean => "r.readBool()".into(),
            PrimitiveType::Octet => "r.readOctet()".into(),
            PrimitiveType::Char => "r.readChar()".into(),
            PrimitiveType::WideChar => "r.readWChar()".into(),
            PrimitiveType::Integer(i) => {
                let m = match i {
                    IntegerType::Short | IntegerType::Int16 => "readInt16",
                    IntegerType::UShort | IntegerType::UInt16 => "readUint16",
                    IntegerType::Long | IntegerType::Int32 => "readInt32",
                    IntegerType::ULong | IntegerType::UInt32 => "readUint32",
                    IntegerType::LongLong | IntegerType::Int64 => "readInt64",
                    IntegerType::ULongLong | IntegerType::UInt64 => "readUint64",
                    IntegerType::Int8 => "readInt8",
                    IntegerType::UInt8 => "readUint8",
                };
                alloc::format!("r.{m}()")
            }
            PrimitiveType::Floating(f) => match f {
                FloatingType::Float => "r.readFloat32()".into(),
                FloatingType::Double => "r.readFloat64()".into(),
                FloatingType::LongDouble => {
                    "(makeLongDouble(r.readBytes(16)) as unknown as never)".into()
                }
            },
        },
        TypeSpec::String(StringType { wide, bound, .. }) => {
            let read = if *wide {
                "r.readWString()"
            } else {
                "r.readString()"
            };
            // B1 follow-up (#22 decode-side parity): mirror the encode-side
            // bound check (`emit_typespec_encode` above, §7.6.2) on decode
            // too — XTypes 1.3 §7.4.3 requires the IDL bound enforced on
            // BOTH sides, not just the wire's remaining-byte validation
            // `r.readString()`/`r.readWString()` already do. Counts code
            // points (`[...s].length`), matching the encode-side check
            // exactly (byte-golden: accepts exactly what encode accepts).
            if let Some(n) = bound.as_ref().and_then(eval_const_int) {
                alloc::format!(
                    "((): string => {{ const _bs = {read}; if ([..._bs].length > {n}) {{ throw new RangeError(`decoded string over capacity {n}: ${{[..._bs].length}}`); }} return _bs; }})()"
                )
            } else {
                read.into()
            }
        }
        TypeSpec::Sequence(seq) => {
            let elem_ts = typespec_to_ts(&seq.elem)?;
            let elem_read = read_typespec_expr(&seq.elem)?;
            // B1 follow-up (#22 decode-side parity): mirror the encode-side
            // bound check — XTypes 1.3 §7.4.3.
            let bound_check = match seq.bound.as_ref().and_then(eval_const_int) {
                Some(bound) => alloc::format!(
                    "if (_n > {bound}) {{ throw new RangeError(`decoded sequence over capacity {bound}: ${{_n}}`); }} "
                ),
                None => String::new(),
            };
            // XCDR2 §7.4.3.5: for non-primitive elements skip the DHEADER.
            if !matches!(&*seq.elem, TypeSpec::Primitive(_)) {
                alloc::format!(
                    "((): Array<{elem_ts}> => {{ const _t = r.beginAppendable(); const _n = r.readUint32(); {bound_check}const _o: Array<{elem_ts}> = []; for (let _i = 0; _i < _n; _i++) {{ _o.push({elem_read}); }} r.endAppendable(_t); return _o; }})()"
                )
            } else {
                alloc::format!(
                    "((): Array<{elem_ts}> => {{ const _n = r.readUint32(); {bound_check}const _o: Array<{elem_ts}> = []; for (let _i = 0; _i < _n; _i++) {{ _o.push({elem_read}); }} return _o; }})()"
                )
            }
        }
        TypeSpec::Map(map) => {
            // XCDR2 §7.4.3.5: the map is framed by a DHEADER ONLY when its
            // (key,value) element is non-primitive. A `map<long,long>` (both
            // primitive) has NO DHEADER — read count + pairs directly. Matches
            // the encode side above + cdr-core `needs_collection_dheader`.
            let k_ts = typespec_to_ts(&map.key)?;
            let v_ts = typespec_to_ts(&map.value)?;
            let k_read = read_typespec_expr(&map.key)?;
            let v_read = read_typespec_expr(&map.value)?;
            let map_dheader =
                !(typespec_is_primitive(&map.key) && typespec_is_primitive(&map.value));
            // B1 follow-up (#22 decode-side parity): mirror the encode-side
            // bound check — XTypes 1.3 §7.4.3.
            let bound_check = match map.bound.as_ref().and_then(eval_const_int) {
                Some(bound) => alloc::format!(
                    "if (_n > {bound}) {{ throw new RangeError(`decoded map over capacity {bound}: ${{_n}}`); }} "
                ),
                None => String::new(),
            };
            if map_dheader {
                alloc::format!(
                    "((): ReadonlyMap<{k_ts}, {v_ts}> => {{ const _mt = r.beginAppendable(); const _n = r.readUint32(); {bound_check}const _o = new Map<{k_ts}, {v_ts}>(); for (let _i = 0; _i < _n; _i++) {{ const _k = {k_read}; const _v = {v_read}; _o.set(_k, _v); }} r.endAppendable(_mt); return _o; }})()"
                )
            } else {
                alloc::format!(
                    "((): ReadonlyMap<{k_ts}, {v_ts}> => {{ const _n = r.readUint32(); {bound_check}const _o = new Map<{k_ts}, {v_ts}>(); for (let _i = 0; _i < _n; _i++) {{ const _k = {k_read}; const _v = {v_read}; _o.set(_k, _v); }} return _o; }})()"
                )
            }
        }
        TypeSpec::Scoped(s) => match lookup_scoped_kind(s) {
            // Nested struct → decode its body from the shared reader.
            Some(ScopedKind::Struct { .. }) => {
                alloc::format!("{}TypeSupport.decodeFrom(r)", scoped_dotted(s))
            }
            // Nested union → decode via its emitted TypeSupport.
            Some(ScopedKind::Union) => {
                alloc::format!("{}TypeSupport.decodeFrom(r)", scoped_dotted(s))
            }
            // Enum → read the int32 ordinal and map it back to the string member
            // via the emitted `<Enum>FromOrdinal` map (cf. encode).
            Some(ScopedKind::Enum { holder_bytes }) => {
                let rm = match holder_bytes {
                    1 => "readInt8",
                    2 => "readInt16",
                    _ => "readInt32",
                };
                alloc::format!(
                    "({}FromOrdinal.get(r.{rm}()) as {})",
                    scoped_dotted(s),
                    scoped_dotted(s)
                )
            }
            // Typedef → decode the aliased type.
            Some(ScopedKind::Typedef(inner)) => read_typespec_expr(&inner)?,
            // bitmask → unsigned holder of the type's width (XTypes §7.4.5),
            // symmetric with `emit_int_holder_encode`.
            Some(ScopedKind::IntLike(width)) => int_holder_read_expr(width),
            // bitset → read the packed unsigned holder, then unpack each named
            // bitfield, symmetric with `emit_bitset_encode`.
            Some(ScopedKind::Bitset {
                holder_bytes,
                fields,
            }) => bitset_read_expr(holder_bytes, &fields),
            // Unresolved ref (forward-declared / external) → 32-bit fallback.
            _ => "r.readInt32() as unknown as never".into(),
        },
        // `any`/`fixed`: unreachable (a containing struct is gated); guard as a
        // codegen error rather than emitting runtime-throwing decode code.
        TypeSpec::Any => {
            return Err(IdlTsError::Unsupported(
                "XCDR2 decode for `any` member is not supported".into(),
            ));
        }
        TypeSpec::Fixed(f) => {
            // fixed<P,S>: read (P+2)/2 packed-BCD octets back into the decimal
            // `string` field via the runtime helper.
            let p = eval_const_int(&f.digits).unwrap_or(0);
            let s = eval_const_int(&f.scale).unwrap_or(0);
            alloc::format!("r.readFixedBcd({p}, {s})")
        }
    })
}

/// Writes only the `@key` fields in big-endian mode
/// (PlainCdr2BeKeyHolder per XTypes §7.6.8).
fn emit_struct_keyhash_body(
    out: &mut String,
    s: &zerodds_idl::ast::StructDef,
    indent: &str,
) -> Result<(), IdlTsError> {
    // XTypes 1.3 §7.6.8.3.1.b: KeyHolder members in ascending member-id
    // order (explicit `@id(N)`, else positional index among the `@key`
    // members) — NOT declaration order.
    // Base-class @key members contribute to the derived type's KeyHash and are
    // ordered before the derived @key members (XTypes §7.4.3.4.1 + §7.6.8).
    let zd_all_members = resolved_wire_members(s);
    let key_members: Vec<&zerodds_idl::ast::Member> = zd_all_members
        .iter()
        .filter(|m| has_annotation(&m.annotations, "key"))
        .collect();
    for m in sort_members_by_id(&key_members) {
        for d in &m.declarators {
            let field = d.name().text.clone();
            emit_key_declarator_encode(
                out,
                &m.type_spec,
                d,
                &alloc::format!("s.{field}"),
                indent,
                0,
            )?;
        }
    }
    Ok(())
}

/// Sorts `members` into ascending member-id order (explicit `@id(N)`, else
/// positional index within `members`) — XTypes 1.3 §7.6.8.3.1.b. Mirrors
/// `idl-rust`'s `emit_key_holder_be` fallback convention (the index is taken
/// within the already-filtered `@key` list, matching the cross-vendor-
/// validated reference), and the same convention this file already uses for
/// `@mutable` EMHEADER auto-id assignment (`annotation_int_value(.., "id")`).
fn sort_members_by_id<'a>(
    members: &[&'a zerodds_idl::ast::Member],
) -> Vec<&'a zerodds_idl::ast::Member> {
    let mut ordered: Vec<(i64, &zerodds_idl::ast::Member)> = members
        .iter()
        .enumerate()
        .map(|(idx, m)| {
            (
                annotation_int_value(&m.annotations, "id").unwrap_or(idx as i64),
                *m,
            )
        })
        .collect();
    ordered.sort_by_key(|(id, _)| *id);
    ordered.into_iter().map(|(_, m)| m).collect()
}

/// KeyHash-specific declarator writer: identical to `emit_declarator_encode`
/// for array dims (out of scope — the investigation found sequence/array
/// `@key` shapes already correct via the generic per-field encoder), but at
/// the scalar leaf delegates to `emit_key_typespec_encode` instead of
/// `emit_typespec_encode`, so a nested `@key` struct expands to its own
/// `@key` subset instead of being fully encoded.
///
/// zerodds-lint: recursion-depth 64 (codegen AST walk; bounded by IDL nesting).
fn emit_key_declarator_encode(
    out: &mut String,
    t: &TypeSpec,
    d: &zerodds_idl::ast::Declarator,
    expr: &str,
    indent: &str,
    dim: usize,
) -> Result<(), IdlTsError> {
    use zerodds_idl::ast::Declarator;
    match d {
        Declarator::Simple(_) => emit_key_typespec_encode(out, t, expr, indent),
        Declarator::Array(arr) => emit_key_array_dim_encode(out, t, &arr.sizes, expr, indent, dim),
    }
}

/// KeyHash-specific counterpart of `emit_array_dim_encode`: identical
/// dimension-loop framing, but the innermost element write goes through
/// `emit_key_typespec_encode`.
/// zerodds-lint: recursion-depth 16 (array dimension count)
fn emit_key_array_dim_encode(
    out: &mut String,
    t: &TypeSpec,
    sizes: &[zerodds_idl::ast::ConstExpr],
    expr: &str,
    indent: &str,
    dim: usize,
) -> Result<(), IdlTsError> {
    if dim >= sizes.len() {
        return emit_key_typespec_encode(out, t, expr, indent);
    }
    let n = eval_const_int(&sizes[dim]).ok_or_else(|| {
        IdlTsError::Unsupported(alloc::format!(
            "fixed-array dimension {dim} is not a constant integer"
        ))
    })?;
    let dheader = array_dim_needs_dheader(t, sizes, dim);
    let atok = alloc::format!("_atok{}", next_encode_id());
    if dheader {
        out.push_str(&alloc::format!(
            "{indent}const {atok} = w.beginAppendable();\n"
        ));
    }
    let idx = alloc::format!("_a{dim}");
    let elem = alloc::format!("{expr}[{idx}]");
    out.push_str(&alloc::format!(
        "{indent}for (let {idx} = 0; {idx} < {n}; {idx}++) {{\n"
    ));
    emit_key_array_dim_encode(out, t, sizes, &elem, &format!("{indent}    "), dim + 1)?;
    out.push_str(&alloc::format!("{indent}}}\n"));
    if dheader {
        out.push_str(&alloc::format!("{indent}w.endAppendable({atok});\n"));
    }
    Ok(())
}

/// KeyHash-specific value writer (XTypes 1.3 §7.6.8). For a `Scoped`
/// reference that resolves (after dealiasing any typedef chain — see the
/// `Typedef` arm below) to a nested struct, expands to that struct's own
/// `@key` subset (or ALL its members if it declares none — XTypes 1.3
/// §7.6.8: a keyless aggregate is keyed in full), in member-id order,
/// instead of delegating to `<Type>TypeSupport.encodeInto(...)` (which —
/// correct for normal, non-key encoding — writes the WHOLE nested struct).
/// Every other shape (primitive, string, sequence, map, enum, bitmask,
/// bitset, union, fixed) is unchanged from — and delegates verbatim to —
/// the general `emit_typespec_encode`: the investigation found those
/// already correct via the existing generic per-field encoder.
/// zerodds-lint: recursion-depth 16
fn emit_key_typespec_encode(
    out: &mut String,
    t: &TypeSpec,
    expr: &str,
    indent: &str,
) -> Result<(), IdlTsError> {
    if let TypeSpec::Scoped(s) = t {
        match lookup_scoped_kind(s) {
            // A `@key` member whose declared type is a typedef must dealias
            // BEFORE the nested-struct check below can even see the struct:
            // `typedef Inner InnerAlias; struct Outer { @key InnerAlias i; }`
            // previously fell straight through to the generic
            // `emit_typespec_encode` fallback (this match only recognised
            // `ScopedKind::Struct` directly), which writes the WHOLE nested
            // struct via `InnerTypeSupport.encodeInto(...)` instead of just
            // its own `@key` subset — the same class of over-inclusion bug
            // as FINDING #20. Unlike the Java backend's typedef wrapper
            // class, a TS typedef is a pure structural type alias — `expr`
            // already has the underlying shape at runtime, so just recurse
            // on the aliased type with the SAME `expr` (mirrors the general
            // encoder's `ScopedKind::Typedef` arm).
            Some(ScopedKind::Typedef(inner)) => {
                return emit_key_typespec_encode(out, &inner, expr, indent);
            }
            Some(ScopedKind::Struct { def, .. }) => {
                let nested_keys: Vec<&zerodds_idl::ast::Member> = def
                    .members
                    .iter()
                    .filter(|m| has_annotation(&m.annotations, "key"))
                    .collect();
                let effective: Vec<&zerodds_idl::ast::Member> = if nested_keys.is_empty() {
                    def.members.iter().collect()
                } else {
                    nested_keys
                };
                for m in sort_members_by_id(&effective) {
                    for d in &m.declarators {
                        // Arrays inside a nested-struct key are out of the
                        // proof scope; reject explicitly rather than
                        // silently DHEADER-framing a per-element encode of
                        // the array (which `emit_key_declarator_encode`
                        // would otherwise do unchanged, mixing DHEADER
                        // framing into a KeyHolder that must always be the
                        // FLAT concatenation of key bytes — XTypes 1.3
                        // §7.6.8). Matches every other backend's identical
                        // rejection of this shape (e.g. `idl-rust`'s
                        // `emit_key_field_write`, `idl-cpp`'s
                        // `emit_key_value_write`, `idl-go`'s
                        // `emit_key_struct_member`). A top-level `@key`
                        // array field of this struct's OWN declarator is
                        // unaffected — those dims are consumed by
                        // `emit_key_declarator_encode` before this Struct
                        // arm is ever reached.
                        if matches!(d, zerodds_idl::ast::Declarator::Array(_)) {
                            return Err(IdlTsError::Unsupported(alloc::format!(
                                "array @key field '{}' inside a nested-struct key",
                                d.name().text
                            )));
                        }
                        let field = d.name().text.clone();
                        emit_key_declarator_encode(
                            out,
                            &m.type_spec,
                            d,
                            &alloc::format!("{expr}.{field}"),
                            indent,
                            0,
                        )?;
                    }
                }
                return Ok(());
            }
            _ => {}
        }
    }
    emit_typespec_encode(out, t, expr, indent)
}

/// Renders a `DdsTypeRef` literal as a TypeScript object expression
/// for a given IDL `TypeSpec`. Used inside descriptor emission.
///
/// zerodds-lint: recursion-depth 16 (type composition depth)
fn typespec_to_typeref_literal(t: &TypeSpec) -> String {
    match t {
        TypeSpec::Primitive(p) => {
            let prim = primitive_to_typeref_name(p);
            alloc::format!("{{ kind: \"primitive\", name: \"{prim}\" }}")
        }
        TypeSpec::String(StringType { wide, bound, .. }) => match bound {
            Some(b) => match eval_const_int(b) {
                Some(n) => alloc::format!("{{ kind: \"string\", bound: {n}, wide: {wide} }}"),
                None => alloc::format!("{{ kind: \"string\", wide: {wide} }}"),
            },
            None => alloc::format!("{{ kind: \"string\", wide: {wide} }}"),
        },
        TypeSpec::Sequence(seq) => {
            let elem = typespec_to_typeref_literal(&seq.elem);
            match &seq.bound {
                Some(b) => match eval_const_int(b) {
                    Some(n) => {
                        alloc::format!("{{ kind: \"sequence\", element: {elem}, bound: {n} }}")
                    }
                    None => alloc::format!("{{ kind: \"sequence\", element: {elem} }}"),
                },
                None => alloc::format!("{{ kind: \"sequence\", element: {elem} }}"),
            }
        }
        TypeSpec::Map(m) => {
            let k = typespec_to_typeref_literal(&m.key);
            let v = typespec_to_typeref_literal(&m.value);
            match &m.bound {
                Some(b) => match eval_const_int(b) {
                    Some(n) => {
                        alloc::format!("{{ kind: \"map\", key: {k}, value: {v}, bound: {n} }}")
                    }
                    None => alloc::format!("{{ kind: \"map\", key: {k}, value: {v} }}"),
                },
                None => alloc::format!("{{ kind: \"map\", key: {k}, value: {v} }}"),
            }
        }
        TypeSpec::Scoped(s) => {
            let qname = s
                .parts
                .iter()
                .map(|p| p.text.clone())
                .collect::<Vec<_>>()
                .join("::");
            alloc::format!("{{ kind: \"ref\", name: \"{qname}\" }}")
        }
        TypeSpec::Any => "{ kind: \"any\" }".into(),
        TypeSpec::Fixed(_) => "{ kind: \"primitive\", name: \"int64\" }".into(),
    }
}

fn primitive_to_typeref_name(p: &PrimitiveType) -> &'static str {
    match p {
        PrimitiveType::Boolean => "boolean",
        PrimitiveType::Char => "char",
        PrimitiveType::WideChar => "wchar",
        PrimitiveType::Octet => "octet",
        PrimitiveType::Integer(i) => match i {
            IntegerType::Short | IntegerType::Int16 => "int16",
            IntegerType::UShort | IntegerType::UInt16 => "uint16",
            IntegerType::Long | IntegerType::Int32 => "int32",
            IntegerType::ULong | IntegerType::UInt32 => "uint32",
            IntegerType::LongLong | IntegerType::Int64 => "int64",
            IntegerType::ULongLong | IntegerType::UInt64 => "uint64",
            IntegerType::Int8 => "int16",
            IntegerType::UInt8 => "uint16",
        },
        PrimitiveType::Floating(f) => match f {
            FloatingType::Float => "float",
            FloatingType::Double => "double",
            FloatingType::LongDouble => "longDouble",
        },
    }
}

/// IDL §7.4.5 Union → TypeScript discriminated-union (algebraic data type).
///
/// Example:
/// ```idl
/// union MyUnion switch (long) {
///     case 1: long a;
///     case 2: string b;
///     default: octet other;
/// };
/// ```
/// produces:
/// ```ts
/// export type MyUnion =
///     | { discriminator: 1; a: number }
///     | { discriminator: 2; b: string }
///     | { discriminator: number; other: number };
/// ```
fn emit_union(out: &mut String, u: &zerodds_idl::ast::UnionDef) -> Result<(), IdlTsError> {
    use zerodds_idl::ast::{CaseLabel, SwitchTypeSpec};

    let name = escape_ts_ident(&u.name.text);
    let name = &name;
    let disc_broad = match &u.switch_type {
        SwitchTypeSpec::Integer(_) | SwitchTypeSpec::Octet => "number",
        SwitchTypeSpec::Char => "Char",
        SwitchTypeSpec::Boolean => "boolean",
        SwitchTypeSpec::Scoped(s) => {
            // For enum discriminators we emit the qualified name —
            // literal-narrowing is then strict (Exclude works).
            let qname = scoped_dotted(s);
            return emit_union_with_enum_discriminator(out, u, &qname);
        }
    };

    out.push_str(&alloc::format!("export type {name} =\n"));
    let mut first = true;
    let mut explicit_labels: Vec<String> = Vec::new();
    for case in &u.cases {
        for label in &case.labels {
            let prefix = if first { "    " } else { "    | " };
            first = false;
            let disc_str = match label {
                CaseLabel::Default => disc_broad.to_string(),
                CaseLabel::Value(expr) => match render_label_for(disc_broad, expr) {
                    Some(s) => {
                        explicit_labels.push(s.clone());
                        s
                    }
                    None => disc_broad.to_string(),
                },
            };
            let elem_ts = typespec_to_ts(&case.element.type_spec)?;
            let field_name = case.element.declarator.name().text.clone();
            out.push_str(&alloc::format!(
                "{prefix}{{ discriminator: {disc_str}; {field_name}: {elem_ts} }}\n"
            ));
        }
    }
    out.push_str(";\n\n");

    emit_union_descriptor(out, u, disc_broad)?;
    emit_union_typesupport(out, u)?;

    Ok(())
}

/// Renders a case-label expression as a TS literal. For broad
/// disc types (`number`/`boolean`) the literal type-system narrowing
/// is partial (TS does not narrow `number` by `Exclude`-of-literals),
/// but the per-arm discriminator value is still emitted as the
/// concrete literal for runtime matching.
fn render_label_for(disc_broad: &str, expr: &zerodds_idl::ast::ConstExpr) -> Option<String> {
    use zerodds_idl::ast::{ConstExpr, LiteralKind};
    if let Some(n) = eval_const_int(expr) {
        return Some(if disc_broad == "boolean" {
            (n != 0).to_string()
        } else {
            alloc::format!("{n}")
        });
    }
    if let ConstExpr::Literal(lit) = expr {
        return Some(match lit.kind {
            LiteralKind::Boolean => match lit.raw.to_lowercase().as_str() {
                "true" | "1" => "true".into(),
                _ => "false".into(),
            },
            LiteralKind::Char | LiteralKind::WideChar => {
                let raw = lit.raw.as_str();
                let trimmed = raw
                    .strip_prefix('L')
                    .unwrap_or(raw)
                    .strip_prefix('\'')
                    .and_then(|s| s.strip_suffix('\''))
                    .unwrap_or(raw);
                alloc::format!("\"{trimmed}\"")
            }
            _ => lit.raw.clone(),
        });
    }
    None
}

/// Special-case for enum-typed discriminators: literal narrowing
/// works because each label is a literal subtype of the enum
/// alias, and the default arm uses `Exclude<Enum, Listed>`.
fn emit_union_with_enum_discriminator(
    out: &mut String,
    u: &zerodds_idl::ast::UnionDef,
    enum_name: &str,
) -> Result<(), IdlTsError> {
    use zerodds_idl::ast::{CaseLabel, ConstExpr};
    let name = escape_ts_ident(&u.name.text);
    let name = &name;
    out.push_str(&alloc::format!("export type {name} =\n"));

    let mut explicit_labels: Vec<String> = Vec::new();
    let mut default_case: Option<&zerodds_idl::ast::Case> = None;
    let mut first = true;

    for case in &u.cases {
        let mut emitted_label = false;
        for label in &case.labels {
            match label {
                CaseLabel::Default => {
                    default_case = Some(case);
                }
                CaseLabel::Value(ConstExpr::Scoped(s)) => {
                    let prefix = if first { "    " } else { "    | " };
                    first = false;
                    let qual = scoped_dotted_value_access(s);
                    let disc_str = if qual.contains('.') {
                        qual.clone()
                    } else {
                        alloc::format!("{enum_name}.{qual}")
                    };
                    // The enum surface is an `as const` object + string-literal
                    // union, NOT a TS `enum`, so `Kind.K_A` is a *value*. In type
                    // position we need `typeof Kind.K_A` (which is the literal
                    // string member type) — a bare `Kind.K_A` is a TS2702 error.
                    let type_disc = alloc::format!("typeof {disc_str}");
                    explicit_labels.push(type_disc.clone());
                    let elem_ts = typespec_to_ts(&case.element.type_spec)?;
                    let field_name = case.element.declarator.name().text.clone();
                    out.push_str(&alloc::format!(
                        "{prefix}{{ discriminator: {type_disc}; {field_name}: {elem_ts} }}\n"
                    ));
                    emitted_label = true;
                }
                CaseLabel::Value(_) => {
                    // Non-scoped label on enum disc: degrade to broad.
                    let prefix = if first { "    " } else { "    | " };
                    first = false;
                    let elem_ts = typespec_to_ts(&case.element.type_spec)?;
                    let field_name = case.element.declarator.name().text.clone();
                    out.push_str(&alloc::format!(
                        "{prefix}{{ discriminator: {enum_name}; {field_name}: {elem_ts} }}\n"
                    ));
                    emitted_label = true;
                }
            }
        }
        let _ = emitted_label;
    }
    if let Some(case) = default_case {
        let prefix = if first { "    " } else { "    | " };
        let elem_ts = typespec_to_ts(&case.element.type_spec)?;
        let field_name = case.element.declarator.name().text.clone();
        let labels_union = if explicit_labels.is_empty() {
            "never".into()
        } else {
            explicit_labels.join(" | ")
        };
        out.push_str(&alloc::format!(
            "{prefix}{{ discriminator: Exclude<{enum_name}, {labels_union}>; {field_name}: {elem_ts} }}\n"
        ));
    }
    out.push_str(";\n\n");

    emit_union_descriptor(out, u, enum_name)?;
    emit_union_typesupport(out, u)?;
    Ok(())
}

/// Emits the `<Name>Type: DdsTypeDescriptor<<Name>>` side-table
/// for an IDL union (§7.5.1). The descriptor's fields list begins
/// with a synthetic discriminator descriptor at id `0xFFFFFFFF`,
/// followed by one descriptor per case-member with its `labels`.
fn emit_union_descriptor(
    out: &mut String,
    u: &zerodds_idl::ast::UnionDef,
    disc_broad: &str,
) -> Result<(), IdlTsError> {
    use zerodds_idl::ast::{CaseLabel, SwitchTypeSpec};
    let name = escape_ts_ident(&u.name.text);
    let name = &name;
    let extensibility = struct_extensibility(&u.annotations);
    let disc_typeref = match &u.switch_type {
        SwitchTypeSpec::Integer(i) => alloc::format!(
            "{{ kind: \"primitive\", name: \"{}\" }}",
            primitive_to_typeref_name(&PrimitiveType::Integer(*i))
        ),
        SwitchTypeSpec::Octet => "{ kind: \"primitive\", name: \"octet\" }".into(),
        SwitchTypeSpec::Char => "{ kind: \"primitive\", name: \"char\" }".into(),
        SwitchTypeSpec::Boolean => "{ kind: \"primitive\", name: \"boolean\" }".into(),
        SwitchTypeSpec::Scoped(s) => {
            let qname = s
                .parts
                .iter()
                .map(|p| p.text.clone())
                .collect::<Vec<_>>()
                .join("::");
            alloc::format!("{{ kind: \"ref\", name: \"{qname}\" }}")
        }
    };
    let _ = disc_broad;

    let mut has_default = false;
    let mut next_id: i64 = 0;

    out.push_str(&alloc::format!(
        "export const {name}Type: DdsTypeDescriptor<{name}> = {{\n"
    ));
    out.push_str("    kind: \"union\",\n");
    out.push_str(&alloc::format!("    name: \"{}\",\n", u.name.text));
    out.push_str(&alloc::format!("    extensibility: \"{extensibility}\",\n"));
    out.push_str("    nested: false,\n");
    out.push_str("    fields: [\n");
    // Synthetic discriminator at reserved id 0xFFFFFFFF.
    out.push_str("        {\n");
    out.push_str("            name: \"discriminator\",\n");
    out.push_str("            id: 0xFFFFFFFF,\n");
    out.push_str(&alloc::format!("            type: {disc_typeref},\n"));
    out.push_str("            key: false,\n");
    out.push_str("            optional: false,\n");
    out.push_str("            mustUnderstand: false,\n");
    out.push_str("        },\n");

    for case in &u.cases {
        let mut labels_lit: Vec<String> = Vec::new();
        let mut is_default = false;
        for label in &case.labels {
            match label {
                CaseLabel::Default => {
                    is_default = true;
                    has_default = true;
                }
                CaseLabel::Value(expr) => {
                    if let Some(s) = render_descriptor_label(expr) {
                        labels_lit.push(s);
                    }
                }
            }
        }
        let elem_ts_ref = typespec_to_typeref_literal(&case.element.type_spec);
        let id_override = annotation_int_value(&case.element.annotations, "id");
        let id = id_override.unwrap_or(next_id);
        next_id = id + 1;
        let field_name = case.element.declarator.name().text.clone();
        out.push_str("        {\n");
        out.push_str(&alloc::format!("            name: \"{field_name}\",\n"));
        out.push_str(&alloc::format!("            id: {id},\n"));
        out.push_str(&alloc::format!("            type: {elem_ts_ref},\n"));
        out.push_str("            key: false,\n");
        out.push_str("            optional: false,\n");
        out.push_str("            mustUnderstand: false,\n");
        if !is_default && !labels_lit.is_empty() {
            out.push_str(&alloc::format!(
                "            labels: [{}],\n",
                labels_lit.join(", ")
            ));
        }
        out.push_str("        },\n");
    }
    out.push_str("    ],\n");
    out.push_str(&alloc::format!("    hasDefault: {has_default},\n"));
    out.push_str(&alloc::format!("    typeGuard: is{name},\n"));
    out.push_str("};\n");

    // Type-guard: structural check for {discriminator, ...} object.
    out.push_str(&alloc::format!(
        "export function is{name}(v: unknown): v is {name} {{\n"
    ));
    out.push_str("    if (typeof v !== \"object\" || v === null) return false;\n");
    out.push_str("    const o = v as Record<string, unknown>;\n");
    out.push_str("    return \"discriminator\" in o;\n");
    out.push_str("}\n\n");

    out.push_str(&alloc::format!("registerType({name}Type);\n\n"));
    Ok(())
}

/// Maps a union `SwitchTypeSpec` to the equivalent member `TypeSpec`, so the
/// discriminator can reuse the scalar encode/decode paths.
fn switch_type_to_typespec(sw: &zerodds_idl::ast::SwitchTypeSpec) -> TypeSpec {
    use zerodds_idl::ast::SwitchTypeSpec;
    match sw {
        SwitchTypeSpec::Integer(i) => TypeSpec::Primitive(PrimitiveType::Integer(*i)),
        SwitchTypeSpec::Char => TypeSpec::Primitive(PrimitiveType::Char),
        SwitchTypeSpec::Boolean => TypeSpec::Primitive(PrimitiveType::Boolean),
        SwitchTypeSpec::Octet => TypeSpec::Primitive(PrimitiveType::Octet),
        SwitchTypeSpec::Scoped(s) => TypeSpec::Scoped(s.clone()),
    }
}

/// Renders a case-label as the TS runtime value used for `===` dispatch in the
/// union codec. Enum-discriminator labels render as the qualified enum member
/// (`Enum.MEMBER`); integer/char/boolean labels render as the literal.
fn render_codec_label(
    sw: &zerodds_idl::ast::SwitchTypeSpec,
    expr: &zerodds_idl::ast::ConstExpr,
) -> Option<String> {
    use zerodds_idl::ast::{ConstExpr, SwitchTypeSpec};
    if let SwitchTypeSpec::Scoped(enum_ref) = sw {
        // Enum discriminator: a scoped label is `Enum.MEMBER`; a bare ordinal
        // resolves to the member name via the enum-literal registry.
        let enum_name = scoped_dotted(enum_ref);
        if let ConstExpr::Scoped(s) = expr {
            let qual = scoped_dotted_value_access(s);
            return Some(if qual.contains('.') {
                qual
            } else {
                alloc::format!("{enum_name}.{qual}")
            });
        }
    }
    // For broad/char/boolean discriminators reuse the per-arm literal renderer
    // (it already folds scoped consts and renders char/bool correctly).
    let disc_broad = match sw {
        SwitchTypeSpec::Integer(_) | SwitchTypeSpec::Octet => "number",
        SwitchTypeSpec::Char => "Char",
        SwitchTypeSpec::Boolean => "boolean",
        SwitchTypeSpec::Scoped(_) => "number",
    };
    render_label_for(disc_broad, expr)
}

/// Emits `<Name>TypeSupport: DdsTopicType<<Name>>` for an IDL union
/// (TS-cluster #1). The wire form (zerodds-xcdr2-ts-1.0 §5) is: an optional
/// DHEADER (for @appendable/@mutable extensibility), the discriminator in its
/// scalar XCDR2 form, then the single selected branch member. On decode the
/// discriminator value selects which branch to read (default branch otherwise).
fn emit_union_typesupport(
    out: &mut String,
    u: &zerodds_idl::ast::UnionDef,
) -> Result<(), IdlTsError> {
    use zerodds_idl::ast::CaseLabel;
    let name = escape_ts_ident(&u.name.text);
    let name = &name;
    let extensibility = struct_extensibility(&u.annotations);
    let disc_ts = switch_type_to_typespec(&u.switch_type);
    let wrap = matches!(extensibility, "appendable" | "mutable");

    out.push_str(&alloc::format!(
        "export const {name}TypeSupport: DdsTopicType<{name}> = {{\n"
    ));
    out.push_str(&alloc::format!("    typeName: \"{}\",\n", u.name.text));
    out.push_str("    isKeyed: false,\n");
    out.push_str(&alloc::format!("    extensibility: \"{extensibility}\",\n"));

    // === encodeInto ===
    out.push_str(&alloc::format!(
        "    encodeInto(w: Xcdr2Writer, s: {name}): void {{\n"
    ));
    if wrap {
        out.push_str("        const _tok = w.beginAppendable();\n");
    }
    // Discriminator first (enum disc routes through its ordinal map).
    emit_typespec_encode(out, &disc_ts, "s.discriminator", "        ")?;
    // Branch dispatch.
    let mut first = true;
    let mut default_case: Option<&zerodds_idl::ast::Case> = None;
    for case in &u.cases {
        let mut labels: Vec<String> = Vec::new();
        let mut is_default = false;
        for label in &case.labels {
            match label {
                CaseLabel::Default => is_default = true,
                CaseLabel::Value(expr) => {
                    if let Some(l) = render_codec_label(&u.switch_type, expr) {
                        labels.push(l);
                    }
                }
            }
        }
        if is_default {
            default_case = Some(case);
            continue;
        }
        if labels.is_empty() {
            continue;
        }
        let cond = labels
            .iter()
            .map(|l| alloc::format!("s.discriminator === {l}"))
            .collect::<Vec<_>>()
            .join(" || ");
        let kw = if first { "if" } else { "} else if" };
        first = false;
        out.push_str(&alloc::format!("        {kw} ({cond}) {{\n"));
        emit_union_branch_encode(out, case, "            ")?;
    }
    if let Some(case) = default_case {
        if first {
            // Only a default case exists.
            emit_union_branch_encode(out, case, "        ")?;
        } else {
            out.push_str("        } else {\n");
            emit_union_branch_encode(out, case, "            ")?;
            out.push_str("        }\n");
        }
    } else if !first {
        out.push_str("        }\n");
    }
    if wrap {
        out.push_str("        w.endAppendable(_tok);\n");
    }
    out.push_str("    },\n");

    // === encode (fresh writer) ===
    out.push_str(&alloc::format!(
        "    encode(s: {name}, endian: EndianMode = \"le\", representation = 1): Uint8Array {{\n"
    ));
    // representation: 1 = XCDR2 (alignment cap 4), 0 = XCDR1 / classic CDR (cap 8,
    // no DHEADER, PL_CDR1 @mutable).
    out.push_str("        const w = new Xcdr2Writer(endian, representation === 0 ? 8 : 4);\n");
    out.push_str("        this.encodeInto(w, s);\n");
    out.push_str("        return w.toBytes();\n");
    out.push_str("    },\n");

    // === decodeFrom ===
    out.push_str(&alloc::format!(
        "    decodeFrom(r: Xcdr2Reader): {name} {{\n"
    ));
    if wrap {
        out.push_str("        const _tok = r.beginAppendable();\n");
    }
    let disc_read = read_typespec_expr(&disc_ts)?;
    let disc_ts_ty = match &u.switch_type {
        zerodds_idl::ast::SwitchTypeSpec::Scoped(s) => scoped_dotted(s),
        _ => typespec_to_ts(&disc_ts)?,
    };
    out.push_str(&alloc::format!(
        "        const _disc: {disc_ts_ty} = {disc_read};\n"
    ));
    out.push_str(&alloc::format!("        let _result: {name};\n"));
    let mut first = true;
    let mut default_case: Option<&zerodds_idl::ast::Case> = None;
    for case in &u.cases {
        let mut labels: Vec<String> = Vec::new();
        let mut is_default = false;
        for label in &case.labels {
            match label {
                CaseLabel::Default => is_default = true,
                CaseLabel::Value(expr) => {
                    if let Some(l) = render_codec_label(&u.switch_type, expr) {
                        labels.push(l);
                    }
                }
            }
        }
        if is_default {
            default_case = Some(case);
            continue;
        }
        if labels.is_empty() {
            continue;
        }
        let cond = labels
            .iter()
            .map(|l| alloc::format!("_disc === {l}"))
            .collect::<Vec<_>>()
            .join(" || ");
        let kw = if first { "if" } else { "} else if" };
        first = false;
        out.push_str(&alloc::format!("        {kw} ({cond}) {{\n"));
        emit_union_branch_decode(out, case, "_disc")?;
    }
    if let Some(case) = default_case {
        if first {
            emit_union_branch_decode_flat(out, case, "_disc", "        ")?;
        } else {
            out.push_str("        } else {\n");
            emit_union_branch_decode(out, case, "_disc")?;
            out.push_str("        }\n");
        }
    } else if !first {
        // No default: a discriminator outside the listed labels has no branch.
        // Per IDL §7.4.2 this is an implicit default with no member; surface a
        // discriminator-only object so decode is total.
        out.push_str("        } else {\n");
        out.push_str("            _result = { discriminator: _disc } as unknown as ");
        out.push_str(&alloc::format!("{name};\n"));
        out.push_str("        }\n");
    }
    if first && default_case.is_none() {
        // Degenerate union with no usable cases.
        out.push_str("        _result = { discriminator: _disc } as unknown as ");
        out.push_str(&alloc::format!("{name};\n"));
    }
    if wrap {
        out.push_str("        r.endAppendable(_tok);\n");
    }
    out.push_str("        return _result;\n");
    out.push_str("    },\n");

    // === decode (fresh reader) ===
    // `endian` trailing-optional (default "le") — see the struct emitter; a
    // big-endian payload decodes via decode(bytes, 0, len, "be").
    out.push_str(&alloc::format!(
        "    decode(bytes: Uint8Array, offset = 0, length: number = bytes.length - offset, endian: EndianMode = \"le\", representation = 1): {name} {{\n"
    ));
    // representation: 1 = XCDR2 (alignment cap 4), 0 = XCDR1 / classic CDR (cap 8,
    // no DHEADER, PL_CDR1 @mutable).
    out.push_str("        const r = new Xcdr2Reader(bytes, offset, length, endian, representation === 0 ? 8 : 4);\n");
    out.push_str("        return this.decodeFrom(r);\n");
    out.push_str("    },\n");

    // === keyHash (unions are not keyed) ===
    out.push_str(&alloc::format!("    keyHash(s: {name}): Uint8Array {{\n"));
    out.push_str("        void s;\n");
    out.push_str("        return new Uint8Array(16);\n");
    out.push_str("    },\n");
    out.push_str("};\n\n");
    Ok(())
}

/// Emits the encode of a single union branch member. The branch field is bound
/// via a per-branch typed cast first — TS cannot narrow `s` to the active arm
/// (the implicit-default arm has the broad `discriminator` type that subsumes
/// the literal labels), so a direct `s.<field>` access would be rejected.
fn emit_union_branch_encode(
    out: &mut String,
    case: &zerodds_idl::ast::Case,
    indent: &str,
) -> Result<(), IdlTsError> {
    let field = case.element.declarator.name().text.clone();
    let base_ts = typespec_to_ts(&case.element.type_spec)?;
    let ts_ty = wrap_with_array_dimensions(&base_ts, &case.element.declarator);
    out.push_str(&alloc::format!(
        "{indent}const _v: {ts_ty} = (s as unknown as {{ {field}: {ts_ty} }}).{field};\n"
    ));
    emit_declarator_encode(
        out,
        &case.element.type_spec,
        &case.element.declarator,
        "_v",
        indent,
        0,
    )
}

/// Emits a union branch decode inside an `if`-block (4-space inner indent under
/// the dispatch `if`): reads the branch field and assigns `_result`.
fn emit_union_branch_decode(
    out: &mut String,
    case: &zerodds_idl::ast::Case,
    disc_var: &str,
) -> Result<(), IdlTsError> {
    emit_union_branch_decode_flat(out, case, disc_var, "            ")
}

/// Emits a union branch decode at the given indent.
fn emit_union_branch_decode_flat(
    out: &mut String,
    case: &zerodds_idl::ast::Case,
    disc_var: &str,
    indent: &str,
) -> Result<(), IdlTsError> {
    let field = case.element.declarator.name().text.clone();
    let base_ts = typespec_to_ts(&case.element.type_spec)?;
    let ts_ty = wrap_with_array_dimensions(&base_ts, &case.element.declarator);
    let read = read_declarator_expr(&case.element.type_spec, &case.element.declarator, &base_ts)?;
    out.push_str(&alloc::format!("{indent}const _b: {ts_ty} = {read};\n"));
    out.push_str(&alloc::format!(
        "{indent}_result = {{ discriminator: {disc_var}, {field}: _b }} as unknown as typeof _result;\n"
    ));
    Ok(())
}

/// Renders a case-label expression as a descriptor-literal value
/// (number / "string" / true|false). Used in `labels: [...]`.
fn render_descriptor_label(expr: &zerodds_idl::ast::ConstExpr) -> Option<String> {
    use zerodds_idl::ast::{ConstExpr, LiteralKind};
    if let Some(n) = eval_const_int(expr) {
        return Some(alloc::format!("{n}"));
    }
    if let ConstExpr::Literal(lit) = expr {
        return Some(match lit.kind {
            LiteralKind::Boolean => match lit.raw.to_lowercase().as_str() {
                "true" | "1" => "true".into(),
                _ => "false".into(),
            },
            LiteralKind::Char | LiteralKind::WideChar => {
                let raw = lit.raw.as_str();
                let trimmed = raw
                    .strip_prefix('L')
                    .unwrap_or(raw)
                    .strip_prefix('\'')
                    .and_then(|s| s.strip_suffix('\''))
                    .unwrap_or(raw);
                alloc::format!("\"{trimmed}\"")
            }
            _ => lit.raw.clone(),
        });
    }
    if let ConstExpr::Scoped(s) = expr {
        let qual = s
            .parts
            .iter()
            .map(|p| p.text.clone())
            .collect::<Vec<_>>()
            .join(".");
        return Some(alloc::format!("\"{qual}\""));
    }
    None
}

/// IDL §7.4.13.4 Bitset → DDS-TS 1.0 §7.7.
///
/// Each bitfield maps to a property whose TypeScript type
/// depends on the bitfield width: ≤32 → `number`, 33..64 →
/// `bigint`. Total width > 64 is rejected (PSM limit, since
/// JavaScript bitwise operations are 32-bit and `bigint` covers
/// 64 bits — wider bitsets cannot be operated on coherently).
fn emit_bitset(out: &mut String, b: &zerodds_idl::ast::BitsetDecl) -> Result<(), IdlTsError> {
    // Verify total width <= 64 (§7.7 fatal-error rule).
    let mut total: i64 = 0;
    for bf in &b.bitfields {
        if let Some(w) = eval_const_int(&bf.spec.width) {
            total = total.saturating_add(w);
        }
    }
    if total > 64 {
        return Err(IdlTsError::Unsupported(alloc::format!(
            "bitset {} total width {total} > 64 (DDS-TS 1.0 §7.7)",
            b.name.text
        )));
    }

    let bs_name = escape_ts_ident(&b.name.text);
    let bs_name = &bs_name;

    out.push_str(&alloc::format!("export interface {bs_name} {{\n"));
    for bf in &b.bitfields {
        if let Some(name) = &bf.name {
            let width = eval_const_int(&bf.spec.width).unwrap_or(0);
            let ts_ty = if width > 32 { "bigint" } else { "number" };
            out.push_str(&alloc::format!("    {}: {ts_ty};\n", name.text));
        }
    }
    out.push_str("}\n\n");

    for bf in &b.bitfields {
        if let Some(name) = &bf.name {
            let width = const_expr_to_ts(&bf.spec.width);
            out.push_str(&alloc::format!(
                "export const {bs_name}_{}_BITS = {width};\n",
                name.text
            ));
        }
    }
    out.push('\n');

    // Type-guard.
    out.push_str(&alloc::format!(
        "export function is{bs_name}(v: unknown): v is {bs_name} {{\n"
    ));
    out.push_str("    if (typeof v !== \"object\" || v === null) return false;\n");
    out.push_str("    const o = v as Record<string, unknown>;\n");
    for bf in &b.bitfields {
        if let Some(name) = &bf.name {
            let width = eval_const_int(&bf.spec.width).unwrap_or(0);
            let ts_ty = if width > 32 { "bigint" } else { "number" };
            out.push_str(&alloc::format!(
                "    if (typeof o.{} !== \"{ts_ty}\") return false;\n",
                name.text
            ));
        }
    }
    out.push_str("    return true;\n}\n\n");

    // Descriptor.
    out.push_str(&alloc::format!(
        "export const {bs_name}Type: DdsTypeDescriptor<{bs_name}> = {{\n"
    ));
    out.push_str("    kind: \"bitset\",\n");
    out.push_str(&alloc::format!("    name: \"{}\",\n", b.name.text));
    out.push_str("    extensibility: \"final\",\n");
    out.push_str("    nested: false,\n");
    out.push_str(&alloc::format!("    bitBound: {total},\n"));
    out.push_str("    fields: [\n");
    let mut next_id: i64 = 0;
    for bf in &b.bitfields {
        if let Some(name) = &bf.name {
            let width = eval_const_int(&bf.spec.width).unwrap_or(0);
            out.push_str("        {\n");
            out.push_str(&alloc::format!("            name: \"{}\",\n", name.text));
            out.push_str(&alloc::format!("            id: {next_id},\n"));
            out.push_str(&alloc::format!(
                "            type: {{ kind: \"bitfield\", width: {width} }},\n"
            ));
            out.push_str("            key: false,\n");
            out.push_str("            optional: false,\n");
            out.push_str("            mustUnderstand: false,\n");
            out.push_str("        },\n");
            next_id += 1;
        }
    }
    out.push_str("    ],\n");
    out.push_str(&alloc::format!("    typeGuard: is{bs_name},\n"));
    out.push_str("};\n");
    out.push_str(&alloc::format!("registerType({bs_name}Type);\n\n"));
    Ok(())
}

/// IDL §7.4.13.5 Bitmask → DDS-TS 1.0 §7.8.
///
/// Default bit width is 32 (per IDL); `@bit_bound(N)` may set
/// 1..64. For ≤32 the emitted shifts are unsigned 32-bit form
/// `(1 << K) >>> 0` with TypeScript `number`. For 33..64 the
/// emitted shifts are BigInt form `1n << Kn` with TypeScript
/// `bigint` — required because JavaScript's `<<` operator
/// coerces both operands to Int32 and would wrap for K >= 32.
///
/// `@position(P)` on a bit value overrides the implicit bit
/// position (defaults to declaration order).
fn emit_bitmask(out: &mut String, b: &zerodds_idl::ast::BitmaskDecl) -> Result<(), IdlTsError> {
    let bit_bound = annotation_int_value(&b.annotations, "bit_bound").unwrap_or(32);
    let use_bigint = bit_bound > 32;
    let alias_ty = if use_bigint { "bigint" } else { "number" };

    let bm_name = escape_ts_ident(&b.name.text);
    let bm_name = &bm_name;

    out.push_str(&alloc::format!("export const {bm_name} = {{\n"));
    for (i, v) in b.values.iter().enumerate() {
        let pos = annotation_int_value(&v.annotations, "position").unwrap_or(i as i64);
        let shift = if use_bigint {
            alloc::format!("1n << {pos}n")
        } else {
            alloc::format!("(1 << {pos}) >>> 0")
        };
        out.push_str(&alloc::format!("    {}: {shift},\n", v.name.text));
    }
    out.push_str("} as const;\n");
    out.push_str(&alloc::format!("export type {bm_name} = {alias_ty};\n"));
    out.push_str(&alloc::format!(
        "export const {bm_name}_BIT_BOUND = {bit_bound};\n\n"
    ));

    // Type-guard for the bitmask alias type (number or bigint).
    out.push_str(&alloc::format!(
        "export function is{bm_name}(v: unknown): v is {bm_name} {{\n"
    ));
    out.push_str(&alloc::format!("    return typeof v === \"{alias_ty}\";\n"));
    out.push_str("}\n\n");

    // Descriptor.
    out.push_str(&alloc::format!(
        "export const {bm_name}Type: DdsTypeDescriptor<{bm_name}> = {{\n"
    ));
    out.push_str("    kind: \"bitmask\",\n");
    out.push_str(&alloc::format!("    name: \"{}\",\n", b.name.text));
    out.push_str("    extensibility: \"final\",\n");
    out.push_str("    nested: false,\n");
    out.push_str(&alloc::format!("    bitBound: {bit_bound},\n"));
    out.push_str("    fields: [\n");
    for (i, v) in b.values.iter().enumerate() {
        let pos = annotation_int_value(&v.annotations, "position").unwrap_or(i as i64);
        out.push_str("        {\n");
        out.push_str(&alloc::format!("            name: \"{}\",\n", v.name.text));
        out.push_str(&alloc::format!("            id: {i},\n"));
        out.push_str("            type: { kind: \"bitfield\", width: 1 },\n");
        out.push_str("            key: false,\n");
        out.push_str("            optional: false,\n");
        out.push_str("            mustUnderstand: false,\n");
        out.push_str(&alloc::format!("            default: {pos},\n"));
        out.push_str("        },\n");
    }
    out.push_str("    ],\n");
    out.push_str(&alloc::format!("    typeGuard: is{bm_name},\n"));
    out.push_str("};\n");
    out.push_str(&alloc::format!("registerType({bm_name}Type);\n\n"));
    Ok(())
}

/// IDL §7.4.4 Typedef → DDS-TS 1.0 §7.10.
///
/// Emits `export type <Alias> = <Base>` plus a Type-Descriptor of
/// kind `"alias"`. For integer-valued typedefs carrying
/// `@bit_bound(N)` with N in 33..64 the alias type switches from
/// `number` to `bigint` (§7.10.2). Bounded-string and bounded-
/// sequence typedef forms additionally emit
/// `<Alias>_BOUND` constants; fixed-size array typedefs emit
/// `<Alias>_LENGTH`.
fn emit_typedef(out: &mut String, t: &zerodds_idl::ast::TypedefDecl) -> Result<(), IdlTsError> {
    use zerodds_idl::ast::Declarator;

    let bit_bound = annotation_int_value(&t.annotations, "bit_bound");
    let base_ts = if let Some(n) = bit_bound {
        if n > 32 && is_integer_typespec(&t.type_spec) {
            "bigint".into()
        } else {
            typespec_to_ts(&t.type_spec)?
        }
    } else {
        typespec_to_ts(&t.type_spec)?
    };

    for d in &t.declarators {
        // `alias` is the TS-syntax (escaped) name, used for every
        // declaration/type-reference below; `raw_alias` is the original
        // IDL name, used only for the descriptor's reflection `name:`
        // string.
        let (alias, raw_alias) = match d {
            Declarator::Simple(name) => {
                let alias = escape_ts_ident(&name.text);
                out.push_str(&alloc::format!("export type {alias} = {base_ts};\n"));
                (alias, name.text.clone())
            }
            Declarator::Array(arr) => {
                let alias = escape_ts_ident(&arr.name.text);
                out.push_str(&alloc::format!("export type {alias} = Array<{base_ts}>;\n"));
                if arr.sizes.len() == 1 {
                    if let Some(len) = eval_const_int(&arr.sizes[0]) {
                        out.push_str(&alloc::format!("export const {alias}_LENGTH = {len};\n"));
                    }
                } else {
                    for (i, sz) in arr.sizes.iter().enumerate() {
                        if let Some(len) = eval_const_int(sz) {
                            out.push_str(&alloc::format!(
                                "export const {alias}_LENGTH_DIM{} = {len};\n",
                                i + 1
                            ));
                        }
                    }
                }
                (alias, arr.name.text.clone())
            }
        };

        // Bounded-string / bounded-sequence: emit <Alias>_BOUND.
        if let TypeSpec::String(StringType { bound: Some(n), .. }) = &t.type_spec {
            if let Some(width) = eval_const_int(n) {
                out.push_str(&alloc::format!("export const {alias}_BOUND = {width};\n"));
            }
        }
        if let TypeSpec::Sequence(seq) = &t.type_spec {
            if let Some(bound) = &seq.bound {
                if let Some(width) = eval_const_int(bound) {
                    out.push_str(&alloc::format!("export const {alias}_BOUND = {width};\n"));
                }
            }
        }

        // Type-guard.
        let typeof_check = typespec_typeof_check(&t.type_spec);
        out.push_str(&alloc::format!(
            "export function is{alias}(v: unknown): v is {alias} {{\n"
        ));
        if let Some(check) = &typeof_check {
            let bb_override = bit_bound.filter(|&n| n > 32 && is_integer_typespec(&t.type_spec));
            let effective = if bb_override.is_some() {
                "typeof v !== \"bigint\"".to_string()
            } else {
                check.replace("VAR", "v")
            };
            out.push_str(&alloc::format!("    if ({effective}) return false;\n"));
        }
        out.push_str("    return true;\n}\n");

        // Descriptor.
        let inner_ref = typespec_to_typeref_literal(&t.type_spec);
        out.push_str(&alloc::format!(
            "export const {alias}Type: DdsTypeDescriptor<{alias}> = {{\n"
        ));
        out.push_str("    kind: \"alias\",\n");
        out.push_str(&alloc::format!("    name: \"{raw_alias}\",\n"));
        out.push_str("    extensibility: \"appendable\",\n");
        out.push_str("    nested: false,\n");
        if let Some(n) = bit_bound {
            out.push_str(&alloc::format!("    bitBound: {n},\n"));
        }
        out.push_str("    fields: [\n");
        out.push_str("        {\n");
        out.push_str("            name: \"value\",\n");
        out.push_str("            id: 0,\n");
        out.push_str(&alloc::format!("            type: {inner_ref},\n"));
        out.push_str("            key: false,\n");
        out.push_str("            optional: false,\n");
        out.push_str("            mustUnderstand: false,\n");
        out.push_str("        },\n");
        out.push_str("    ],\n");
        out.push_str(&alloc::format!("    typeGuard: is{alias},\n"));
        out.push_str("};\n");
        out.push_str(&alloc::format!("registerType({alias}Type);\n\n"));
    }
    Ok(())
}

/// True iff the `TypeSpec` is an integer primitive.
fn is_integer_typespec(t: &TypeSpec) -> bool {
    matches!(t, TypeSpec::Primitive(PrimitiveType::Integer(_)))
}

/// Wraps a base TypeScript type in `Array<…>` per Array-Declarator
/// dimensions. Returns `base` unchanged for `Declarator::Simple`.
/// For multi-dimensional arrays produces `Array<Array<…<T>>…>`
/// nested by dimension count (DDS-TS 1.0 §7.9 Multi-Dimensional
/// Arrays).
fn wrap_with_array_dimensions(base: &str, d: &zerodds_idl::ast::Declarator) -> String {
    use zerodds_idl::ast::Declarator;
    match d {
        Declarator::Simple(_) => base.to_string(),
        Declarator::Array(arr) => {
            let mut out = base.to_string();
            for _ in &arr.sizes {
                out = alloc::format!("Array<{out}>");
            }
            out
        }
    }
}

