const FEED: &str = "IDL:Shop/Feed:1.0";

fn mode(m: i32) -> Property {
    Property::new(GROUP_CREATION_MODE, AnyValue::Long(m))
}

fn address(a: &str) -> Property {
    Property::new(PROTOCOL_ENDPOINTS_IP_ADDRESS, AnyValue::Str(a.into()))
}

fn port(p: u16) -> Property {
    Property::new(PROTOCOL_ENDPOINTS_IP_PORT, AnyValue::UShort(p))
}

fn object(r: &ObjectReference) -> AnyValue {
    AnyValue::ObjRef {
        type_code: TypeCode::ObjRef {
            repo_id: "IDL:omg.org/CORBA/Object:1.0".into(),
            name: "Object".into(),
        },
        reference: Some(r.clone()),
    }
}

fn iiop_ref(host: &str, p: u16, key: &[u8]) -> ObjectReference {
    ObjectReference {
        type_id: "IDL:X:1.0".into(),
        iiop_profile: IiopProfileBody::new(IiopVersion::V1_2, host.into(), p, key.to_vec())
            .encode_encapsulation(Endianness::Big)
            .unwrap(),
        policy_overrides: Vec::new(),
        profiles: Vec::new(),
    }
}

#[test]
fn corba_p2_11_2_6_6_create_object_makes_a_group_reference() {
    let mgm = Mgm::default();
    let (ior, creation_id) = mgm.create_object(FEED, &[]).unwrap();
    assert_eq!(ior.type_id, FEED);
    let g = group_profiles(&ior).unwrap();
    // GENERATED by default: an address of the pool, reference version 1,
    // the default group domain.
    assert_eq!(g.uipmc.len(), 1);
    assert_eq!(g.uipmc[0].the_address, "239.255.100.0");
    assert_eq!(g.uipmc[0].the_port, 7_300);
    assert_eq!(g.groups, vec![GroupInfo::new("DefaultGroupDomain", 1, 1)]);
    assert_eq!(creation_id, CorbaAny(AnyValue::ULongLong(1)));
    assert_eq!(mgm.get_object_group_id(&ior).unwrap(), 1);
    assert_eq!(mgm.get_object_group_ref(&ior).unwrap(), ior);
    // A second group gets the next free address.
    let (second, _) = mgm.create_object(FEED, &[]).unwrap();
    assert_eq!(
        group_profiles(&second).unwrap().uipmc[0].the_address,
        "239.255.100.1"
    );
    // delete_object removes the group (§11.3.2: then not found).
    mgm.delete_object(&creation_id).unwrap();
    assert_eq!(
        mgm.get_object_group_ref(&ior),
        Err(MgmError::ObjectGroupNotFound)
    );
    assert_eq!(
        mgm.delete_object(&creation_id),
        Err(MgmError::ObjectNotFound)
    );
    assert_eq!(
        mgm.delete_object(&CorbaAny(AnyValue::Long(2))),
        Err(MgmError::ObjectNotFound)
    );
}

#[test]
fn corba_p2_11_2_6_8_1_the_creation_mode_and_the_endpoints_must_agree() {
    let mgm = Mgm::default();
    let supplied = [
        mode(CREATE_ADDRESS_SUPPLIED),
        address("225.1.1.8"),
        port(5000),
    ];
    let (ior, _) = mgm.create_object(FEED, &supplied).unwrap();
    let u = &group_profiles(&ior).unwrap().uipmc[0];
    assert_eq!((u.the_address.as_str(), u.the_port), ("225.1.1.8", 5000));
    for criteria in [
        vec![mode(CREATE_ADDRESS_SUPPLIED)],
        vec![mode(CREATE_ADDRESS_SUPPLIED), address("225.1.1.8")],
        vec![mode(CREATE_ADDRESS_GENERATED), port(5000)],
        vec![
            mode(CREATE_ADDRESS_DEFERED),
            address("225.1.1.8"),
            port(5000),
        ],
    ] {
        assert!(
            matches!(
                mgm.create_object(FEED, &criteria),
                Err(MgmError::CannotMeetCriteria(_))
            ),
            "{criteria:?}"
        );
    }
    // DEFERED: no endpoint yet; setting them later gives the reference
    // its UIPMC profile and the next version.
    let (deferred, _) = mgm
        .create_object(FEED, &[mode(CREATE_ADDRESS_DEFERED)])
        .unwrap();
    assert!(deferred.profiles.is_empty());
    // A deferred reference without a gateway has no profile to name the
    // group by; with a gateway, its IIOP profile carries the group.
    let gateway = iiop_ref("gw.example", 2809, b"gw");
    let (with_gw, _) = mgm
        .create_object(
            FEED,
            &[
                mode(CREATE_ADDRESS_DEFERED),
                Property::new(CREATE_SPECIFY_GATEWAY, object(&gateway)),
                Property::new(CREATE_INCLUDE_GATEWAY, AnyValue::Boolean(true)),
            ],
        )
        .unwrap();
    assert_eq!(with_gw.profiles.len(), 1);
    mgm.set_properties_dynamically(&with_gw, &[address("225.1.1.9"), port(5001)])
        .unwrap();
    let now = mgm.get_object_group_ref(&with_gw).unwrap();
    let g = group_profiles(&now).unwrap();
    assert_eq!(g.uipmc[0].the_address, "225.1.1.9");
    assert_eq!(g.groups[0].object_group_ref_version, 2);
    // The gateway profile's key names the group (§11.2.3.1).
    assert!(g.iiop[0].object_key.starts_with(b"MIOP"));
    assert_eq!(g.iiop[0].host, "gw.example");
    // The creation mode is set at creation only.
    assert!(matches!(
        mgm.set_properties_dynamically(&now, &[mode(CREATE_ADDRESS_GENERATED)]),
        Err(MgmError::InvalidProperty(_))
    ));
}

#[test]
fn corba_p2_11_2_6_4_properties_come_from_the_most_specific_place() {
    let mgm = Mgm::default();
    mgm.set_default_properties(&[Property::new(GROUP_DOMAIN_ID, AnyValue::Str("Shop".into()))])
        .unwrap();
    mgm.set_type_properties(
        FEED,
        &[
            mode(CREATE_ADDRESS_SUPPLIED),
            address("225.2.2.2"),
            port(6000),
        ],
    )
    .unwrap();
    assert_eq!(mgm.get_type_properties(FEED).len(), 4);
    assert_eq!(mgm.get_type_properties("IDL:Other:1.0").len(), 1);
    let (ior, _) = mgm.create_object(FEED, &[port(6001)]).unwrap();
    let g = group_profiles(&ior).unwrap();
    assert_eq!(g.groups[0].group_domain_id, "Shop");
    assert_eq!(g.uipmc[0].the_address, "225.2.2.2");
    assert_eq!(g.uipmc[0].the_port, 6001);
    mgm.set_properties_dynamically(&ior, &[port(6002)]).unwrap();
    let props = mgm.get_properties(&ior).unwrap();
    let port_of = props
        .iter()
        .find(|p| p.nam[0].id == PROTOCOL_ENDPOINTS_IP_PORT)
        .map(|p| p.val.0.clone());
    assert_eq!(port_of, Some(AnyValue::UShort(6002)));
    // The domain was set by default and cannot be set again.
    assert!(matches!(
        mgm.set_properties_dynamically(
            &ior,
            &[Property::new(GROUP_DOMAIN_ID, AnyValue::Str("X".into()))]
        ),
        Err(MgmError::InvalidProperty(_))
    ));
    mgm.remove_type_properties(FEED, &[port(0)]).unwrap();
    assert_eq!(mgm.get_type_properties(FEED).len(), 3);
    mgm.remove_default_properties(&[Property::new(GROUP_DOMAIN_ID, AnyValue::Str(String::new()))])
        .unwrap();
    assert!(mgm.get_default_properties().is_empty());
}

#[test]
fn corba_p2_11_2_6_3_unknown_repeated_and_mistyped_properties_are_refused() {
    let mgm = Mgm::default();
    assert!(matches!(
        mgm.set_default_properties(&[Property::new("org.omg.mgm.Nonsense", AnyValue::Long(1))]),
        Err(MgmError::UnsupportedProperty { .. })
    ));
    // `create_object` raises no UnsupportedProperty: criteria it does not
    // understand are InvalidCriteria, and only those are named.
    assert_eq!(
        mgm.create_object(
            FEED,
            &[
                port(9),
                Property::new("org.omg.mgm.Nonsense", AnyValue::Long(1))
            ]
        ),
        Err(MgmError::InvalidCriteria(vec![Property::new(
            "org.omg.mgm.Nonsense",
            AnyValue::Long(1)
        )]))
    );
    for bad in [
        vec![Property::new(PROTOCOL_ENDPOINTS_IP_PORT, AnyValue::Long(5))],
        vec![address("10.0.0.1")],
        vec![mode(7)],
        vec![port(1), port(2)],
        vec![Property::new(CREATE_INCLUDE_GATEWAY, AnyValue::Long(1))],
    ] {
        assert!(
            matches!(
                mgm.create_object(FEED, &bad),
                Err(MgmError::InvalidProperty(_))
            ),
            "{bad:?}"
        );
    }
    // A gateway to include without a gateway.
    assert!(matches!(
        mgm.create_object(
            FEED,
            &[Property::new(
                CREATE_INCLUDE_GATEWAY,
                AnyValue::Boolean(true)
            )]
        ),
        Err(MgmError::CannotMeetCriteria(_))
    ));
    // A reference the MGM did not create.
    let (other, _) = Mgm::default().create_object("IDL:Y:1.0", &[]).unwrap();
    let mut foreign = other.clone();
    foreign.profiles[0] = zerodds_corba_ior::miop::UipmcProfileBody::new(
        "239.1.1.1",
        1,
        vec![GroupInfo::new("Elsewhere", 1, 1).to_component(Endianness::Big)],
    )
    .to_tagged_profile(Endianness::Big)
    .unwrap();
    assert_eq!(
        mgm.get_object_group_id(&foreign),
        Err(MgmError::ObjectGroupNotFound)
    );
    assert!(matches!(
        mgm.membership_operation("add_member"),
        Err(MgmError::System(_))
    ));
    // A pool of one address is exhausted by one group.
    let small = Mgm::new(AddressPool {
        first: "239.255.101.1".parse().unwrap(),
        count: 1,
        port: 7000,
    });
    small.create_object(FEED, &[]).unwrap();
    assert!(matches!(
        small.create_object(FEED, &[]),
        Err(MgmError::CannotMeetCriteria(_))
    ));
}

fn nil_object() -> AnyValue {
    AnyValue::ObjRef {
        type_code: TypeCode::ObjRef {
            repo_id: "IDL:omg.org/CORBA/Object:1.0".into(),
            name: "Object".into(),
        },
        reference: None,
    }
}

/// An MGM served on a new IIOP server, its acceptor and a proxy to it.
fn served_mgm(repository: Option<zerodds_corba_ir::Repository>) -> (Arc<Mgm>, Acceptor, MgmProxy) {
    let server = CorbaServer::new();
    let acceptor = server.serve("127.0.0.1:0".parse().unwrap()).unwrap();
    let mut mgm = Mgm::new(AddressPool::default());
    if let Some(r) = repository {
        mgm = mgm.with_interface_repository(Arc::new(r));
    }
    let mgm = mgm
        .serve(&server, "127.0.0.1", acceptor.listen_addr().port(), b"MGM")
        .unwrap();
    let proxy = MgmProxy::new(
        mgm.reference().unwrap().clone(),
        Arc::new(IiopCorbaConnection::new()),
    );
    (mgm, acceptor, proxy)
}

/// `Shop::Feed : Shop::Base` in an interface repository.
fn feed_repository() -> zerodds_corba_ir::Repository {
    use zerodds_corba_ir::{DefDetails, Definition, DefinitionKind, Repository};
    let mut r = Repository::new();
    r.register(
        Definition::new(FEED, "Feed", "1.0", DefinitionKind::Interface).with_details(
            DefDetails::Interface {
                base_interfaces: vec!["IDL:Shop/Base:1.0".into()],
                is_abstract: false,
            },
        ),
    )
    .unwrap();
    r.register(Definition::new(
        "IDL:Shop/Base:1.0",
        "Base",
        "1.0",
        DefinitionKind::Interface,
    ))
    .unwrap();
    r
}

fn call_bool(
    conn: &IiopCorbaConnection,
    target: &ObjectReference,
    op: &str,
    arg: Option<&str>,
) -> bool {
    let mut w = zerodds_wire::Writer::new(Endianness::Big);
    if let Some(a) = arg {
        w.write_string(a);
    }
    let (body, e) = conn
        .invoke(target, op, Endianness::Big, &marshaled_body(&w.finish(), 0))
        .unwrap();
    zerodds_wire::Reader::new(&body, e).read_bool().unwrap()
}

#[test]
fn corba_p2_11_2_6_8_3_implicit_operations_go_into_the_group_iiop_component() {
    let oma = iiop_ref("oma.example", 1234, b"oma");
    let mgm = Mgm::default();
    let (ior, _) = mgm
        .create_object(
            FEED,
            &[Property::new(SUPPORT_IMPLICIT_OPERATIONS, object(&oma))],
        )
        .unwrap();
    let u = &group_profiles(&ior).unwrap().uipmc[0];
    assert_eq!(u.group_iiop_profile().unwrap().unwrap().host, "oma.example");
    // A nil object names the MGM; an MGM that is not served has no
    // reference to put there.
    let nil = Property::new(SUPPORT_IMPLICIT_OPERATIONS, nil_object());
    assert!(matches!(
        mgm.create_object(FEED, std::slice::from_ref(&nil)),
        Err(MgmError::CannotMeetCriteria(_))
    ));
    assert_eq!(
        mgm.set_properties_dynamically(&ior, std::slice::from_ref(&nil)),
        Err(MgmError::InvalidProperty(Box::new(nil.clone())))
    );
    // A served MGM puts the object of the group under its own address.
    let (served, acceptor, _proxy) = served_mgm(Some(feed_repository()));
    let (group, creation_id) = served.create_object(FEED, &[nil]).unwrap();
    let u = &group_profiles(&group).unwrap().uipmc[0];
    let body = u.group_iiop_profile().unwrap().unwrap();
    assert_eq!(
        (body.host.as_str(), body.port),
        ("127.0.0.1", acceptor.listen_addr().port())
    );
    assert_eq!(body.object_key, b"MGM/group/1");
    // Over IIOP the MGM answers the operations of CORBA::Object for the
    // group (§11.2.6.10, §11.3.2).
    let conn = IiopCorbaConnection::new();
    let client = MiopClient::new();
    assert!(client.is_a(&group, FEED, &conn).unwrap());
    assert!(client.is_a(&group, "IDL:Shop/Base:1.0", &conn).unwrap());
    assert!(!client.is_a(&group, "IDL:Other:1.0", &conn).unwrap());
    let oma = two_way_reference(&group).unwrap();
    assert!(!call_bool(&conn, &oma, "_non_existent", None));
    let err = conn
        .invoke(&oma, "price", Endianness::Big, &no_arguments)
        .unwrap_err();
    assert!(
        matches!(&err, CorbaException::System(e) if e.kind == SystemExceptionKind::NoImplement),
        "{err:?}"
    );
    // A deleted group: is_a false, non_existent true (§11.3.2).
    served.delete_object(&creation_id).unwrap();
    assert!(!call_bool(&conn, &oma, "_is_a", Some(FEED)));
    assert!(call_bool(&conn, &oma, "_non_existent", None));
    let err = conn
        .invoke(&oma, "_repository_id", Endianness::Big, &no_arguments)
        .unwrap_err();
    assert!(
        matches!(&err, CorbaException::System(e) if e.kind == SystemExceptionKind::ObjectNotExist),
        "{err:?}"
    );
}

#[test]
fn corba_p2_11_3_3_1_1_the_mgm_is_called_over_iiop() {
    let (mgm, _acceptor, proxy) = served_mgm(None);
    // The object of the MGM itself.
    let conn = IiopCorbaConnection::new();
    let me = mgm.reference().unwrap().clone();
    assert_eq!(me.type_id, OBJECT_GROUP_FACTORY_REPOSITORY_ID);
    assert!(call_bool(
        &conn,
        &me,
        "_is_a",
        Some("IDL:omg.org/PortableGroup/GenericFactory:1.0")
    ));
    assert!(call_bool(
        &conn,
        &me,
        "_is_a",
        Some(OBJECT_GROUP_FACTORY_REPOSITORY_ID)
    ));
    assert!(!call_bool(&conn, &me, "_non_existent", None));
    // PropertyManager.
    proxy
        .set_default_properties(&[Property::new(GROUP_DOMAIN_ID, AnyValue::Str("Shop".into()))])
        .unwrap();
    proxy
        .set_type_properties(
            FEED,
            &[
                mode(CREATE_ADDRESS_SUPPLIED),
                address("225.3.3.3"),
                port(6100),
            ],
        )
        .unwrap();
    assert_eq!(proxy.get_default_properties().unwrap().len(), 1);
    assert_eq!(proxy.get_type_properties(FEED).unwrap().len(), 4);
    // GenericFactory and ObjectGroupManager.
    let (group, creation_id) = proxy.create_object(FEED, &[port(6101)]).unwrap();
    assert_eq!(creation_id, CorbaAny(AnyValue::ULongLong(1)));
    let g = group_profiles(&group).unwrap();
    assert_eq!(g.groups, vec![GroupInfo::new("Shop", 1, 1)]);
    assert_eq!(
        (g.uipmc[0].the_address.as_str(), g.uipmc[0].the_port),
        ("225.3.3.3", 6101)
    );
    assert_eq!(proxy.get_object_group_id(&group).unwrap(), 1);
    proxy
        .set_properties_dynamically(&group, &[port(6102)])
        .unwrap();
    let now = proxy.get_object_group_ref(&group).unwrap();
    assert_eq!(group_profiles(&now).unwrap().uipmc[0].the_port, 6102);
    assert_eq!(
        group_profiles(&now).unwrap().groups[0].object_group_ref_version,
        2
    );
    let props = proxy.get_properties(&now).unwrap();
    assert!(props.contains(&port(6102)), "{props:?}");
    proxy.remove_type_properties(FEED, &[port(0)]).unwrap();
    assert_eq!(proxy.get_type_properties(FEED).unwrap().len(), 3);
    proxy
        .remove_default_properties(&[Property::new(GROUP_DOMAIN_ID, AnyValue::Str(String::new()))])
        .unwrap();
    assert!(proxy.get_default_properties().unwrap().is_empty());
    // The exceptions come back with their members.
    let nonsense = Property::new("org.omg.mgm.Nonsense", AnyValue::Long(1));
    assert_eq!(
        proxy.set_default_properties(std::slice::from_ref(&nonsense)),
        Err(MgmError::UnsupportedProperty {
            nam: nonsense.nam.clone()
        })
    );
    assert_eq!(
        proxy.create_object(FEED, std::slice::from_ref(&nonsense)),
        Err(MgmError::InvalidCriteria(vec![nonsense]))
    );
    assert_eq!(
        proxy.create_object(FEED, &[mode(9)]),
        Err(MgmError::InvalidProperty(Box::new(mode(9))))
    );
    assert_eq!(
        proxy.create_object("IDL:Other:1.0", &[mode(CREATE_ADDRESS_SUPPLIED)]),
        Err(MgmError::CannotMeetCriteria(vec![mode(
            CREATE_ADDRESS_SUPPLIED
        )]))
    );
    proxy.delete_object(&creation_id).unwrap();
    assert_eq!(
        proxy.get_object_group_ref(&group),
        Err(MgmError::ObjectGroupNotFound)
    );
    assert_eq!(
        proxy.delete_object(&creation_id),
        Err(MgmError::ObjectNotFound)
    );
    // Membership is not the MGM's (§11.2.6.5); an unknown operation is
    // BAD_OPERATION; arguments that do not decode are MARSHAL.
    for (op, kind) in [
        ("add_member", SystemExceptionKind::NoImplement),
        ("no_such_operation", SystemExceptionKind::BadOperation),
        ("get_object_group_id", SystemExceptionKind::Marshal),
    ] {
        let err = conn
            .invoke(&me, op, Endianness::Big, &marshaled_body(&[1, 2], 0))
            .unwrap_err();
        assert!(
            matches!(&err, CorbaException::System(e) if e.kind == kind),
            "{op}: {err:?}"
        );
    }
}

#[test]
fn corba_p2_11_3_3_1_a_group_the_mgm_created_is_reached_over_multicast() {
    let mgm = Mgm::new(AddressPool {
        first: "239.255.102.1".parse().unwrap(),
        count: 4,
        port: 31_000 + (std::process::id() % 1000) as u16,
    });
    let (group, _) = mgm.create_object(FEED, &[]).unwrap();
    let goa = Goa::new();
    let id = goa.create_id_for_reference(&group).unwrap();
    let calls: Arc<Mutex<Vec<String>>> = Arc::default();
    let c = Arc::clone(&calls);
    goa.activate_object_with_id(&id, move |op, _b, _e| {
        c.lock().unwrap().push(op.to_string());
        SkeletonResult::Reply(Vec::new())
    });
    MiopClient::new()
        .send_oneway(&group, "price", Endianness::Big, &marshaled_body(b"1", 0))
        .unwrap();
    let deadline = Instant::now() + Duration::from_secs(5);
    while calls.lock().unwrap().is_empty() && Instant::now() < deadline {
        std::thread::sleep(Duration::from_millis(10));
    }
    assert_eq!(calls.lock().unwrap().as_slice(), ["price".to_string()]);
}
