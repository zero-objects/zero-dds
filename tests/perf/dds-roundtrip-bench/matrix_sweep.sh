#!/usr/bin/env bash
# SPDX-License-Identifier: Apache-2.0
#
# matrix_sweep.sh — cross-vendor roundtrip matrix with payload sweep.
#
# Runs each vendor as ping against each vendor as pong (incl. self,
# 5x5 = 25 cells) for each payload size 0..8192 bytes in 10%
# steps (11 points) — 275 cells. Per cell, `REPEAT_RUNS`
# independent runs are made (default 5); the line with the lowest
# p50 goes into the main CSV — "min-of-medians" lowers
# co-tenant jitter from the virtualisation host (load typically 12+ on 16 cores) to
# below 5%. All runs also land in `matrix_runs_raw.csv`
# for inspecting the spread.
#
# Usage (on x86-host):
#   tests/perf/dds-roundtrip-bench/matrix_sweep.sh [out_dir]
#   REPEAT_RUNS=N tests/perf/dds-roundtrip-bench/matrix_sweep.sh [out_dir]
#
# Prerequisite: the five <vendor>-roundtrip binaries are built in
# build/; Cyclone/Fast-DDS/RTI/OpenDDS installed (paths below).

set -u

BENCH_DIR="$(cd "$(dirname "$0")" && pwd)"
BUILD_DIR="$BENCH_DIR/build"
ZD_REPO="$(cd "$BENCH_DIR/../../.." && pwd)"
# OPENDDS_INI overrides the OpenDDS transport config, e.g.
# opendds_rtps_shm.ini for the self pairs over each stack's own shared memory.
INI="${OPENDDS_INI:-$BENCH_DIR/opendds_rtps.ini}"
OUT_DIR="${1:-$BENCH_DIR/matrix-out}"
mkdir -p "$OUT_DIR"
CSV="$OUT_DIR/matrix_results.csv"
RAW_CSV="$OUT_DIR/matrix_runs_raw.csv"
REPORT="$OUT_DIR/matrix_report.md"
LOAD_CSV="$OUT_DIR/cell_load.csv"

SAMPLES="${BENCH_SAMPLES:-2000}"
# LOAD_MAX gates every run on the host's 1-minute load: the Linux test host is an LXC
# guest and /proc/loadavg is the hypervisor's, which other guests drive (it
# read 27 at the start of the run of 2026-10-02 afternoon, 0.7-1.6 on 09-30).
# Unset, nothing waits. Set, a run starts only below LOAD_MAX, waits at most
# LOAD_WAIT seconds (default 1800) and runs anyway after that; either way the
# load it started under goes to cell_load.csv next to the CSV. LOAD_BUDGET
# (default 2 x LOAD_WAIT) caps the waiting of the whole sweep: under a load
# that never drops, 360 runs would otherwise wait 1800 s each.
LOAD_MAX="${LOAD_MAX:-}"
LOAD_WAIT="${LOAD_WAIT:-1800}"
LOAD_BUDGET="${LOAD_BUDGET:-$((2 * LOAD_WAIT))}"
WARMUP="${BENCH_WARMUP:-200}"
REPEAT_RUNS="${REPEAT_RUNS:-5}"
# BENCH_VENDORS overrides the set, e.g. without rti while its licence is
# expired: BENCH_VENDORS="zerodds cyclone fastdds opendds opensplice".
read -r -a VENDORS <<< "${BENCH_VENDORS:-zerodds cyclone fastdds rti opendds}"
# 0..8192 bytes in 10% steps (11 points), rounded.
# BENCH_PAYLOADS overrides it, e.g. "0" for a short trial over every pair.
read -r -a PAYLOADS <<< "${BENCH_PAYLOADS:-0 819 1638 2458 3277 4096 4915 5734 6554 7373 8192}"
# BENCH_KIND=rich runs the <vendor>-roundtrip-rich apps (RoundtripRich: a
# string, a double[16] and a sequence of nested structs) instead of the basis
# type. BENCH_SECURITY=1 turns DDS-Security 1.2 on for every app (governance
# with data_protection=ENCRYPT, domain 200 as the governance's domain rule,
# the assets of security/, generated by `bash security/gen.sh`), as
# sec_matrix.sh did for one run per cell; RTI's security plugin is not
# licensed here and OpenSplice CE has none.
KIND="${BENCH_KIND:-basis}"
case "$KIND" in
    basis) SUFFIX="-roundtrip" ;;
    rich)  SUFFIX="-roundtrip-rich" ;;
    *) echo "BENCH_KIND must be basis or rich, not $KIND" >&2; exit 2 ;;
esac
SECURITY="${BENCH_SECURITY:-0}"
SECDIR="${BENCH_SEC_DIR:-$BENCH_DIR/security}"
# BENCH_WITH restricts the sweep to the pairs with that vendor on one side,
# e.g. BENCH_WITH=zerodds to re-measure after a change to ZeroDDS alone;
# the pairs without it keep their cells from the full run.
WITH="${BENCH_WITH:-}"
in_scope() { [ -z "$WITH" ] || [ "$1" = "$WITH" ] || [ "$2" = "$WITH" ]; }

# Every pair over UDPv4, the ZeroDDS self pair included: ZeroDDS would take
# its same-host shared-memory carrier for a ZeroDDS peer, and a table that
# puts that next to the other stacks' UDPv4 compares transports, not stacks.
# ZERODDS_SAME_HOST_SHM=1 measures the carrier on purpose.
export ZERODDS_SAME_HOST_SHM="${ZERODDS_SAME_HOST_SHM:-0}"

# --- Vendor runtime environment ---
# Caller-overrideable defaults — if already set (e.g. a macOS host
# with vendors in $HOME/dds-prefix), we leave them. Only the Linux
# x86-host fills in the default paths.
: "${NDDSHOME:=/opt/rti.com/rti_connext_dds-7.7.0}"
: "${RTI_LICENSE_FILE:=$NDDSHOME/rti_license.dat}"
export NDDSHOME RTI_LICENSE_FILE
if [ "$(uname)" = Linux ]; then
    : "${LD_LIBRARY_PATH:=/opt/cyclone/lib:/opt/fastdds/lib:$NDDSHOME/lib/x64Linux4gcc8.5.0:$ZD_REPO/target/release}"
    export LD_LIBRARY_PATH
    # OpenDDS service participant env (DCPSInfoRepo etc.) — best effort.
    # shellcheck disable=SC1091
    [ -n "${OPENDDS_SRC:-}" ] && . "$OPENDDS_SRC/setenv.sh" 2>/dev/null || true
elif [ "$(uname)" = Darwin ]; then
    # macOS SIP strips DYLD_LIBRARY_PATH on exec of Apple-signed
    # binaries (e.g. /bin/bash). Re-export here in the script body, because
    # the bash process itself is SIP-protected and loses the env
    # on spawn. `DYLD_LIBRARY_PATH_OVERRIDE` is a caller convention; the
    # value is mirrored here into the real DYLD_LIBRARY_PATH.
    if [ -n "${DYLD_LIBRARY_PATH_OVERRIDE:-}" ]; then
        export DYLD_LIBRARY_PATH="$DYLD_LIBRARY_PATH_OVERRIDE"
    else
        # Default macOS paths for Cyclone/Fast-DDS/RTI in $HOME/dds-prefix
        # or the RTI install in $HOME/y.
        : "${DYLD_LIBRARY_PATH:=$ZD_REPO/target/release:$HOME/dds-prefix/lib:$HOME/y/rti_connext_dds-7.7.0/lib/arm64Darwin23clang16.0}"
        export DYLD_LIBRARY_PATH
    fi
fi

cd "$BUILD_DIR" || { echo "build dir missing: $BUILD_DIR" >&2; exit 1; }

for v in "${VENDORS[@]}"; do
    [ -x "./${v}${SUFFIX}" ] || { echo "Binary missing: ${v}${SUFFIX}" >&2; exit 1; }
    if [ "$SECURITY" = 1 ]; then
        case "$v" in
            rti|opensplice) echo "no security for $v on this host (see BENCH_SECURITY)" >&2; exit 1 ;;
        esac
    fi
done
if [ "$SECURITY" = 1 ] && [ ! -f "$SECDIR/governance.p7s" ]; then
    echo "security assets missing in $SECDIR: run bash security/gen.sh" >&2; exit 1
fi
# The pairs with OpenSplice run in XCDR1 (below); ZeroDDS needs its XCDR1 build.
case " ${VENDORS[*]} " in
    *" opensplice "*) [ -x "./zerodds-xcdr1-roundtrip" ] || {
        echo "Binary missing: zerodds-xcdr1-roundtrip (needed for the pairs with opensplice)" >&2; exit 1; } ;;
esac

# The data representation of a pair: XCDR2 as in the matrix of 23.05., and
# XCDR1 when OpenSplice is one side — it writes and reads XCDR1 only. The
# apps read it from ZERODDS_BENCH_REPR; ZeroDDS has one codec per build, so
# its XCDR1 pairs run zerodds-xcdr1-roundtrip.
pair_repr() { case " $1 $2 " in *" opensplice "*) echo XCDR1 ;; *) echo XCDR2 ;; esac; }
binary_of() { # <vendor> <repr>
    if [ "$1" = zerodds ] && [ "$2" = XCDR1 ]; then echo "./zerodds-xcdr1${SUFFIX}"; else echo "./$1${SUFFIX}"; fi
}

# OpenDDS binaries need -DCPSConfigFile; the others do not.
extra_args() {
    [ "$1" = opendds ] || return 0
    if [ "$SECURITY" = 1 ]; then
        printf '%s' "-DCPSConfigFile $BENCH_DIR/opendds_rtps_sec.ini"
    else
        printf '%s' "-DCPSConfigFile $INI"
    fi
}

# The environment one app runs in: its data representation, and with
# BENCH_SECURITY the security configuration sec_matrix.sh gave each vendor
# (<vendor> <role> <repr>, one assignment per line).
app_env() {
    echo "ZERODDS_BENCH_REPR=$3"
    [ "$SECURITY" = 1 ] || return 0
    echo "ZERODDS_BENCH_DOMAIN=200"
    case "$1" in
        cyclone) echo "CYCLONEDDS_URI=file://$SECDIR/cyclone_security_$2.xml" ;;
        *) echo "ZERODDS_BENCH_SECURITY=1"
           echo "ZERODDS_BENCH_SEC_DIR=$SECDIR"
           echo "ZERODDS_BENCH_SEC_NAME=$2" ;;
    esac
}

# Runs one cell; prints the ping result line on stdout
# ("payload=.. n=.. min=.. p50=.. .." or "no samples" or empty).
run_cell() {
    local ping=$1 pong=$2 payload=$3
    local pong_log ping_log repr
    pong_log="$(mktemp)"; ping_log="$(mktemp)"
    repr="$(pair_repr "$ping" "$pong")"

    # pong in the background — generous runtime, killed after ping.
    # shellcheck disable=SC2086
    local -a pong_env ping_env
    mapfile -t pong_env < <(app_env "$pong" pong "$repr")
    mapfile -t ping_env < <(app_env "$ping" ping "$repr")
    env "${pong_env[@]}" "$(binary_of "$pong" "$repr")" pong 60 $(extra_args "$pong") >"$pong_log" 2>&1 &
    local pong_pid=$!

    # OpenDDS pong starts slowly — longer discovery window.
    [ "$pong" = opendds ] && sleep 5 || sleep 3

    # shellcheck disable=SC2086
    env "${ping_env[@]}" timeout 90 "$(binary_of "$ping" "$repr")" ping --payload "$payload" \
        --samples "$SAMPLES" --warmup "$WARMUP" $(extra_args "$ping") \
        >"$ping_log" 2>&1

    kill "$pong_pid" 2>/dev/null
    sleep 0.5
    kill -9 "$pong_pid" 2>/dev/null
    wait "$pong_pid" 2>/dev/null

    # macOS multicast/SHM state needs a real settle gap between cells
    # — otherwise sockets stay stuck in TIME_WAIT and subsequent pongs fail
    # with `Port in use`. 2s is enough for loopback cleanup.
    if [ "$(uname)" = Darwin ]; then sleep 2; fi

    grep -E "payload=|no samples" "$ping_log" | head -1
    rm -f "$pong_log" "$ping_log"
}

# Extracts a "key=NUMBER" field from the result line.
field() { printf '%s' "$1" | grep -oE "$2=[0-9.]+" | head -1 | cut -d= -f2; }

echo "ping_vendor,pong_vendor,payload_bytes,n,min_us,p50_us,p90_us,p99_us,p999_us,max_us,status" >"$CSV"
echo "ping_vendor,pong_vendor,payload_bytes,run_idx,n,min_us,p50_us,p90_us,p99_us,p999_us,max_us,status" >"$RAW_CSV"
echo "ping_vendor,pong_vendor,payload_bytes,run_idx,load1,waited_s" >"$LOAD_CSV"

# Waits for the load gate (see LOAD_MAX) and records the load a run starts
# under. <ping> <pong> <payload> <run>
load_gate() {
    local load waited=0 limit
    load="$(cut -d' ' -f1 /proc/loadavg)"
    if [ -n "$LOAD_MAX" ]; then
        # The caller runs in a command substitution, so the sweep's waiting so
        # far comes from the waited_s column, not from a shell variable.
        limit=$((LOAD_BUDGET - $(awk -F, 'NR>1{s+=$6}END{print s+0}' "$LOAD_CSV")))
        [ "$limit" -gt "$LOAD_WAIT" ] && limit=$LOAD_WAIT
        while awk "BEGIN{exit !($load > $LOAD_MAX)}" && [ "$waited" -lt "$limit" ]; do
            sleep 15; waited=$((waited + 15))
            load="$(cut -d' ' -f1 /proc/loadavg)"
        done
    fi
    echo "$1,$2,$3,$4,$load,$waited" >>"$LOAD_CSV"
}

pairs=0
for ping in "${VENDORS[@]}"; do
    for pong in "${VENDORS[@]}"; do
        in_scope "$ping" "$pong" && pairs=$((pairs + 1))
    done
done
total=$(( pairs * ${#PAYLOADS[@]} ))
idx=0
started="$(date +%s)"

# Runs a cell `REPEAT_RUNS` times, collects all run lines into the
# raw CSV and returns the line with the smallest p50 on stdout
# (or a timeout line if every run failed). This makes the
# main CSV "min-of-medians" — invariant against co-tenant jitter.
run_cell_repeated() {
    local ping=$1 pong=$2 payload=$3
    local best_line="" best_p50="" line p50 r
    for r in $(seq 1 "$REPEAT_RUNS"); do
        load_gate "$ping" "$pong" "$payload" "$r"
        line="$(run_cell "$ping" "$pong" "$payload")"
        if [ -z "$line" ] || ! printf '%s' "$line" | grep -q "payload="; then
            # Retry immediately, otherwise mark as timeout/no-samples.
            sleep 1
            line="$(run_cell "$ping" "$pong" "$payload")"
        fi
        if printf '%s' "$line" | grep -q "payload="; then
            p50="$(field "$line" p50)"
            local rn rm rp50 rp90 rp99 rp999 rmx
            rn="$(field "$line" n)"
            rm="$(field "$line" min)"
            rp50="$p50"
            rp90="$(field "$line" p90)"
            rp99="$(field "$line" p99)"
            rp999="$(field "$line" p999)"
            rmx="$(field "$line" max)"
            echo "$ping,$pong,$payload,$r,$rn,$rm,$rp50,$rp90,$rp99,$rp999,$rmx,ok" >>"$RAW_CSV"
            if [ -z "$best_p50" ] || awk "BEGIN{exit !($p50 < $best_p50)}"; then
                best_p50="$p50"
                best_line="$line"
            fi
        else
            local st
            if [ -z "$line" ]; then st=timeout; else st=no-samples; fi
            echo "$ping,$pong,$payload,$r,0,,,,,,,$st" >>"$RAW_CSV"
            # A pair without a result in its first run and that run's retry
            # does not get four more: they cost 90 s each and say the same.
            [ "$r" = 1 ] && [ -z "$best_line" ] && break
        fi
        # Multicast/socket cleanup gap between repetitions.
        sleep 1
    done
    # Return best-of-N (smallest p50); empty = all runs failed.
    printf '%s' "$best_line"
}

for payload in "${PAYLOADS[@]}"; do
    for ping in "${VENDORS[@]}"; do
        for pong in "${VENDORS[@]}"; do
            in_scope "$ping" "$pong" || continue
            idx=$((idx + 1))
            printf '[%3d/%d] payload=%-5d %-8s -> %-8s ' \
                "$idx" "$total" "$payload" "$ping" "$pong"

            line="$(run_cell_repeated "$ping" "$pong" "$payload")"

            if printf '%s' "$line" | grep -q "payload="; then
                n="$(field "$line" n)"
                mn="$(field "$line" min)"
                p50="$(field "$line" p50)"
                p90="$(field "$line" p90)"
                p99="$(field "$line" p99)"
                p999="$(field "$line" p999)"
                mx="$(field "$line" max)"
                status=ok
                printf 'p50_min=%s us (N=%d runs)\n' "$p50" "$REPEAT_RUNS"
            else
                n=0; mn=; p50=; p90=; p99=; p999=; mx=
                status=timeout
                # Only run 1 can end here: a result in it sets the best
                # line, and without one run_cell_repeated stops.
                printf 'FAIL (run 1 and its retry without a result; no further runs)\n'
            fi

            echo "$ping,$pong,$payload,$n,$mn,$p50,$p90,$p99,$p999,$mx,$status" >>"$CSV"
        done
    done
done

elapsed=$(( $(date +%s) - started ))
echo
echo "Matrix done in $((elapsed / 60)) min $((elapsed % 60)) s."
echo "CSV:    $CSV"

if python3 "$BENCH_DIR/matrix_report.py" "$CSV" >"$REPORT" 2>/dev/null; then
    echo "Report: $REPORT"
else
    echo "Report generation failed — the CSV is complete." >&2
fi
