// HDDS roundtrip bench app: the row `hdds` of the speed setup
// (tests/perf/speed/speed.py, rc8-plan.md D1). The same modes, environment
// and output lines as the C++ apps of this directory (bench_common.hpp),
// over the HDDS Rust API, the one its C and C++ SDKs wrap.
//
// Why Rust and not C++ like the other vendors' apps: the C SDK of HDDS
// v1.1.5 answers `hdds_reader_set_listener` with HddsUnsupported
// ("not yet implemented", crates/hdds-c/src/listener.rs), and every app here
// takes its samples in a listener. The Rust API calls a DataReaderListener.
//
// Type: roundtrip.idl, generated by build.rs with hddsgen (HDDS's IDL code
// generator, git.hdds.io/hdds/hdds_gen).
//
// What differs from the C++ apps, because the HDDS API has no counterpart:
// - the listener receives the decoded sample (`on_data_available(&T)`) and
//   HDDS also keeps it in the reader's cache; the listener takes the cache
//   empty, so a KEEP_ALL reader does not fill up with samples it has seen;
// - matching is read from the listeners' matched callbacks (the DataWriter
//   and DataReader of HDDS have no matched-status getter);
// - the DataWriter has no wait_for_acknowledgments: `acked=-1` for RELIABLE
//   as for BEST_EFFORT, and the 2 s linger before the writer goes;
// - UDPv4 for every pair as for the other stacks: HDDS takes its
//   shared-memory transport between two BEST_EFFORT endpoints of one host
//   unless told otherwise (ShmPolicy::Prefer, crates/hdds/src/transport/shm/
//   policy.rs), so the participants are built with `shm_disable()`, and with
//   ZERODDS_BENCH_TRANSPORT=SHM with `shm_require()`.

use std::sync::atomic::{AtomicU32, AtomicU64, Ordering};
use std::sync::{Arc, Condvar, Mutex, OnceLock};
use std::time::{Duration, Instant};

use hdds::dds::{
    DataReaderListener, DataWriterListener, PublicationMatchedStatus, SubscriptionMatchedStatus,
};
use hdds::{DataReader, DataWriter, Participant, QoS, TransportMode};

#[allow(dead_code, non_snake_case, clippy::all)]
mod generated {
    include!(concat!(env!("OUT_DIR"), "/roundtrip.rs"));
}
use generated::RoundtripBench::Roundtrip as Sample;

const REQ_TOPIC: &str = "RoundtripBench_Request";
const ECHO_TOPIC: &str = "RoundtripBench_Echo";

fn now_ns() -> u64 {
    static START: OnceLock<Instant> = OnceLock::new();
    START.get_or_init(Instant::now).elapsed().as_nanos() as u64
}

/// CPU time of the whole process, every thread of the stack included
/// (CLOCK_PROCESS_CPUTIME_ID), as bench::cpu_ns().
fn cpu_ns() -> u64 {
    let mut ts = libc::timespec {
        tv_sec: 0,
        tv_nsec: 0,
    };
    // SAFETY: clock_gettime writes the timespec it is given.
    unsafe { libc::clock_gettime(libc::CLOCK_PROCESS_CPUTIME_ID, &mut ts) };
    ts.tv_sec as u64 * 1_000_000_000 + ts.tv_nsec as u64
}

// ------------------------------------------------------------------ QoS

/// bench::QosSpec from the same variables.
struct QosSpec {
    reliable: bool,
    keep_all: bool,
    depth: u32,
    max_samples: i64,
}

fn qos_from_env() -> QosSpec {
    let mut q = QosSpec {
        reliable: true,
        keep_all: false,
        depth: 64,
        max_samples: -1,
    };
    if let Ok(v) = std::env::var("ZERODDS_BENCH_RELIABILITY") {
        match v.as_str() {
            "besteffort" | "best_effort" | "be" => q.reliable = false,
            "reliable" => q.reliable = true,
            _ => {
                eprintln!("ZERODDS_BENCH_RELIABILITY={v} unknown");
                std::process::exit(2);
            }
        }
    }
    if let Ok(v) = std::env::var("ZERODDS_BENCH_HISTORY") {
        if v == "all" {
            q.keep_all = true;
        } else {
            match v.parse::<u32>() {
                Ok(d) if d >= 1 => q.depth = d,
                _ => {
                    eprintln!("ZERODDS_BENCH_HISTORY={v} unknown");
                    std::process::exit(2);
                }
            }
        }
    }
    if let Ok(v) = std::env::var("ZERODDS_BENCH_MAX_SAMPLES") {
        q.max_samples = v.parse().unwrap_or(-1);
    }
    q
}

fn print_qos(role: &str, q: &QosSpec) {
    let history = if q.keep_all {
        "keep_all".to_string()
    } else {
        format!("keep_last({})", q.depth)
    };
    println!(
        "qos[{role}]: reliability={} history={history} max_samples={}",
        if q.reliable { "reliable" } else { "besteffort" },
        q.max_samples
    );
}

/// The QoS of both endpoints. RESOURCE_LIMITS: max_samples and
/// max_samples_per_instance as the other apps set them; HDDS also bounds a
/// RELIABLE history by bytes (`max_quota_bytes`, 100 MB by default,
/// crates/hdds/src/qos.rs), which would refuse the 2048 samples of 64 KiB
/// the setup asks for before their count, so it is raised to hold them.
fn hdds_qos(q: &QosSpec, payload_hint: usize) -> QoS {
    let mut qos = if q.reliable {
        QoS::reliable()
    } else {
        QoS::best_effort()
    };
    qos = if q.keep_all {
        qos.keep_all()
    } else {
        qos.keep_last(q.depth)
    };
    if q.max_samples > 0 {
        let n = q.max_samples as usize;
        qos.resource_limits.max_samples = n;
        qos.resource_limits.max_samples_per_instance = n;
        qos.resource_limits.max_quota_bytes = qos
            .resource_limits
            .max_quota_bytes
            .max(n * (payload_hint + 64));
    }
    qos
}

fn domain() -> u32 {
    std::env::var("ZERODDS_BENCH_DOMAIN")
        .ok()
        .and_then(|s| s.parse().ok())
        .unwrap_or(200)
}

fn participant(name: &str) -> Arc<Participant> {
    let builder = Participant::builder(name)
        .with_transport(TransportMode::UdpMulticast)
        .domain_id(domain());
    let builder = match std::env::var("ZERODDS_BENCH_TRANSPORT").as_deref() {
        Ok("SHM") => builder.shm_require(),
        _ => builder.shm_disable(),
    };
    match builder.build() {
        Ok(p) => p,
        Err(e) => {
            eprintln!("hdds-app: participant: {e:?}");
            std::process::exit(1);
        }
    }
}

fn writer(p: &Arc<Participant>, topic: &str, qos: QoS, l: Arc<Matched>) -> DataWriter<Sample> {
    let w = p
        .topic::<Sample>(topic)
        .and_then(|t| t.writer().qos(qos).with_listener(l).build());
    w.unwrap_or_else(|e| {
        eprintln!("hdds-app: writer {topic}: {e:?}");
        std::process::exit(1);
    })
}

fn reader(
    p: &Arc<Participant>,
    topic: &str,
    qos: QoS,
    l: Arc<dyn DataReaderListener<Sample>>,
) -> Arc<DataReader<Sample>> {
    let r = p
        .topic::<Sample>(topic)
        .and_then(|t| t.reader().qos(qos).with_listener(l).build());
    Arc::new(r.unwrap_or_else(|e| {
        eprintln!("hdds-app: reader {topic}: {e:?}");
        std::process::exit(1);
    }))
}

// ------------------------------------------------------------ listeners

/// The current matched count of a writer, from its listener.
#[derive(Default)]
struct Matched {
    current: AtomicU32,
}

impl DataWriterListener<Sample> for Matched {
    fn on_publication_matched(&self, status: PublicationMatchedStatus) {
        self.current.store(status.current_count, Ordering::SeqCst);
    }
}

/// A reader's listener: what to do with a sample, the reader's matched
/// count, and the reader itself to take its cache empty after each sample.
struct OnSample<F: Fn(&Sample) + Send + Sync> {
    f: F,
    matched: AtomicU32,
    reader: OnceLock<Arc<DataReader<Sample>>>,
}

impl<F: Fn(&Sample) + Send + Sync> OnSample<F> {
    fn new(f: F) -> Arc<Self> {
        Arc::new(Self {
            f,
            matched: AtomicU32::new(0),
            reader: OnceLock::new(),
        })
    }
}

impl<F: Fn(&Sample) + Send + Sync> DataReaderListener<Sample> for OnSample<F> {
    fn on_data_available(&self, sample: &Sample) {
        (self.f)(sample);
        if let Some(r) = self.reader.get() {
            while let Ok(Some(_)) = r.take() {}
        }
    }
    fn on_subscription_matched(&self, status: SubscriptionMatchedStatus) {
        self.matched.store(status.current_count, Ordering::SeqCst);
    }
}

fn make_sample(payload: usize) -> Sample {
    Sample {
        sequence_id: 0,
        t_send_ns: 0,
        payload: vec![0xAB; payload],
    }
}

// ----------------------------------------------------------- ping / pong

fn run_pong(max_runtime_s: u64) -> i32 {
    let q = qos_from_env();
    let p = participant("hdds-pong");
    let w_matched = Arc::new(Matched::default());
    // The DataWriter of HDDS is not Sync (a RefCell inside), so the
    // listener, called from HDDS's own threads, reaches it through a mutex.
    let w = Arc::new(Mutex::new(writer(
        &p,
        ECHO_TOPIC,
        hdds_qos(&q, 65536),
        w_matched,
    )));
    let w2 = Arc::clone(&w);
    let l = OnSample::new(move |s: &Sample| {
        // A write refused (KEEP_ALL with unacknowledged samples) is a lost
        // echo, not the end.
        let _ = w2.lock().unwrap().write(s);
    });
    let r = reader(&p, REQ_TOPIC, hdds_qos(&q, 65536), l.clone());
    let _ = l.reader.set(Arc::clone(&r));
    println!("pong: matched, listener registered");
    std::thread::sleep(Duration::from_secs(max_runtime_s));
    0
}

struct PingState {
    mu: Mutex<(u64, Vec<u64>)>,
    cv: Condvar,
    warmup: u64,
}

fn print_quantiles(rtts: &mut [u64], payload: usize) {
    if rtts.is_empty() {
        println!("no samples");
        return;
    }
    rtts.sort_unstable();
    let pct =
        |p: f64| rtts[((p * (rtts.len() - 1) as f64) as usize).min(rtts.len() - 1)] as f64 / 1000.0;
    println!(
        "payload={payload}  n={}  min={}us  p50={}us  p90={}us  p99={}us  p999={}us  max={}us",
        rtts.len(),
        rtts[0] as f64 / 1000.0,
        pct(0.50),
        pct(0.90),
        pct(0.99),
        pct(0.999),
        rtts[rtts.len() - 1] as f64 / 1000.0
    );
}

fn run_ping(payload: usize, warmup: u64, samples: u64, max_seconds: u64) -> i32 {
    let q = qos_from_env();
    let p = participant("hdds-ping");
    let w_matched = Arc::new(Matched::default());
    let w = writer(&p, REQ_TOPIC, hdds_qos(&q, payload), Arc::clone(&w_matched));
    let st = Arc::new(PingState {
        mu: Mutex::new((0, Vec::with_capacity(samples as usize))),
        cv: Condvar::new(),
        warmup,
    });
    let st2 = Arc::clone(&st);
    let l = OnSample::new(move |s: &Sample| {
        let now = now_ns();
        let rtt = now.saturating_sub(s.t_send_ns).max(1);
        let mut g = st2.mu.lock().unwrap();
        if g.0 >= st2.warmup {
            g.1.push(rtt);
        }
        g.0 += 1;
        drop(g);
        st2.cv.notify_all();
    });
    let r = reader(&p, ECHO_TOPIC, hdds_qos(&q, payload), l.clone());
    let _ = l.reader.set(Arc::clone(&r));

    // Both directions matched, at most 10 s, then 100 ms for the reliable
    // handshake, as the C++ apps wait.
    let deadline = Instant::now() + Duration::from_secs(10);
    while Instant::now() < deadline {
        if w_matched.current.load(Ordering::SeqCst) >= 1 && l.matched.load(Ordering::SeqCst) >= 1 {
            break;
        }
        std::thread::sleep(Duration::from_millis(10));
    }
    if w_matched.current.load(Ordering::SeqCst) == 0 || l.matched.load(Ordering::SeqCst) == 0 {
        eprintln!(
            "ping: match timeout (pub={} sub={})",
            w_matched.current.load(Ordering::SeqCst) >= 1,
            l.matched.load(Ordering::SeqCst) >= 1
        );
    }
    std::thread::sleep(Duration::from_millis(100));

    let mut msg = make_sample(payload);
    let total = warmup + samples;
    let stop = if max_seconds > 0 {
        now_ns() + max_seconds * 1_000_000_000
    } else {
        0
    };
    let mut sent = 0u64;
    let mut seq = 0u64;
    while seq < total && !(stop != 0 && now_ns() >= stop) {
        msg.sequence_id = seq as u32;
        msg.t_send_ns = now_ns();
        let _ = w.write(&msg);
        let g = st.mu.lock().unwrap();
        let _ = st
            .cv
            .wait_timeout_while(g, Duration::from_millis(50), |g| g.0 <= seq);
        seq += 1;
        sent += 1;
    }
    println!("ping-sent: {sent}");
    let mut g = st.mu.lock().unwrap();
    let mut rtts = std::mem::take(&mut g.1);
    drop(g);
    print_quantiles(&mut rtts, payload);
    0
}

// ------------------------------------------------------------ throughput

/// bench::TputSub.
#[derive(Default)]
struct TputSub {
    received: AtomicU64,
    inner: Mutex<TputInner>,
}

#[derive(Default)]
struct TputInner {
    bytes: u64,
    gaps: u64,
    reordered: u64,
    first_seq: u32,
    last_seq: u32,
    t_first_ns: u64,
    t_last_ns: u64,
    any: bool,
}

impl TputSub {
    fn on_sample(&self, seq: u32, len: usize) {
        let now = now_ns();
        let mut s = self.inner.lock().unwrap();
        if !s.any {
            s.any = true;
            s.first_seq = seq;
            s.last_seq = seq;
            s.t_first_ns = now;
        } else {
            let expected = s.last_seq.wrapping_add(1);
            if seq < expected {
                s.reordered += 1;
            } else {
                s.gaps += u64::from(seq - expected);
                s.last_seq = seq;
            }
        }
        s.t_last_ns = now;
        s.bytes += len as u64;
        self.received.fetch_add(1, Ordering::Relaxed);
    }
}

fn run_tput_sub(max_s: u64) -> i32 {
    let q = qos_from_env();
    print_qos("tput-sub", &q);
    let p = participant("hdds-tput-sub");
    let st = Arc::new(TputSub::default());
    let st2 = Arc::clone(&st);
    let l = OnSample::new(move |s: &Sample| st2.on_sample(s.sequence_id, s.payload.len()));
    let r = reader(&p, REQ_TOPIC, hdds_qos(&q, 65536), l.clone());
    let _ = l.reader.set(Arc::clone(&r));

    // bench::tput_sub_wait_and_report, idle 2000 ms.
    let idle_ms = 2000u64;
    let t0 = now_ns();
    let limit = t0 + max_s * 1_000_000_000;
    let (mut seen, mut cpu_a, mut cnt_a, mut cpu_b, mut cnt_b, mut last_change) =
        (0u64, 0u64, 0u64, 0u64, 0u64, t0);
    let mut started = false;
    loop {
        std::thread::sleep(Duration::from_millis(20));
        let now = now_ns();
        let c = st.received.load(Ordering::Relaxed);
        if c != seen {
            let cpu = cpu_ns();
            if !started {
                started = true;
                cpu_a = cpu;
                cnt_a = c;
            }
            cpu_b = cpu;
            cnt_b = c;
            seen = c;
            last_change = now;
        } else if started && now - last_change > idle_ms * 1_000_000 {
            break;
        }
        if now >= limit {
            break;
        }
    }
    let s = st.inner.lock().unwrap();
    println!(
        "tput-sub: received={} bytes={} first_seq={} last_seq={} gaps={} reordered={} rx_window_ns={} cpu_ns={} cpu_samples={}",
        st.received.load(Ordering::Relaxed),
        s.bytes,
        s.first_seq,
        s.last_seq,
        s.gaps,
        s.reordered,
        s.t_last_ns - s.t_first_ns,
        cpu_b - cpu_a,
        cnt_b - cnt_a
    );
    0
}

fn run_tput_pub(payload: usize, seconds: u64) -> i32 {
    let q = qos_from_env();
    print_qos("tput-pub", &q);
    let p = participant("hdds-tput-pub");
    let matched = Arc::new(Matched::default());
    let w = writer(&p, REQ_TOPIC, hdds_qos(&q, payload), Arc::clone(&matched));

    // bench::tput_wait_matched: 10 s at most, then 500 ms.
    let deadline = Instant::now() + Duration::from_secs(10);
    let mut ok = false;
    while Instant::now() < deadline {
        if matched.current.load(Ordering::SeqCst) >= 1 {
            ok = true;
            break;
        }
        std::thread::sleep(Duration::from_millis(10));
    }
    if !ok {
        eprintln!("tput-pub: no matched reader within 10 s");
    }
    std::thread::sleep(Duration::from_millis(500));

    // bench::tput_pub_run.
    let mut msg = make_sample(payload);
    let (mut written, mut failed) = (0u64, 0u64);
    let mut seq = 0u32;
    let cpu0 = cpu_ns();
    let t0 = now_ns();
    let end = t0 + seconds * 1_000_000_000;
    let mut t1: u64;
    let mut i = 1u64;
    loop {
        msg.sequence_id = seq;
        let accepted = w.write(&msg).is_ok();
        if accepted {
            written += 1;
            seq = seq.wrapping_add(1);
        } else {
            failed += 1;
        }
        if !accepted || i & 15 == 0 {
            t1 = now_ns();
            if t1 >= end {
                break;
            }
        }
        i += 1;
    }
    let cpu = cpu_ns() - cpu0;
    println!(
        "tput-pub: payload={payload} written={written} failed={failed} window_ns={} cpu_ns={cpu} acked=-1 ack_ns=0",
        t1 - t0
    );
    // bench::tput_linger.
    std::thread::sleep(Duration::from_secs(2));
    0
}

// ------------------------------------------------------------------ main

fn flag(args: &[String], name: &str, default: u64) -> u64 {
    // Pairs from args[2] on, `--flag value`, as bench::parse_*_args.
    let mut i = 2;
    while i + 1 < args.len() {
        if args[i] == name {
            return args[i + 1].parse().unwrap_or(default);
        }
        i += 2;
    }
    default
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let _ = now_ns();
    let code = match args.get(1).map(String::as_str) {
        Some("pong") => run_pong(args.get(2).and_then(|s| s.parse().ok()).unwrap_or(30)),
        Some("ping") => run_ping(
            flag(&args, "--payload", 64) as usize,
            flag(&args, "--warmup", 200),
            flag(&args, "--samples", 5000),
            flag(&args, "--max-seconds", 0),
        ),
        Some("tput-sub") => run_tput_sub(flag(&args, "--seconds", 5)),
        Some("tput-pub") => run_tput_pub(
            flag(&args, "--payload", 1024) as usize,
            flag(&args, "--seconds", 5),
        ),
        _ => {
            eprintln!(
                "Usage:\n  hdds-roundtrip pong [max_runtime_s]\n  hdds-roundtrip ping --payload N [--samples N] [--warmup N]\n  hdds-roundtrip tput-sub --seconds MAX\n  hdds-roundtrip tput-pub --payload N --seconds S"
            );
            2
        }
    };
    std::process::exit(code);
}
