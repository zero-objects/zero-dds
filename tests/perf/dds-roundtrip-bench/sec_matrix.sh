#!/usr/bin/env bash
# 4x4 DDS-Security 1.2 cross-vendor roundtrip matrix.
#
# Vendors: cyclone, fastdds, opendds, zerodds (RTI left out —
# its security plugin needs a Pro/LM licence that we deliberately do not
# buy; documented as license-blocked).
#
# Each cell: pong_vendor (echo) + ping_vendor (measurement) on domain 200
# (= governance.xml domain_rule) with DDS-Security active. Sequential,
# process kill + settle between cells against discovery state bleed.
#
# Asset tree: by default the in-repo `security/` directory next to this
# script (CA self-signed variant A — accepted by all four vendors since
# the CmsPkcs7Verifier self-trust fix). The certs + CMS `.p7s` are generated by
# `security/gen.sh` (gitignored); run `bash security/gen.sh` once,
# then the matrix is reproducible from a clean checkout.
#
# Usage:  bash sec_matrix.sh [BUILD_DIR] [SEC_DIR] [SAMPLES]
#   BUILD_DIR  cmake build of the roundtrip apps (default: build-sec)
#   SEC_DIR    asset tree (default: <script-dir>/security)
#   ZERODDS_LIB_DIR  env: path to libzerodds_c_api (default: target/release of the repo)

set -u
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BUILD="${1:-build-sec}"
SECDIR="${2:-$HERE/security}"
SAMPLES="${3:-2000}"
WARMUP=200
PAYLOAD=64
DOMAIN=200
VENDORS=(cyclone fastdds opendds zerodds)
DYLIB_DIR="$(cd "$(dirname "$BUILD")" && pwd)"

# Starts a roundtrip process in one role (ping|pong) for a
# vendor with security. Echoes the PID. $1=vendor $2=role $3=logfile [$4=ping-args]
start_proc() {
    local vendor="$1" role="$2" log="$3"; shift 3
    local bin="$BUILD/${vendor}-roundtrip"
    local -a env=(ZERODDS_BENCH_DOMAIN=$DOMAIN)
    case "$vendor" in
        cyclone)
            env+=("CYCLONEDDS_URI=file://${SECDIR}/cyclone_security_${role}.xml")
            ;;
        fastdds|zerodds)
            env+=(ZERODDS_BENCH_SECURITY=1 ZERODDS_BENCH_SEC_DIR=$SECDIR ZERODDS_BENCH_SEC_NAME=$role)
            ;;
        opendds)
            env+=(ZERODDS_BENCH_SECURITY=1 ZERODDS_BENCH_SEC_DIR=$SECDIR ZERODDS_BENCH_SEC_NAME=$role)
            ;;
    esac
    # zerodds-roundtrip needs the secure dylib in the library path.
    # Default: target/release of the repo (4 levels above this script);
    # overridable via ZERODDS_LIB_DIR (e.g. a dedicated build directory).
    local zlib="${ZERODDS_LIB_DIR:-$HERE/../../../target/release}"
    [ "$vendor" = zerodds ] && env+=("LD_LIBRARY_PATH=${zlib}:${LD_LIBRARY_PATH:-}")

    # OpenDDS needs the security ini via -DCPSConfigFile.
    local -a appargs=("$@")
    if [ "$vendor" = opendds ]; then
        appargs+=(-DCPSConfigFile "$(dirname "$BUILD")/opendds_rtps_sec.ini")
    fi

    env "${env[@]}" "$bin" "${appargs[@]}" > "$log" 2>&1 &
    echo $!
}

run_cell() {
    local ping_v="$1" pong_v="$2"
    local plog="/tmp/sec_${ping_v}_${pong_v}_pong.log"
    local glog="/tmp/sec_${ping_v}_${pong_v}_ping.log"
    pkill -f -- "-roundtrip" 2>/dev/null; sleep 1

    local pong_pid; pong_pid=$(start_proc "$pong_v" pong "$plog" pong 20)
    sleep 2
    local ping_pid; ping_pid=$(start_proc "$ping_v" ping "$glog" ping --payload $PAYLOAD --warmup $WARMUP --samples $SAMPLES)

    # wait at most 60s for ping
    for i in $(seq 1 60); do kill -0 "$ping_pid" 2>/dev/null || break; sleep 1; done
    kill "$pong_pid" 2>/dev/null; pkill -f -- "-roundtrip" 2>/dev/null; sleep 1

    # extract the quantile line (all apps print "payload=.. p50=..")
    local res; res=$(grep -hoE "p50=[0-9.]+us" "$glog" 2>/dev/null | head -1)
    if [ -z "$res" ]; then
        # classify the failure cause
        if grep -qiE "PKCS7|permission|security|auth" "$glog" "$plog" 2>/dev/null; then
            res="SEC_FAIL"
        elif grep -qiE "timeout|wait_for" "$glog" 2>/dev/null; then
            res="NO_MATCH"
        else
            res="FAIL"
        fi
    fi
    printf "%-9s -> %-9s : %s\n" "$ping_v" "$pong_v" "$res"
}

echo "=== 4x4 DDS-Security Cross-Vendor Matrix (domain $DOMAIN, n=$SAMPLES) ==="
echo "ping \\ pong"
for pv in "${VENDORS[@]}"; do
    for gv in "${VENDORS[@]}"; do
        run_cell "$pv" "$gv"
    done
done
echo "=== done ==="
