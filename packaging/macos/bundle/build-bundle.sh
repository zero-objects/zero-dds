#!/usr/bin/env bash
# packaging/macos/bundle/build-bundle.sh
# Assembles the Homebrew bundle `zerodds-<version>-<target>.tar.gz` that
# packaging/macos/homebrew/zerodds.rb installs. One bundle per macOS target.
# Spec: zerodds-deployment-1.0.md §3.1 (layout) and §3.2.1 (Homebrew).
#
# Usage:
#   build-bundle.sh --target aarch64-apple-darwin --version 1.0.0-rc.7 \
#                   --out target/distrib
set -euo pipefail

TARGET=""
VERSION=""
OUT=""
while [ $# -gt 0 ]; do
    case "$1" in
        --target)  TARGET="$2";  shift 2;;
        --version) VERSION="$2"; shift 2;;
        --out)     OUT="$2";     shift 2;;
        *) echo "unknown arg: $1" >&2; exit 1;;
    esac
done
[ -n "$TARGET" ]  || { echo "--target required" >&2; exit 1; }
[ -n "$VERSION" ] || { echo "--version required" >&2; exit 1; }
[ -n "$OUT" ]     || { echo "--out required" >&2; exit 1; }

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
RELEASE="$ROOT/target/$TARGET/release"

# The release binaries the meta formula ships: the seven daemons and the
# seventeen CLIs of §1.1/§1.3, in the spelling the Windows Scoop manifest
# (packaging/windows/scoop/zerodds.json) and the MSI already use. The package
# names differ from the binary names for the daemons and three tools, so both
# lists are spelled out.
PACKAGES=(
    zerodds-websocket-bridge
    zerodds-mqtt-bridge
    zerodds-coap-bridge
    zerodds-amqp-endpoint
    zerodds-grpc-bridge
    zerodds-corba-dds-bridge
    rmw-zerodds-shim
    zerodds-admin
    zerodds-bench
    zerodds-idlc
    zerodds-spy
    zerodds-record
    zerodds-replay
    zerodds-snitch
    zerodds-monitor-cli
    zerodds-mq
    zerodds-pcap
    zerodds-perf
    zerodds-xmlc
    zerodds-traceability
    zerodds-lint
    zerodds-chaos
    zerodds-dashboard
    zerodds-recorder-bridge
    # The C-FFI cdylib `libzerodds.dylib` + its cbindgen header.
    zerodds-c-api
)

BINS=(
    zerodds-ws-bridged
    zerodds-mqtt-bridged
    zerodds-coap-bridged
    zerodds-amqp-bridged
    zerodds-grpc-bridged
    zerodds-corba-bridged
    zerodds-ros2-shim
    zerodds-admin
    zerodds-bench
    zerodds-idlc
    zerodds-spy
    zerodds-record
    zerodds-replay
    zerodds-snitch
    zerodds-monitor
    zerodds-mq
    zerodds-pcap
    zerodds-perf
    zerodds-xmlc
    zerodds-traceability
    zerodds-lint
    zerodds-chaos
    zerodds-dashboard
    zerodds-recorder-bridge
)

cargo_pkgs=()
for pkg in "${PACKAGES[@]}"; do
    cargo_pkgs+=(-p "$pkg")
done
cargo build --release --locked --target "$TARGET" "${cargo_pkgs[@]}"

STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT
mkdir -p "$STAGE/bin" "$STAGE/lib/pkgconfig" \
         "$STAGE/include/zerodds" "$STAGE/include/dds" \
         "$STAGE/share/zerodds/configs" \
         "$STAGE/share/man/man1" "$STAGE/share/man/man5" \
         "$STAGE/share/launchd"

for bin in "${BINS[@]}"; do
    [ -x "$RELEASE/$bin" ] || { echo "missing release binary: $RELEASE/$bin" >&2; exit 1; }
    install -m 0755 "$RELEASE/$bin" "$STAGE/bin/$bin"
done

# libzerodds — the C-FFI cdylib; Homebrew's `lib.install Dir["lib/libzerodds.*"]`.
[ -f "$RELEASE/libzerodds.dylib" ] || { echo "missing $RELEASE/libzerodds.dylib" >&2; exit 1; }
install -m 0755 "$RELEASE/libzerodds.dylib" "$STAGE/lib/libzerodds.dylib"

# C header generated by cbindgen during the build; C++ headers from the two
# CMake-installed trees. The formula installs include/zerodds.h,
# include/zerodds/* and, when present, include/dds.
install -m 0644 "$ROOT/crates/zerodds-c-api/include/zerodds.h" "$STAGE/include/zerodds.h"
install -m 0644 "$ROOT/crates/cpp/include/zerodds/dds.hpp" "$STAGE/include/zerodds/dds.hpp"
install -m 0644 "$ROOT/runtime/cpp/include/zerodds/wire.hpp" "$STAGE/include/zerodds/wire.hpp"
cp -R "$ROOT/crates/cpp/include/dds/." "$STAGE/include/dds/"
cp -R "$ROOT/runtime/cpp/include/dds/." "$STAGE/include/dds/"

# pkg-config descriptor from the one CMake template, so the prefix stays
# relocatable through ${pcfiledir} (spec P0-4: one SDK source of truth).
sed -e 's|@CMAKE_INSTALL_LIBDIR@|lib|g' \
    -e 's|@CMAKE_INSTALL_INCLUDEDIR@|include|g' \
    -e "s|@ZERODDS_VERSION_FULL@|${VERSION}|g" \
    "$ROOT/cmake/zerodds.pc.in" > "$STAGE/lib/pkgconfig/zerodds.pc"

install -m 0644 "$ROOT"/packaging/linux/configs/*.example "$STAGE/share/zerodds/configs/"
install -m 0644 "$ROOT"/man/man1/zerodds-*.1 "$STAGE/share/man/man1/"
install -m 0644 "$ROOT"/man/man5/zerodds*.yaml.5 "$STAGE/share/man/man5/"
install -m 0644 "$ROOT"/packaging/macos/launchd/*.plist "$STAGE/share/launchd/"

mkdir -p "$OUT"
ARCHIVE="$OUT/zerodds-${VERSION}-${TARGET}.tar.gz"
tar -czf "$ARCHIVE" -C "$STAGE" bin lib include share
( cd "$OUT" && shasum -a 256 "$(basename "$ARCHIVE")" > "$(basename "$ARCHIVE").sha256" )
echo "Built $ARCHIVE"
