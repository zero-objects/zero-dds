// Byte-golden + state-machine test for xrce_client.ts, checked against
// endpoints/testdata/xrce-client/ (*.bin), the same fixtures every other
// language port of this client in this repository is checked against.
// Golden bytes embedded here (hex) rather than read from the fixture
// files, so this test needs no working-directory convention of its own
// (same reasoning as endpoints/c/test/test_xrce_client.c and
// endpoints/node/xrce_client.test.js's own layout).
//
// usage: tsc && node --test dist/xrce_client.test.js

import test from 'node:test';
import assert from 'node:assert';
import * as xc from './xrce_client';

const KEY = Buffer.from([0x01, 0x02, 0x03, 0x04]);
const STATE_KEY = Buffer.from([0xaa, 0xbb, 0xcc, 0xdd]);
const SESSION_ID = 0x01;

const hex = (b: Buffer) => b.toString('hex');

// Golden bytes, byte by byte, matching endpoints/c/test/test_xrce_client.c's
// own embedded golden arrays. session_id = 0x01 throughout (<=127, so
// every header after CREATE_CLIENT carries the ClientKey). CREATE_CLIENT
// travels on STREAM_ID_NONE, seq 0, with header session 0x00
// (SESSION_ID_NONE_WITH_CLIENT_KEY, DDS-XRCE 1.0 §8.3.2.1) while its payload
// asks for session 0x01. The four post-handshake operations
// are all reliable, so they share STREAM_ID_BUILTIN_RELIABLE (0x80) and a
// real, strictly increasing sequence number (0..3) -- not the
// best-effort stream with hand-picked numbers a previous fixture set
// used.
const GOLDEN_CREATE_CLIENT = Buffer.from([
  0x00, 0x00, 0x00, 0x00, 0x01, 0x02, 0x03, 0x04, 0x00, 0x01, 0x10, 0x00, 0x58, 0x52, 0x43, 0x45, 0x01, 0x00, 0x00,
  0x00, 0x01, 0x02, 0x03, 0x04, 0x01, 0x00, 0xfc, 0x01,
]);

const GOLDEN_CREATE = Buffer.from([
  0x01, 0x80, 0x00, 0x00, 0x01, 0x02, 0x03, 0x04, 0x01, 0x01, 0x1b, 0x00, 0x00, 0x01, 0x00, 0x15, 0x05, 0x01, 0x00,
  0x00, 0x0d, 0x00, 0x00, 0x00, 0x53, 0x65, 0x6e, 0x73, 0x6f, 0x72, 0x57, 0x72, 0x69, 0x74, 0x65, 0x72, 0x00, 0x00,
  0x13,
]);

const GOLDEN_DELETE = Buffer.from([
  0x01, 0x80, 0x01, 0x00, 0x01, 0x02, 0x03, 0x04, 0x03, 0x01, 0x04, 0x00, 0x00, 0x02, 0x00, 0x15,
]);

const GOLDEN_WRITE_DATA = Buffer.from([
  0x01, 0x80, 0x03, 0x00, 0x01, 0x02, 0x03, 0x04, 0x07, 0x01, 0x06, 0x00, 0x00, 0x04, 0x00, 0x15, 0x19, 0x00,
]);

const GOLDEN_READ_DATA = Buffer.from([
  0x01, 0x80, 0x02, 0x00, 0x01, 0x02, 0x03, 0x04, 0x08, 0x01, 0x08, 0x00, 0x00, 0x03, 0x00, 0x26, 0x01, 0x00, 0x00,
  0x00,
]);

// A second CREATE, appended to the same session: object_id=pack(raw=0x010,
// kind=Topic), the real two-level ObjectVariant::ByReference
// ("HelloWorldTopic") under parent=pack(raw=0x001,kind=Participant),
// request_id={0x00,0x05}, sequence_nr=4. OBJK_TOPIC's own representation
// carries its participant's ObjectId (commit 31c62df2a63, "xrce:
// OBJK_TOPIC_Representation carries its participant's ObjectId"), the
// same trailing field OBJK_PUBLISHER's representation carries above --
// matches endpoints/testdata/xrce-client/xrce_client_create_topic.bin,
// generated by endpoints/golden-gen, not a hand-picked byte string.
const GOLDEN_CREATE_TOPIC = Buffer.from([
  0x01, 0x80, 0x04, 0x00, 0x01, 0x02, 0x03, 0x04, 0x01, 0x01, 0x1e, 0x00, 0x00, 0x05, 0x01, 0x02, 0x02, 0x01, 0x00,
  0x00, 0x10, 0x00, 0x00, 0x00, 0x48, 0x65, 0x6c, 0x6c, 0x6f, 0x57, 0x6f, 0x72, 0x6c, 0x64, 0x54, 0x6f, 0x70, 0x69,
  0x63, 0x00, 0x00, 0x11,
]);

// --- state-machine tests, mirroring crates/xrce-client's own unit tests ---

test('new client starts Disconnected', () => {
  const c = new xc.XrceClient(STATE_KEY);
  assert.strictEqual(c.state, xc.XrceClientState.Disconnected);
  assert.deepStrictEqual(c.clientKey, STATE_KEY);
});

test('connect transitions to Connecting', () => {
  const c = new xc.XrceClient(STATE_KEY);
  c.connect(SESSION_ID);
  assert.strictEqual(c.state, xc.XrceClientState.Connecting);
});

test('markConnected transitions to Connected', () => {
  const c = new xc.XrceClient(STATE_KEY);
  c.connect(SESSION_ID);
  c.markConnected();
  assert.strictEqual(c.state, xc.XrceClientState.Connected);
});

test('double connect rejected', () => {
  const c = new xc.XrceClient(STATE_KEY);
  c.connect(SESSION_ID);
  assert.throws(() => c.connect(SESSION_ID), xc.XrceClientError);
});

test('createObject without connect rejected', () => {
  const c = new xc.XrceClient(STATE_KEY);
  assert.throws(() => c.createObject(), xc.XrceClientError);
});

test('requestWrite without connect rejected', () => {
  const c = new xc.XrceClient(STATE_KEY);
  assert.throws(() => c.requestWrite(), xc.XrceClientError);
});

test('requestRead without connect rejected', () => {
  const c = new xc.XrceClient(STATE_KEY);
  assert.throws(() => c.requestRead(), xc.XrceClientError);
});

test('full lifecycle creates unique, monotonic request ids', () => {
  const c = new xc.XrceClient(STATE_KEY);
  c.connect(SESSION_ID);
  c.markConnected();
  const r1 = c.createObject();
  const r2 = c.deleteObject();
  const r3 = c.requestWrite();
  const r4 = c.requestRead();
  assert.deepStrictEqual([r1, r2, r3, r4], [1, 2, 3, 4]);
});

test('disconnect clears state', () => {
  const c = new xc.XrceClient(STATE_KEY);
  c.connect(SESSION_ID);
  c.markConnected();
  c.disconnect();
  assert.strictEqual(c.state, xc.XrceClientState.Disconnected);
});

// --- wire-octet tests, against endpoints/testdata/xrce-client/ -------------

test('CREATE_CLIENT matches xrce_client_create_client.bin', () => {
  const repr = xc.encodeClientRepresentation([0x01, 0x00], [0x00, 0x00], KEY, SESSION_ID);
  const got = xc.frameCreateClient(SESSION_ID, KEY, repr);
  assert.strictEqual(hex(got), hex(GOLDEN_CREATE_CLIENT));
});

// DDS-XRCE 1.0 §7.8.2.1 prose vs Annex A / B.1: representationTimestamps.
test('representationTimestamps: absent (default) 16 octets, present appendable 28, present final 24', () => {
  const head = [0x58, 0x52, 0x43, 0x45, 0x01, 0x00, 0x00, 0x00];
  const timeT = [0x8c, 0xaa, 0x88, 0x5a, 0x00, 0x65, 0xcd, 0x1d];
  const tail = [0x01, 0x02, 0x03, 0x04, 0x01, 0x00, 0xfc, 0x01];
  const absent = Buffer.from([...head, ...tail]);
  const appendable = Buffer.from([...head, 0x08, 0x00, 0x00, 0x00, ...timeT, ...tail]);
  const final = Buffer.from([...head, ...timeT, ...tail]);
  const t = { seconds: 1518905996, nanoseconds: 500000000 };
  const enc = (o?: xc.ClientRepresentationOptions) =>
    xc.encodeClientRepresentation([0x01, 0x00], [0x00, 0x00], KEY, 0x01, 508, o);
  assert.strictEqual(hex(enc()), hex(absent));
  assert.strictEqual(hex(enc({ representationTimestamps: 'absent', ...t })), hex(absent));
  assert.strictEqual(hex(enc({ representationTimestamps: 'present', ...t })), hex(appendable));
  assert.strictEqual(hex(enc({ representationTimestamps: 'present', unannotatedTypes: 'final', ...t })), hex(final));
  assert.strictEqual(new xc.XrceClient(KEY, { representationTimestamps: 'present' }).clientRepresentation().length, 28);
  assert.strictEqual(new xc.XrceClient(KEY).clientRepresentation().length, 16);
});

test('CREATE_CLIENT for a session_id >= 128 has header session 0x80 and no key', () => {
  const repr = xc.encodeClientRepresentation([0x01, 0x00], [0x00, 0x00], KEY, 0x81);
  const got = xc.frameCreateClient(0x81, KEY, repr);
  assert.strictEqual(got[0], 0x80);
  assert.strictEqual(got.length, 4 + 4 + repr.length);
  assert.strictEqual(got[4 + 4 + 12], 0x81);
});

// CREATE/DELETE/READ_DATA/WRITE_DATA -- one client, exercised through its
// real request-id counter (not just the encoder). All four are reliable,
// so they share STREAM_ID_BUILTIN_RELIABLE and a real, strictly
// increasing sequence number (0..3) -- not the best-effort stream with
// hand-picked numbers a previous fixture set used.
test('CREATE/DELETE/READ_DATA/WRITE_DATA match the session fixtures', () => {
  const c = new xc.XrceClient(KEY);
  c.connect(SESSION_ID);
  c.markConnected();

  const writer = xc.xrceObjectId(0x001, xc.XrceObjectKind.DataWriter);
  const publisher = xc.xrceObjectId(0x001, xc.XrceObjectKind.Publisher);
  const reader = xc.xrceObjectId(0x002, xc.XrceObjectKind.DataReader);

  let req = c.createObject();
  assert.strictEqual(req, 1);
  let got = xc.frameCreate(SESSION_ID, KEY, 0, req, writer, xc.XrceObjectKind.DataWriter, 'SensorWriter', publisher);
  assert.strictEqual(hex(got), hex(GOLDEN_CREATE));

  req = c.deleteObject();
  assert.strictEqual(req, 2);
  got = xc.frameDelete(SESSION_ID, KEY, 1, req, writer);
  assert.strictEqual(hex(got), hex(GOLDEN_DELETE));

  req = c.requestRead();
  assert.strictEqual(req, 3);
  got = xc.frameReadData(SESSION_ID, KEY, 2, req, reader, 0x01);
  assert.strictEqual(hex(got), hex(GOLDEN_READ_DATA));

  req = c.requestWrite();
  assert.strictEqual(req, 4);
  got = xc.frameWriteData(SESSION_ID, KEY, 3, req, writer, Buffer.from([0x19, 0x00]));
  assert.strictEqual(hex(got), hex(GOLDEN_WRITE_DATA));

  req = c.createObject();
  assert.strictEqual(req, 5);
  const topic = xc.xrceObjectId(0x010, xc.XrceObjectKind.Topic);
  const participant = xc.xrceObjectId(0x001, xc.XrceObjectKind.Participant);
  got = xc.frameCreate(SESSION_ID, KEY, 4, req, topic, xc.XrceObjectKind.Topic, 'HelloWorldTopic', participant);
  assert.strictEqual(hex(got), hex(GOLDEN_CREATE_TOPIC));
});

// Cross-check independent of the fixtures above.
test('ObjectId packs kind into the low 4 bits', () => {
  const id = xc.xrceObjectId(0x123, xc.XrceObjectKind.DataWriter);
  assert.strictEqual(id, (0x123 << 4) | 0x05);
});

// The 16-bit submessage_length bounds the body (BaseObjectRequest + sample):
// a body of exactly 0xFFFF frames, one octet more is refused.
test('frameWriteData refuses a body above the 16-bit submessage_length', () => {
  const writer = xc.xrceObjectId(0x001, xc.XrceObjectKind.DataWriter);
  const maxSample = Buffer.alloc(0xffff - 4);
  const frame = xc.frameWriteData(SESSION_ID, KEY, 0, 1, writer, maxSample);
  assert.strictEqual(frame.readUInt16LE(10), 0xffff);
  assert.strictEqual(frame.length, 8 + 4 + 0xffff);

  assert.throws(
    () => xc.frameWriteData(SESSION_ID, KEY, 0, 1, writer, Buffer.alloc(0xffff - 4 + 1)),
    RangeError,
  );
});
