// Byte-golden + state-machine test for XrceClient.java, checked against
// endpoints/testdata/xrce-client/ (*.bin), the same fixtures every other
// language port of this client in this repository is checked against.
// Golden bytes embedded here rather than read from the fixture files, so
// this test needs no working-directory convention of its own (same
// reasoning as endpoints/c/test/test_xrce_client.c).
//
// usage: javac XrceClient.java XrceClientTest.java && java XrceClientTest

import java.util.Arrays;

public final class XrceClientTest {

    static int failures = 0;

    static void check(boolean cond, String msg) {
        if (!cond) {
            System.out.println("FAIL: " + msg);
            failures++;
        }
    }

    static final byte[] FIXTURE_KEY = { 0x01, 0x02, 0x03, 0x04 };
    static final byte[] STATE_KEY = { (byte) 0xAA, (byte) 0xBB, (byte) 0xCC, (byte) 0xDD };
    static final int SESSION_ID = 0x01;

    // Session_id = 0x01 throughout (<=127, so every header carries the
    // ClientKey; the CREATE_CLIENT header itself carries
    // SESSION_ID_NONE_WITH_CLIENT_KEY 0x00, DDS-XRCE 1.0 8.3.2.1). CREATE_CLIENT travels on STREAM_ID_NONE, seq 0. The four
    // post-handshake operations are all reliable, so they share
    // STREAM_ID_BUILTIN_RELIABLE (0x80) and a real, strictly increasing
    // sequence number (0..3) -- not the best-effort stream with
    // hand-picked numbers a previous fixture set used.
    static final byte[] GOLDEN_CREATE_CLIENT = {
        0x00, 0x00, 0x00, 0x00, 0x01, 0x02, 0x03, 0x04,
        0x00, 0x01, 0x10, 0x00,
        0x58, 0x52, 0x43, 0x45, 0x01, 0x00, 0x00, 0x00, 0x01, 0x02, 0x03, 0x04,
        0x01, 0x00, (byte) 0xfc, 0x01
    };

    static final byte[] GOLDEN_CREATE = {
        0x01, (byte) 0x80, 0x00, 0x00, 0x01, 0x02, 0x03, 0x04,
        0x01, 0x01, 0x1b, 0x00,
        0x00, 0x01, 0x00, 0x15,
        0x05, 0x01, 0x00, 0x00, 0x0d, 0x00, 0x00, 0x00,
        'S', 'e', 'n', 's', 'o', 'r', 'W', 'r', 'i', 't', 'e', 'r', 0x00,
        0x00, 0x13
    };

    static final byte[] GOLDEN_DELETE = {
        0x01, (byte) 0x80, 0x01, 0x00, 0x01, 0x02, 0x03, 0x04,
        0x03, 0x01, 0x04, 0x00,
        0x00, 0x02, 0x00, 0x15
    };

    static final byte[] GOLDEN_WRITE_DATA = {
        0x01, (byte) 0x80, 0x03, 0x00, 0x01, 0x02, 0x03, 0x04,
        0x07, 0x01, 0x06, 0x00,
        0x00, 0x04, 0x00, 0x15, 0x19, 0x00
    };

    static final byte[] GOLDEN_READ_DATA = {
        0x01, (byte) 0x80, 0x02, 0x00, 0x01, 0x02, 0x03, 0x04,
        0x08, 0x01, 0x08, 0x00,
        0x00, 0x03, 0x00, 0x26, 0x01, 0x00, 0x00, 0x00
    };

    // A second CREATE, appended to the same session: object_id=pack(raw=
    // 0x010,kind=TOPIC), the real two-level ObjectVariant::ByReference
    // ("HelloWorldTopic") under parent=pack(raw=0x001,kind=PARTICIPANT),
    // request_id=5, sequence_nr=4. OBJK_TOPIC's own representation
    // carries its participant's ObjectId (commit 31c62df2a63, "xrce:
    // OBJK_TOPIC_Representation carries its participant's ObjectId"),
    // the same trailing field OBJK_PUBLISHER's representation carries
    // above -- matches
    // endpoints/testdata/xrce-client/xrce_client_create_topic.bin,
    // generated by endpoints/golden-gen, not a hand-picked byte string.
    static final byte[] GOLDEN_CREATE_TOPIC = {
        0x01, (byte) 0x80, 0x04, 0x00, 0x01, 0x02, 0x03, 0x04,
        0x01, 0x01, 0x1e, 0x00,
        0x00, 0x05, 0x01, 0x02,
        0x02, 0x01, 0x00, 0x00, 0x10, 0x00, 0x00, 0x00,
        'H', 'e', 'l', 'l', 'o', 'W', 'o', 'r', 'l', 'd', 'T', 'o', 'p', 'i', 'c', 0x00,
        0x00, 0x11
    };

    static void stateMachine() {
        XrceClient c = new XrceClient(STATE_KEY);
        check(c.state() == XrceClient.State.DISCONNECTED, "new client is disconnected");
        check(Arrays.equals(c.clientKey(), STATE_KEY), "client_key stored");

        c.connect(SESSION_ID);
        check(c.state() == XrceClient.State.CONNECTING, "state == connecting");
        try { c.connect(SESSION_ID); check(false, "second connect() rejected"); }
        catch (XrceClient.ClientError e) { }

        c.markConnected();
        check(c.state() == XrceClient.State.CONNECTED, "state == connected");

        int r1 = c.createObject();
        int r2 = c.deleteObject();
        int r3 = c.requestWrite();
        int r4 = c.requestRead();
        check(r1 == 1 && r2 == 2 && r3 == 3 && r4 == 4, "request ids strictly monotonic");

        c.disconnect();
        check(c.state() == XrceClient.State.DISCONNECTED, "disconnect -> disconnected");
    }

    static void rejectedBeforeConnect() {
        XrceClient c = new XrceClient(STATE_KEY);
        try { c.createObject(); check(false, "createObject before connect rejected"); }
        catch (XrceClient.ClientError e) { }
        try { c.requestWrite(); check(false, "requestWrite before connect rejected"); }
        catch (XrceClient.ClientError e) { }
        try { c.requestRead(); check(false, "requestRead before connect rejected"); }
        catch (XrceClient.ClientError e) { }
    }

    static void framing() {
        byte[] createClient = XrceClient.frameCreateClient(SESSION_ID, FIXTURE_KEY);
        check(Arrays.equals(createClient, GOLDEN_CREATE_CLIENT),
              "CREATE_CLIENT byte-identical to xrce_client_create_client.bin");
        // Requested session >= 128: header 0x80, no client key (Sec 8.3.2.1); payload keeps 0x81.
        byte[] high = XrceClient.frameCreateClient(0x81, FIXTURE_KEY);
        check(high.length == createClient.length - 4 && high[0] == (byte) 0x80 && high[20] == (byte) 0x81,
              "CREATE_CLIENT session 0x81: header 0x80 without client key, payload 0x81");

        int writer = XrceClient.objectId(0x001, XrceClient.ObjectKind.DATAWRITER);
        int publisher = XrceClient.objectId(0x001, XrceClient.ObjectKind.PUBLISHER);
        byte[] create = XrceClient.frameCreate(SESSION_ID, FIXTURE_KEY, 0, 1,
            writer, XrceClient.ObjectKind.DATAWRITER, "SensorWriter", publisher, false, false);
        check(Arrays.equals(create, GOLDEN_CREATE), "CREATE byte-identical to xrce_client_create.bin");

        byte[] delete = XrceClient.frameDelete(SESSION_ID, FIXTURE_KEY, 1, 2, writer);
        check(Arrays.equals(delete, GOLDEN_DELETE), "DELETE byte-identical to xrce_client_delete.bin");

        byte[] readData = XrceClient.frameReadData(SESSION_ID, FIXTURE_KEY, 2, 3,
            XrceClient.objectId(0x002, XrceClient.ObjectKind.DATAREADER), 0x01);
        check(Arrays.equals(readData, GOLDEN_READ_DATA),
              "READ_DATA byte-identical to xrce_client_read_data.bin");

        byte[] writeData = XrceClient.frameWriteData(SESSION_ID, FIXTURE_KEY, 3, 4,
            writer, new byte[] { 0x19, 0x00 });
        check(Arrays.equals(writeData, GOLDEN_WRITE_DATA),
              "WRITE_DATA byte-identical to xrce_client_write_data.bin");

        int topic = XrceClient.objectId(0x010, XrceClient.ObjectKind.TOPIC);
        int participant = XrceClient.objectId(0x001, XrceClient.ObjectKind.PARTICIPANT);
        byte[] createTopic = XrceClient.frameCreate(SESSION_ID, FIXTURE_KEY, 4, 5,
            topic, XrceClient.ObjectKind.TOPIC, "HelloWorldTopic", participant, false, false);
        check(Arrays.equals(createTopic, GOLDEN_CREATE_TOPIC),
              "CREATE(topic) byte-identical to xrce_client_create_topic.bin");
    }

    static final byte[] REP_ABSENT = {
        0x58, 0x52, 0x43, 0x45, 0x01, 0x00, 0x00, 0x00, 0x01, 0x02, 0x03, 0x04,
        0x01, 0x00, (byte) 0xfc, 0x01
    };
    static final byte[] REP_PRESENT_APPENDABLE = {
        0x58, 0x52, 0x43, 0x45, 0x01, 0x00, 0x00, 0x00,
        0x08, 0x00, 0x00, 0x00,
        (byte) 0x8c, (byte) 0xaa, (byte) 0x88, 0x5a, 0x00, 0x65, (byte) 0xcd, 0x1d,
        0x01, 0x02, 0x03, 0x04, 0x01, 0x00, (byte) 0xfc, 0x01
    };
    static final byte[] REP_PRESENT_FINAL = {
        0x58, 0x52, 0x43, 0x45, 0x01, 0x00, 0x00, 0x00,
        (byte) 0x8c, (byte) 0xaa, (byte) 0x88, 0x5a, 0x00, 0x65, (byte) 0xcd, 0x1d,
        0x01, 0x02, 0x03, 0x04, 0x01, 0x00, (byte) 0xfc, 0x01
    };

    // Representation timestamps (DDS-XRCE 1.0 7.8.2.1 prose vs Annex A / B.1).
    static void representationTimestamps() {
        final int sec = 0x5A88AA8C, nsec = 0x1DCD6500;
        check(Arrays.equals(XrceClient.encodeClientRepresentation(0x0100, 0, FIXTURE_KEY, SESSION_ID, 508),
                REP_ABSENT), "representation: default is absent, 16 octets");
        check(Arrays.equals(XrceClient.encodeClientRepresentation(0x0100, 0, FIXTURE_KEY, SESSION_ID, 508,
                XrceClient.RepresentationTimestamps.ABSENT, XrceClient.UnannotatedTypes.APPENDABLE, sec, nsec),
                REP_ABSENT), "representation: absent ignores the timestamp");
        check(Arrays.equals(XrceClient.encodeClientRepresentation(0x0100, 0, FIXTURE_KEY, SESSION_ID, 508,
                XrceClient.RepresentationTimestamps.PRESENT, XrceClient.UnannotatedTypes.APPENDABLE, sec, nsec),
                REP_PRESENT_APPENDABLE), "representation: present, appendable, 28 octets");
        check(Arrays.equals(XrceClient.encodeClientRepresentation(0x0100, 0, FIXTURE_KEY, SESSION_ID, 508,
                XrceClient.RepresentationTimestamps.PRESENT, XrceClient.UnannotatedTypes.FINAL, sec, nsec),
                REP_PRESENT_FINAL), "representation: present, final, 24 octets");
        byte[] frame = XrceClient.frameCreateClient(SESSION_ID, FIXTURE_KEY,
                XrceClient.RepresentationTimestamps.PRESENT, XrceClient.UnannotatedTypes.APPENDABLE, sec, nsec);
        check(frame.length == 8 + 4 + 28 && frame[10] == 28 && frame[11] == 0,
              "CREATE_CLIENT present: submessage length 28");
        XrceClient c = new XrceClient(FIXTURE_KEY, XrceClient.RepresentationTimestamps.PRESENT);
        c.connect(SESSION_ID);
        check(c.frameCreateClient().length == 8 + 4 + 28, "client option present: CREATE_CLIENT grows to 28 octets");
        check(new XrceClient(FIXTURE_KEY).representationTimestamps() == XrceClient.RepresentationTimestamps.ABSENT,
              "client default is absent");
    }

    static void endToEnd() {
        XrceClient c = new XrceClient(FIXTURE_KEY);
        c.connect(SESSION_ID);
        check(Arrays.equals(XrceClient.frameCreateClient(c.sessionId(), c.clientKey()), GOLDEN_CREATE_CLIENT),
              "e2e CREATE_CLIENT frame");
        c.markConnected();

        int writer = XrceClient.objectId(0x001, XrceClient.ObjectKind.DATAWRITER);
        int publisher = XrceClient.objectId(0x001, XrceClient.ObjectKind.PUBLISHER);
        int req = c.createObject();
        check(Arrays.equals(
                XrceClient.frameCreate(c.sessionId(), c.clientKey(), 0, req,
                    writer, XrceClient.ObjectKind.DATAWRITER, "SensorWriter", publisher, false, false),
                GOLDEN_CREATE),
              "e2e CREATE frame");

        int deleteReq = c.deleteObject();
        check(deleteReq == 2, "e2e delete request id 2 (create_object above took 1)");

        int readReq = c.requestRead();
        check(readReq == 3, "e2e read request id 3");

        int writeReq = c.requestWrite();
        check(writeReq == 4, "e2e write request id 4");
    }

    public static void main(String[] args) {
        stateMachine();
        rejectedBeforeConnect();
        framing();
        representationTimestamps();
        endToEnd();

        if (failures != 0) {
            System.out.println(failures + " check(s) FAILED");
            System.exit(1);
        }
        System.out.println("XRCE client (Java): all checks OK");
    }
}
