// Fixtures 2-5 are read independently, each as one wire example of its own
// submessage kind -- not as one application-consistent object lifecycle:
// WRITE_DATA below targets the DataWriter DELETE already removed, and
// nothing about either frame's bytes depends on the other one having run
// first.
static void t_end_to_end_session_matches_all_fixtures()
{
    zerodds::XrceClient c(FIXTURE_KEY);
    unsigned int writer = ZDWC_OBJECT_ID(0x001, ZDWC_OBJK_DATAWRITER);
    unsigned int publisher = ZDWC_OBJECT_ID(0x001, ZDWC_OBJK_PUBLISHER);
    unsigned int reader = ZDWC_OBJECT_ID(0x002, ZDWC_OBJK_DATAREADER);

    CHECK(c.connect(SESSION_ID) == ZDWC_OK, "e2e connect");
    CHECK(matches(zerodds::xrce::frame_create_client(c.session_id(), c.client_key()),
                  GOLDEN_CREATE_CLIENT, sizeof(GOLDEN_CREATE_CLIENT)),
          "e2e CREATE_CLIENT frame");

    CHECK(c.mark_connected() == ZDWC_OK, "e2e mark_connected");

    unsigned int req = 0;
    CHECK(c.create_object(&req) == ZDWC_OK, "e2e create_object");
    CHECK(req == 1, "e2e create request id 1");
    CHECK(matches(zerodds::xrce::frame_create(c.session_id(), c.client_key(), 0u, req,
                                              writer, ZDWC_OBJK_DATAWRITER,
                                              "SensorWriter", true, publisher, false, false),
                  GOLDEN_CREATE, sizeof(GOLDEN_CREATE)),
          "e2e CREATE frame");

    CHECK(c.delete_object(&req) == ZDWC_OK, "e2e delete_object");
    CHECK(req == 2, "e2e delete request id 2");
    CHECK(matches(zerodds::xrce::frame_delete(c.session_id(), c.client_key(), 1u, req, writer),
                  GOLDEN_DELETE, sizeof(GOLDEN_DELETE)),
          "e2e DELETE frame");

    CHECK(c.request_read(&req) == ZDWC_OK, "e2e request_read");
    CHECK(req == 3, "e2e read request id 3");
    CHECK(matches(zerodds::xrce::frame_read_data(c.session_id(), c.client_key(), 2u, req,
                                                 reader, 0x01u),
                  GOLDEN_READ_DATA, sizeof(GOLDEN_READ_DATA)),
          "e2e READ_DATA frame");

    CHECK(c.request_write(&req) == ZDWC_OK, "e2e request_write");
    CHECK(req == 4, "e2e write request id 4");
    {
        std::vector<unsigned char> sample;
        sample.push_back(0x19); sample.push_back(0x00);
        CHECK(matches(zerodds::xrce::frame_write_data(c.session_id(), c.client_key(), 3u, req,
                                                       writer, sample),
                      GOLDEN_WRITE_DATA, sizeof(GOLDEN_WRITE_DATA)),
              "e2e WRITE_DATA frame");
    }
}

int main()
{
    t_state_machine();
    t_create_without_connect_rejected();
    t_frame_create_client();
    t_representation_timestamps();
    t_frame_create();
    t_frame_write_data();
    t_frame_read_data();
    t_frame_delete();
    t_frame_create_topic();
    t_end_to_end_session_matches_all_fixtures();

    if (failures != 0) {
        std::fprintf(stderr, "%d check(s) FAILED\n", failures);
        return 1;
    }
    std::printf("XRCE client (C++): all checks OK\n");
    return 0;
}
