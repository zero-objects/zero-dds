static void t_frame_does_not_fit_reports_zero(void)
{
    unsigned char tiny[3];
    CHECK(zdwc_frame_create_client(SESSION_ID, FIXTURE_KEY, tiny, sizeof(tiny)) == 0,
          "CREATE_CLIENT into an undersized buffer returns 0");
    CHECK(zdwc_frame_write_data(SESSION_ID, FIXTURE_KEY, 1u, 1u, 0, 0, 0,
                                tiny, sizeof(tiny)) == 0,
          "WRITE_DATA into an undersized buffer returns 0");
}

/* ---- an end-to-end session, state machine driving the framing ---- */
/* Fixtures 2-5 are read independently, each as one wire example of its
 * own submessage kind -- not as one application-consistent object
 * lifecycle: WRITE_DATA below targets the DataWriter DELETE already
 * removed, and nothing about either frame's bytes depends on the other
 * one having run first. */

static void t_end_to_end_session_matches_all_fixtures(void)
{
    zdwc_client c;
    unsigned char buf[64];
    unsigned int req;
    unsigned int writer = ZDWC_OBJECT_ID(0x001, ZDWC_OBJK_DATAWRITER);
    unsigned int publisher = ZDWC_OBJECT_ID(0x001, ZDWC_OBJK_PUBLISHER);
    unsigned int reader = ZDWC_OBJECT_ID(0x002, ZDWC_OBJK_DATAREADER);
    size_t n;

    zdwc_client_init(&c, FIXTURE_KEY);
    CHECK(zdwc_connect(&c, SESSION_ID) == ZDWC_OK, "e2e connect");
    n = zdwc_frame_create_client(c.session_id, c.client_key, buf, sizeof(buf));
    CHECK(frame_matches(buf, n, GOLDEN_CREATE_CLIENT, sizeof(GOLDEN_CREATE_CLIENT)),
          "e2e CREATE_CLIENT frame");

    CHECK(zdwc_mark_connected(&c) == ZDWC_OK, "e2e mark_connected");

    CHECK(zdwc_create_object(&c, &req) == ZDWC_OK, "e2e create_object");
    CHECK(req == 1, "e2e create request id 1");
    n = zdwc_frame_create(c.session_id, c.client_key, 0u, req, writer,
                          ZDWC_OBJK_DATAWRITER, "SensorWriter", 1, publisher,
                          0, 0, buf, sizeof(buf));
    CHECK(frame_matches(buf, n, GOLDEN_CREATE, sizeof(GOLDEN_CREATE)),
          "e2e CREATE frame");

    CHECK(zdwc_delete_object(&c, &req) == ZDWC_OK, "e2e delete_object");
    CHECK(req == 2, "e2e delete request id 2");
    n = zdwc_frame_delete(c.session_id, c.client_key, 1u, req, writer, buf, sizeof(buf));
    CHECK(frame_matches(buf, n, GOLDEN_DELETE, sizeof(GOLDEN_DELETE)), "e2e DELETE frame");

    CHECK(zdwc_request_read(&c, &req) == ZDWC_OK, "e2e request_read");
    CHECK(req == 3, "e2e read request id 3");
    n = zdwc_frame_read_data(c.session_id, c.client_key, 2u, req, reader, 0x01u,
                             buf, sizeof(buf));
    CHECK(frame_matches(buf, n, GOLDEN_READ_DATA, sizeof(GOLDEN_READ_DATA)),
          "e2e READ_DATA frame");

    CHECK(zdwc_request_write(&c, &req) == ZDWC_OK, "e2e request_write");
    CHECK(req == 4, "e2e write request id 4");
    {
        static const unsigned char sample[2] = { 0x19, 0x00 };
        n = zdwc_frame_write_data(c.session_id, c.client_key, 3u, req, writer,
                                  sample, sizeof(sample), buf, sizeof(buf));
        CHECK(frame_matches(buf, n, GOLDEN_WRITE_DATA, sizeof(GOLDEN_WRITE_DATA)),
              "e2e WRITE_DATA frame");
    }
}

int main(void)
{
    t_new_client_starts_disconnected();
    t_connect_transitions_to_connecting();
    t_mark_connected_transitions_to_connected();
    t_double_connect_rejected();
    t_create_without_connect_rejected();
    t_write_without_connect_rejected();
    t_read_without_connect_rejected();
    t_full_lifecycle_creates_unique_request_ids();
    t_disconnect_clears_state();
    t_request_id_wraps_skipping_zero();

    t_frame_create_client();
    t_representation_timestamps();
    t_frame_create();
    t_frame_write_data();
    t_frame_read_data();
    t_frame_delete();
    t_frame_create_topic();
    t_frame_does_not_fit_reports_zero();

    t_end_to_end_session_matches_all_fixtures();

    if (failures != 0) {
        fprintf(stderr, "%d check(s) FAILED\n", failures);
        return 1;
    }
    printf("XRCE client: all checks OK\n");
    return 0;
}
