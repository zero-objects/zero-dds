// Byte-golden + state-machine test for XrceClient.cs, checked against
// endpoints/testdata/xrce-client/ (*.bin), the same fixtures every other
// language port of this client in this repository is checked against.
// Golden bytes embedded here rather than read from the fixture files, so
// this test needs no working-directory convention of its own (same
// reasoning as endpoints/c/test/test_xrce_client.c).
//
// usage: dotnet run --project XrceClientTest.csproj

using System;
using ZeroDDS;

namespace ZeroDDS.Examples
{
    public static class XrceClientTest
    {
        private static int _failures = 0;

        private static void Check(bool cond, string msg)
        {
            if (!cond)
            {
                Console.WriteLine($"FAIL: {msg}");
                _failures++;
            }
        }

        private static readonly byte[] FixtureKey = { 0x01, 0x02, 0x03, 0x04 };
        private static readonly byte[] StateKey = { 0xAA, 0xBB, 0xCC, 0xDD };
        private const byte SessionId = 0x01;

        // session_id = 0x01 throughout (<=127, so every header carries the
        // ClientKey; the CREATE_CLIENT header itself carries
        // SESSION_ID_NONE_WITH_CLIENT_KEY 0x00, DDS-XRCE 1.0 8.3.2.1). CREATE_CLIENT travels on StreamIdNone, seq 0. The
        // four post-handshake operations are all reliable, so they share
        // StreamIdBuiltinReliable (0x80) and a real, strictly increasing
        // sequence number (0..3) -- not the best-effort stream with
        // hand-picked numbers a previous fixture set used.
        private static readonly byte[] GoldenCreateClient = {
            0x00, 0x00, 0x00, 0x00, 0x01, 0x02, 0x03, 0x04,
            0x00, 0x01, 0x10, 0x00,
            0x58, 0x52, 0x43, 0x45, 0x01, 0x00, 0x00, 0x00, 0x01, 0x02, 0x03, 0x04,
            0x01, 0x00, 0xfc, 0x01
        };

        private static readonly byte[] GoldenCreate = {
            0x01, 0x80, 0x00, 0x00, 0x01, 0x02, 0x03, 0x04,
            0x01, 0x01, 0x1b, 0x00,
            0x00, 0x01, 0x00, 0x15,
            0x05, 0x01, 0x00, 0x00, 0x0d, 0x00, 0x00, 0x00,
            (byte)'S', (byte)'e', (byte)'n', (byte)'s', (byte)'o', (byte)'r',
            (byte)'W', (byte)'r', (byte)'i', (byte)'t', (byte)'e', (byte)'r', 0x00,
            0x00, 0x13
        };

        private static readonly byte[] GoldenDelete = {
            0x01, 0x80, 0x01, 0x00, 0x01, 0x02, 0x03, 0x04,
            0x03, 0x01, 0x04, 0x00,
            0x00, 0x02, 0x00, 0x15
        };

        private static readonly byte[] GoldenWriteData = {
            0x01, 0x80, 0x03, 0x00, 0x01, 0x02, 0x03, 0x04,
            0x07, 0x01, 0x06, 0x00,
            0x00, 0x04, 0x00, 0x15, 0x19, 0x00
        };

        private static readonly byte[] GoldenReadData = {
            0x01, 0x80, 0x02, 0x00, 0x01, 0x02, 0x03, 0x04,
            0x08, 0x01, 0x08, 0x00,
            0x00, 0x03, 0x00, 0x26, 0x01, 0x00, 0x00, 0x00
        };

        // A second CREATE, appended to the same session: object_id=pack(raw=
        // 0x010,kind=Topic), the real two-level ObjectVariant::ByReference
        // ("HelloWorldTopic") under parent=pack(raw=0x001,kind=Participant),
        // request_id=5, sequence_nr=4. OBJK_TOPIC's own representation
        // carries its participant's ObjectId (commit 31c62df2a63, "xrce:
        // OBJK_TOPIC_Representation carries its participant's ObjectId"),
        // the same trailing field OBJK_PUBLISHER's representation carries
        // above -- matches
        // endpoints/testdata/xrce-client/xrce_client_create_topic.bin,
        // generated by endpoints/golden-gen, not a hand-picked byte string.
        private static readonly byte[] GoldenCreateTopic = {
            0x01, 0x80, 0x04, 0x00, 0x01, 0x02, 0x03, 0x04,
            0x01, 0x01, 0x1e, 0x00,
            0x00, 0x05, 0x01, 0x02,
            0x02, 0x01, 0x00, 0x00, 0x10, 0x00, 0x00, 0x00,
            (byte)'H', (byte)'e', (byte)'l', (byte)'l', (byte)'o', (byte)'W', (byte)'o', (byte)'r',
            (byte)'l', (byte)'d', (byte)'T', (byte)'o', (byte)'p', (byte)'i', (byte)'c', 0x00,
            0x00, 0x11
        };

        private static bool Eq(byte[] a, byte[] b) => new ReadOnlySpan<byte>(a).SequenceEqual(b);

        private static void StateMachine()
        {
            var c = new XrceClient(StateKey);
            Check(c.State == XrceClientState.Disconnected, "new client is disconnected");
            Check(Eq(c.ClientKey, StateKey), "client_key stored");

            c.Connect(SessionId);
            Check(c.State == XrceClientState.Connecting, "state == connecting");
            try { c.Connect(SessionId); Check(false, "second Connect() rejected"); }
            catch (XrceClientError) { }

            c.MarkConnected();
            Check(c.State == XrceClientState.Connected, "state == connected");

            ushort r1 = c.CreateObject();
            ushort r2 = c.DeleteObject();
            ushort r3 = c.RequestWrite();
            ushort r4 = c.RequestRead();
            Check(r1 == 1 && r2 == 2 && r3 == 3 && r4 == 4, "request ids strictly monotonic");

            c.Disconnect();
            Check(c.State == XrceClientState.Disconnected, "disconnect -> disconnected");
        }

        private static void RejectedBeforeConnect()
        {
            var c = new XrceClient(StateKey);
            try { c.CreateObject(); Check(false, "CreateObject before connect rejected"); }
            catch (XrceClientError) { }
            try { c.RequestWrite(); Check(false, "RequestWrite before connect rejected"); }
            catch (XrceClientError) { }
            try { c.RequestRead(); Check(false, "RequestRead before connect rejected"); }
            catch (XrceClientError) { }
        }

        private static void Framing()
        {
            var createClient = XrceFrame.CreateClient(SessionId, FixtureKey);
            Check(Eq(createClient, GoldenCreateClient),
                  "CREATE_CLIENT byte-identical to xrce_client_create_client.bin");
            // Requested session >= 128: header 0x80, no client key (§8.3.2.1); payload keeps 0x81.
            var high = XrceFrame.CreateClient(0x81, FixtureKey);
            Check(high.Length == createClient.Length - 4 && high[0] == 0x80 && high[20] == 0x81,
                  "CREATE_CLIENT session 0x81: header 0x80 without client key, payload 0x81");

            ushort writer = XrceObjectId.New(0x001, XrceObjectKind.DataWriter);
            ushort publisher = XrceObjectId.New(0x001, XrceObjectKind.Publisher);
            var create = XrceFrame.Create(SessionId, FixtureKey, 0, 1,
                writer, XrceObjectKind.DataWriter, "SensorWriter", publisher, false, false);
            Check(Eq(create, GoldenCreate), "CREATE byte-identical to xrce_client_create.bin");

            var delete = XrceFrame.Delete(SessionId, FixtureKey, 1, 2, writer);
            Check(Eq(delete, GoldenDelete), "DELETE byte-identical to xrce_client_delete.bin");

            var readData = XrceFrame.ReadData(SessionId, FixtureKey, 2, 3,
                XrceObjectId.New(0x002, XrceObjectKind.DataReader), 0x01);
            Check(Eq(readData, GoldenReadData),
                  "READ_DATA byte-identical to xrce_client_read_data.bin");

            var writeData = XrceFrame.WriteData(SessionId, FixtureKey, 3, 4,
                writer, new byte[] { 0x19, 0x00 });
            Check(Eq(writeData, GoldenWriteData),
                  "WRITE_DATA byte-identical to xrce_client_write_data.bin");

            ushort topic = XrceObjectId.New(0x010, XrceObjectKind.Topic);
            ushort participant = XrceObjectId.New(0x001, XrceObjectKind.Participant);
            var createTopic = XrceFrame.Create(SessionId, FixtureKey, 4, 5,
                topic, XrceObjectKind.Topic, "HelloWorldTopic", participant, false, false);
            Check(Eq(createTopic, GoldenCreateTopic),
                  "CREATE(topic) byte-identical to xrce_client_create_topic.bin");
        }

        private static readonly byte[] RepAbsent = {
            0x58, 0x52, 0x43, 0x45, 0x01, 0x00, 0x00, 0x00, 0x01, 0x02, 0x03, 0x04, 0x01, 0x00, 0xfc, 0x01
        };
        private static readonly byte[] RepPresentAppendable = {
            0x58, 0x52, 0x43, 0x45, 0x01, 0x00, 0x00, 0x00,
            0x08, 0x00, 0x00, 0x00,
            0x8c, 0xaa, 0x88, 0x5a, 0x00, 0x65, 0xcd, 0x1d,
            0x01, 0x02, 0x03, 0x04, 0x01, 0x00, 0xfc, 0x01
        };
        private static readonly byte[] RepPresentFinal = {
            0x58, 0x52, 0x43, 0x45, 0x01, 0x00, 0x00, 0x00,
            0x8c, 0xaa, 0x88, 0x5a, 0x00, 0x65, 0xcd, 0x1d,
            0x01, 0x02, 0x03, 0x04, 0x01, 0x00, 0xfc, 0x01
        };

        // Representation timestamps (DDS-XRCE 1.0 7.8.2.1 prose vs Annex A / B.1).
        private static void RepresentationTimestampsCases()
        {
            const int sec = 0x5A88AA8C;
            const uint nsec = 0x1DCD6500;
            Check(Eq(XrceFrame.EncodeClientRepresentation(0x0100, 0, FixtureKey, SessionId, 508), RepAbsent),
                  "representation: default is absent, 16 octets");
            Check(Eq(XrceFrame.EncodeClientRepresentation(0x0100, 0, FixtureKey, SessionId, 508,
                         RepresentationTimestamps.Absent, XrceUnannotatedTypes.Appendable, sec, nsec), RepAbsent),
                  "representation: absent ignores the timestamp");
            Check(Eq(XrceFrame.EncodeClientRepresentation(0x0100, 0, FixtureKey, SessionId, 508,
                         RepresentationTimestamps.Present, XrceUnannotatedTypes.Appendable, sec, nsec),
                     RepPresentAppendable),
                  "representation: present, appendable, 28 octets");
            Check(Eq(XrceFrame.EncodeClientRepresentation(0x0100, 0, FixtureKey, SessionId, 508,
                         RepresentationTimestamps.Present, XrceUnannotatedTypes.Final, sec, nsec),
                     RepPresentFinal),
                  "representation: present, final, 24 octets");
            var frame = XrceFrame.CreateClient(SessionId, FixtureKey, RepresentationTimestamps.Present,
                                               XrceUnannotatedTypes.Appendable, sec, nsec);
            Check(frame.Length == 8 + 4 + 28 && frame[10] == 28 && frame[11] == 0,
                  "CREATE_CLIENT present: submessage length 28");
            var c = new XrceClient(FixtureKey, RepresentationTimestamps.Present);
            c.Connect(SessionId);
            Check(c.FrameCreateClient().Length == 8 + 4 + 28,
                  "client option present: CREATE_CLIENT grows to 28 octets");
            Check(new XrceClient(FixtureKey).RepresentationTimestamps == RepresentationTimestamps.Absent,
                  "client default is absent");
        }

        private static void EndToEnd()
        {
            var c = new XrceClient(FixtureKey);
            c.Connect(SessionId);
            Check(Eq(XrceFrame.CreateClient(c.SessionId, c.ClientKey), GoldenCreateClient), "e2e CREATE_CLIENT frame");
            c.MarkConnected();

            ushort writer = XrceObjectId.New(0x001, XrceObjectKind.DataWriter);
            ushort publisher = XrceObjectId.New(0x001, XrceObjectKind.Publisher);
            ushort req = c.CreateObject();
            Check(Eq(XrceFrame.Create(c.SessionId, c.ClientKey, 0, req,
                                       writer, XrceObjectKind.DataWriter,
                                       "SensorWriter", publisher, false, false), GoldenCreate),
                  "e2e CREATE frame");

            ushort deleteReq = c.DeleteObject();
            Check(deleteReq == 2, "e2e delete request id 2 (create_object above took 1)");

            ushort readReq = c.RequestRead();
            Check(readReq == 3, "e2e read request id 3");

            ushort writeReq = c.RequestWrite();
            Check(writeReq == 4, "e2e write request id 4");
        }

        public static int Main(string[] args)
        {
            StateMachine();
            RejectedBeforeConnect();
            Framing();
            RepresentationTimestampsCases();
            EndToEnd();

            if (_failures != 0)
            {
                Console.WriteLine($"{_failures} check(s) FAILED");
                return 1;
            }
            Console.WriteLine("XRCE client (C#): all checks OK");
            return 0;
        }
    }
}
