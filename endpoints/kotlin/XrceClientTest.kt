// Byte-golden + state-machine test for src/XrceClient.kt, checked against
// endpoints/testdata/xrce-client/ (*.bin), the same fixtures every other
// language port of this client in this repository is checked against.
// Golden bytes embedded here rather than read from the fixture files, so
// this test needs no working-directory convention of its own.
// Runs as a main (no gradle) -- exits non-zero on failure.
//
// usage: kotlinc src/Zerodds.kt src/XrceClient.kt XrceClientTest.kt -include-runtime -d xrce_test.jar
//        java -jar xrce_test.jar

import zerodds.XrceClient
import zerodds.XrceClientError
import zerodds.XrceClientState
import zerodds.RepresentationTimestamps
import zerodds.XrceUnannotatedTypes
import zerodds.XrceFrame
import zerodds.XrceObjectKind
import zerodds.xrceObjectId
import kotlin.system.exitProcess

private var failures = 0

private fun check(cond: Boolean, msg: String) {
    if (!cond) {
        println("FAIL: $msg")
        failures++
    }
}

private val FIXTURE_KEY = byteArrayOf(0x01, 0x02, 0x03, 0x04)
private val STATE_KEY = byteArrayOf(0xAA.toByte(), 0xBB.toByte(), 0xCC.toByte(), 0xDD.toByte())
private const val SESSION_ID = 0x01

// session_id = 0x01 throughout (<=127, so every header carries the
// ClientKey; the CREATE_CLIENT header itself carries
// SESSION_ID_NONE_WITH_CLIENT_KEY 0x00, DDS-XRCE 1.0 8.3.2.1). CREATE_CLIENT travels on STREAM_ID_NONE, seq 0. The four
// post-handshake operations are all reliable, so they share
// STREAM_ID_BUILTIN_RELIABLE (0x80) and a real, strictly increasing
// sequence number (0..3) -- not the best-effort stream with hand-picked
// numbers a previous fixture set used.
private val GOLDEN_CREATE_CLIENT = byteArrayOf(
    0x00, 0x00, 0x00, 0x00, 0x01, 0x02, 0x03, 0x04,
    0x00, 0x01, 0x10, 0x00,
    0x58, 0x52, 0x43, 0x45, 0x01, 0x00, 0x00, 0x00, 0x01, 0x02, 0x03, 0x04,
    0x01, 0x00, 0xfc.toByte(), 0x01,
)

private val GOLDEN_CREATE = byteArrayOf(
    0x01, 0x80.toByte(), 0x00, 0x00, 0x01, 0x02, 0x03, 0x04,
    0x01, 0x01, 0x1b, 0x00,
    0x00, 0x01, 0x00, 0x15,
    0x05, 0x01, 0x00, 0x00, 0x0d, 0x00, 0x00, 0x00,
    'S'.code.toByte(), 'e'.code.toByte(), 'n'.code.toByte(), 's'.code.toByte(), 'o'.code.toByte(),
    'r'.code.toByte(), 'W'.code.toByte(), 'r'.code.toByte(), 'i'.code.toByte(), 't'.code.toByte(),
    'e'.code.toByte(), 'r'.code.toByte(), 0x00,
    0x00, 0x13,
)

private val GOLDEN_DELETE = byteArrayOf(
    0x01, 0x80.toByte(), 0x01, 0x00, 0x01, 0x02, 0x03, 0x04,
    0x03, 0x01, 0x04, 0x00,
    0x00, 0x02, 0x00, 0x15,
)

private val GOLDEN_WRITE_DATA = byteArrayOf(
    0x01, 0x80.toByte(), 0x03, 0x00, 0x01, 0x02, 0x03, 0x04,
    0x07, 0x01, 0x06, 0x00,
    0x00, 0x04, 0x00, 0x15, 0x19, 0x00,
)

private val GOLDEN_READ_DATA = byteArrayOf(
    0x01, 0x80.toByte(), 0x02, 0x00, 0x01, 0x02, 0x03, 0x04,
    0x08, 0x01, 0x08, 0x00,
    0x00, 0x03, 0x00, 0x26, 0x01, 0x00, 0x00, 0x00,
)

// A second CREATE, appended to the same session: object_id=pack(raw=
// 0x010,kind=TOPIC), the real two-level ObjectVariant::ByReference
// ("HelloWorldTopic") under parent=pack(raw=0x001,kind=PARTICIPANT),
// request_id=5, sequence_nr=4. OBJK_TOPIC's own representation carries
// its participant's ObjectId (commit 31c62df2a63, "xrce:
// OBJK_TOPIC_Representation carries its participant's ObjectId"), the
// same trailing field OBJK_PUBLISHER's representation carries above --
// matches endpoints/testdata/xrce-client/xrce_client_create_topic.bin,
// generated by endpoints/golden-gen, not a hand-picked byte string.
private val GOLDEN_CREATE_TOPIC = byteArrayOf(
    0x01, 0x80.toByte(), 0x04, 0x00, 0x01, 0x02, 0x03, 0x04,
    0x01, 0x01, 0x1e, 0x00,
    0x00, 0x05, 0x01, 0x02,
    0x02, 0x01, 0x00, 0x00, 0x10, 0x00, 0x00, 0x00,
    'H'.code.toByte(), 'e'.code.toByte(), 'l'.code.toByte(), 'l'.code.toByte(), 'o'.code.toByte(),
    'W'.code.toByte(), 'o'.code.toByte(), 'r'.code.toByte(), 'l'.code.toByte(), 'd'.code.toByte(),
    'T'.code.toByte(), 'o'.code.toByte(), 'p'.code.toByte(), 'i'.code.toByte(), 'c'.code.toByte(), 0x00,
    0x00, 0x11,
)

private fun stateMachine() {
    val c = XrceClient(STATE_KEY)
    check(c.state == XrceClientState.DISCONNECTED, "new client is disconnected")
    check(c.clientKey.contentEquals(STATE_KEY), "client_key stored")

    c.connect(SESSION_ID)
    check(c.state == XrceClientState.CONNECTING, "state == connecting")
    try {
        c.connect(SESSION_ID)
        check(false, "second connect() rejected")
    } catch (e: XrceClientError) { }

    c.markConnected()
    check(c.state == XrceClientState.CONNECTED, "state == connected")

    val r1 = c.createObject()
    val r2 = c.deleteObject()
    val r3 = c.requestWrite()
    val r4 = c.requestRead()
    check(r1 == 1 && r2 == 2 && r3 == 3 && r4 == 4, "request ids strictly monotonic")

    c.disconnect()
    check(c.state == XrceClientState.DISCONNECTED, "disconnect -> disconnected")
}

private fun rejectedBeforeConnect() {
    val c = XrceClient(STATE_KEY)
    try { c.createObject(); check(false, "createObject before connect rejected") } catch (e: XrceClientError) { }
    try { c.requestWrite(); check(false, "requestWrite before connect rejected") } catch (e: XrceClientError) { }
    try { c.requestRead(); check(false, "requestRead before connect rejected") } catch (e: XrceClientError) { }
}

private fun framing() {
    val createClient = XrceFrame.createClient(SESSION_ID, FIXTURE_KEY)
    check(createClient.contentEquals(GOLDEN_CREATE_CLIENT),
        "CREATE_CLIENT byte-identical to xrce_client_create_client.bin")
    // Requested session >= 128: header 0x80, no client key (§8.3.2.1); payload keeps 0x81.
    val high = XrceFrame.createClient(0x81, FIXTURE_KEY)
    check(high.size == createClient.size - 4 && high[0] == 0x80.toByte() && high[20] == 0x81.toByte(),
        "CREATE_CLIENT session 0x81: header 0x80 without client key, payload 0x81")

    val writer = xrceObjectId(0x001, XrceObjectKind.DATAWRITER)
    val publisher = xrceObjectId(0x001, XrceObjectKind.PUBLISHER)
    val create = XrceFrame.create(SESSION_ID, FIXTURE_KEY, 0, 1,
        writer, XrceObjectKind.DATAWRITER, "SensorWriter", publisher)
    check(create.contentEquals(GOLDEN_CREATE), "CREATE byte-identical to xrce_client_create.bin")

    val delete = XrceFrame.delete(SESSION_ID, FIXTURE_KEY, 1, 2, writer)
    check(delete.contentEquals(GOLDEN_DELETE), "DELETE byte-identical to xrce_client_delete.bin")

    val readData = XrceFrame.readData(SESSION_ID, FIXTURE_KEY, 2, 3,
        xrceObjectId(0x002, XrceObjectKind.DATAREADER), 0x01)
    check(readData.contentEquals(GOLDEN_READ_DATA), "READ_DATA byte-identical to xrce_client_read_data.bin")

    val writeData = XrceFrame.writeData(SESSION_ID, FIXTURE_KEY, 3, 4,
        writer, byteArrayOf(0x19, 0x00))
    check(writeData.contentEquals(GOLDEN_WRITE_DATA), "WRITE_DATA byte-identical to xrce_client_write_data.bin")

    val topic = xrceObjectId(0x010, XrceObjectKind.TOPIC)
    val participant = xrceObjectId(0x001, XrceObjectKind.PARTICIPANT)
    val createTopic = XrceFrame.create(SESSION_ID, FIXTURE_KEY, 4, 5,
        topic, XrceObjectKind.TOPIC, "HelloWorldTopic", participant)
    check(createTopic.contentEquals(GOLDEN_CREATE_TOPIC),
        "CREATE(topic) byte-identical to xrce_client_create_topic.bin")
}

private val REP_ABSENT = intArrayOf(
    0x58, 0x52, 0x43, 0x45, 0x01, 0x00, 0x00, 0x00, 0x01, 0x02, 0x03, 0x04, 0x01, 0x00, 0xfc, 0x01,
).map { it.toByte() }.toByteArray()
private val REP_PRESENT_APPENDABLE = intArrayOf(
    0x58, 0x52, 0x43, 0x45, 0x01, 0x00, 0x00, 0x00,
    0x08, 0x00, 0x00, 0x00,
    0x8c, 0xaa, 0x88, 0x5a, 0x00, 0x65, 0xcd, 0x1d,
    0x01, 0x02, 0x03, 0x04, 0x01, 0x00, 0xfc, 0x01,
).map { it.toByte() }.toByteArray()
private val REP_PRESENT_FINAL = intArrayOf(
    0x58, 0x52, 0x43, 0x45, 0x01, 0x00, 0x00, 0x00,
    0x8c, 0xaa, 0x88, 0x5a, 0x00, 0x65, 0xcd, 0x1d,
    0x01, 0x02, 0x03, 0x04, 0x01, 0x00, 0xfc, 0x01,
).map { it.toByte() }.toByteArray()

// Representation timestamps (DDS-XRCE 1.0 7.8.2.1 prose vs Annex A / B.1).
private fun representationTimestamps() {
    val sec = 0x5A88AA8C
    val nsec = 0x1DCD6500
    check(XrceFrame.encodeClientRepresentation(0x0100, 0, FIXTURE_KEY, SESSION_ID, 508).contentEquals(REP_ABSENT),
        "representation: default is absent, 16 octets")
    check(XrceFrame.encodeClientRepresentation(0x0100, 0, FIXTURE_KEY, SESSION_ID, 508,
        RepresentationTimestamps.ABSENT, XrceUnannotatedTypes.APPENDABLE, sec, nsec).contentEquals(REP_ABSENT),
        "representation: absent ignores the timestamp")
    check(XrceFrame.encodeClientRepresentation(0x0100, 0, FIXTURE_KEY, SESSION_ID, 508,
        RepresentationTimestamps.PRESENT, XrceUnannotatedTypes.APPENDABLE, sec, nsec)
        .contentEquals(REP_PRESENT_APPENDABLE), "representation: present, appendable, 28 octets")
    check(XrceFrame.encodeClientRepresentation(0x0100, 0, FIXTURE_KEY, SESSION_ID, 508,
        RepresentationTimestamps.PRESENT, XrceUnannotatedTypes.FINAL, sec, nsec)
        .contentEquals(REP_PRESENT_FINAL), "representation: present, final, 24 octets")
    val frame = XrceFrame.createClient(SESSION_ID, FIXTURE_KEY, RepresentationTimestamps.PRESENT,
        XrceUnannotatedTypes.APPENDABLE, sec, nsec)
    check(frame.size == 8 + 4 + 28 && frame[10].toInt() == 28 && frame[11].toInt() == 0,
        "CREATE_CLIENT present: submessage length 28")
    val c = XrceClient(FIXTURE_KEY, RepresentationTimestamps.PRESENT)
    c.connect(SESSION_ID)
    check(c.frameCreateClient().size == 8 + 4 + 28, "client option present: CREATE_CLIENT grows to 28 octets")
    check(XrceClient(FIXTURE_KEY).representationTimestamps == RepresentationTimestamps.ABSENT,
        "client default is absent")
}

private fun endToEnd() {
    val c = XrceClient(FIXTURE_KEY)
    c.connect(SESSION_ID)
    check(XrceFrame.createClient(c.sessionId, c.clientKey).contentEquals(GOLDEN_CREATE_CLIENT), "e2e CREATE_CLIENT frame")
    c.markConnected()

    val writer = xrceObjectId(0x001, XrceObjectKind.DATAWRITER)
    val publisher = xrceObjectId(0x001, XrceObjectKind.PUBLISHER)
    val req = c.createObject()
    check(
        XrceFrame.create(c.sessionId, c.clientKey, 0, req,
            writer, XrceObjectKind.DATAWRITER, "SensorWriter", publisher).contentEquals(GOLDEN_CREATE),
        "e2e CREATE frame",
    )

    val deleteReq = c.deleteObject()
    check(deleteReq == 2, "e2e delete request id 2 (create_object above took 1)")

    val readReq = c.requestRead()
    check(readReq == 3, "e2e read request id 3")

    val writeReq = c.requestWrite()
    check(writeReq == 4, "e2e write request id 4")
}

fun main() {
    stateMachine()
    rejectedBeforeConnect()
    framing()
    representationTimestamps()
    endToEnd()

    if (failures != 0) {
        println("$failures check(s) FAILED")
        exitProcess(1)
    }
    println("XRCE client (Kotlin): all checks OK")
}
