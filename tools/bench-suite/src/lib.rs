//! Shared helpers for the v1.2 benchmark suite.
//!
//! Crate `zerodds-bench-suite`. Safety classification: **COMFORT**.
//! Test/bench only, no runtime dependency. No unsafe,
//! but also no formal no-panic contract for the harness
//! helper — `make_payload` can panic on OOM (bench runs
//! on a dedicated machine).
//!
//! # Scope
//!
//! Citable perf measurements need a **standardized
//! Harness**: same payload generation, same timing pattern,
//! documentable reproduction recipe. This crate provides the
//! Bausteine:
//!
//! - [`PAYLOAD_SIZES`] — canonical payload axis (9 sizes from
//!   32 B bis 4 MB).
//! - `TransportDriver` — trait for a uniform sender
//!   Lifecycle (prepare → warmup → measure).
//! - `make_payload` — deterministically generated bytes (no
//!   allocator noise, no RNG overhead in the hot path).
//!
//! The bench targets (`benches/*.rs`) use these building blocks +
//! `criterion`. Reports land as JSON in `target/criterion/` and
//! are referenced via `internal/perf/baseline-*.md`.

#![warn(missing_docs)]

/// Canonical payload size axis. Two scale decades per stage,
/// up to 4 MiB (enough for high-res camera frames after fragmentation).
///
/// **Design decision** — we always measure these 9 points together,
/// so reports are directly comparable across runs. Ad-hoc sizes
/// do not belong in the suite; they lead to inconsistent plots.
pub const PAYLOAD_SIZES: &[usize] = &[
    32, 128, 1_024,     // 1 KiB
    4_096,     // 4 KiB
    16_384,    // 16 KiB
    65_536,    // 64 KiB — UDP-DGRAM-cap, meaningful boundary
    262_144,   // 256 KiB
    1_048_576, // 1 MiB
    4_194_304, // 4 MiB
];

/// Largest payload on the axis — for Vec preallocation in the fixture.
pub const MAX_PAYLOAD: usize = 4_194_304;

/// Generate a deterministic payload. LCG-based, so the
/// content is not all-zero (some transports/OSes have a fastpath
/// for zero pages, which skews baselines).
#[must_use]
pub fn make_payload(size: usize) -> Vec<u8> {
    let mut out = Vec::with_capacity(size);
    let mut state: u64 = 0xDEAD_BEEF_CAFE_BABE;
    for _ in 0..size {
        state = state
            .wrapping_mul(6_364_136_223_846_793_005)
            .wrapping_add(1);
        out.push((state >> 33) as u8);
    }
    out
}

/// Bench-relevant payload sizes with human-readable label.
/// For BenchmarkId parameter.
#[must_use]
pub fn size_label(size: usize) -> String {
    if size < 1024 {
        format!("{size}B")
    } else if size < 1024 * 1024 {
        format!("{}KiB", size / 1024)
    } else {
        format!("{}MiB", size / (1024 * 1024))
    }
}

#[cfg(test)]
#[allow(clippy::unwrap_used, clippy::expect_used)]
mod tests {
    use super::*;

    #[test]
    fn payload_sizes_are_sorted_ascending() {
        for pair in PAYLOAD_SIZES.windows(2) {
            assert!(pair[0] < pair[1]);
        }
    }

    #[test]
    fn max_payload_matches_last_entry() {
        assert_eq!(MAX_PAYLOAD, *PAYLOAD_SIZES.last().unwrap());
    }

    #[test]
    fn make_payload_is_deterministic() {
        let a = make_payload(128);
        let b = make_payload(128);
        assert_eq!(a, b);
    }

    #[test]
    fn make_payload_is_not_all_zero() {
        let p = make_payload(1024);
        assert!(p.iter().any(|&b| b != 0));
    }

    #[test]
    fn size_label_formats() {
        assert_eq!(size_label(32), "32B");
        assert_eq!(size_label(1024), "1KiB");
        assert_eq!(size_label(1_048_576), "1MiB");
    }
}
