//! The two tables, rendered from the ledger and from nothing else.
//!
//! Same shape, one for each direction. One row per (case, encoding,
//! byte order); one column per system; a diff explanation that is
//! empty exactly when every system that was asked answered the same;
//! and the setting that reproduces each difference, spelled as the
//! command line takes it.
//!
//! ## The diff column is derived, not written
//!
//! For each row the systems that produced bytes are grouped by the
//! byte string. One group is agreement. Two or more is a difference,
//! and what the column says is which groups there are, how long each
//! one's payload is and at which octet the first two diverge. No
//! sentence about *why* is invented here: a cause belongs in
//! `docs/wire-feature-inventory.md`, which cites a clause for it, and a
//! generated guess beside a measured byte offset would be taken for a
//! measurement.
//!
//! ## The mitigation column is a measurement
//!
//! For each group that is not the one ZeroDDS's default is in, the twelve
//! configurations of `crates/wire-probe/tests/three_column_gate.rs` are
//! searched for one whose bytes **equal that group's**. What the column
//! prints is that configuration's flag. Where no configuration
//! reproduces the group the column says `none`, which is the finding:
//! a divergence a setting covers and a divergence nothing covers are
//! different things, and only one of them can be answered on request.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use crate::ledger::{Entry, Ledger, Outcome, RowIds};
use crate::rust_column::{self, CaseSweep};
use crate::systems::SYSTEMS;
use crate::{Case, tree};

/// Which direction a table is for.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Direction {
    /// What each system put on the wire.
    Write,
    /// What each system got back off it.
    Read,
}

impl Direction {
    const fn title(self) -> &'static str {
        match self {
            Self::Write => "The write direction",
            Self::Read => "The read direction",
        }
    }

    const fn file(self) -> &'static str {
        match self {
            Self::Write => "write.md",
            Self::Read => "read.md",
        }
    }
}

/// Render one table.
#[must_use]
pub fn render(
    direction: Direction,
    ledger: &Ledger,
    cases: &[Case],
    sweeps: &BTreeMap<String, CaseSweep>,
    ids: &mut RowIds,
) -> String {
    let by_case: BTreeMap<&str, &Case> = cases
        .iter()
        .map(|case| (case.name.as_str(), case))
        .collect();
    let mut rows: BTreeMap<String, Vec<&Entry>> = BTreeMap::new();
    let mut order: Vec<String> = Vec::new();
    for entry in &ledger.entries {
        let key = entry.row_key();
        if !rows.contains_key(&key) {
            order.push(key.clone());
        }
        rows.entry(key).or_default().push(entry);
    }

    let mut out = header(direction, order.len());
    for key in &order {
        let entries = &rows[key];
        let first = entries[0];
        let case = by_case[first.case.as_str()];
        let number = ids.number(key);
        let sweep = sweeps.get(&first.case);
        out.push_str(&row(direction, number, case, first, entries, sweep));
    }
    out
}

fn header(direction: Direction, rows: usize) -> String {
    let mut out = format!(
        "<!-- generated by tools/interop-results; do not edit -->\n\
         # {}\n\n\
         {} rows: one per corpus case, encoding and byte order. \
         {} systems: one column each, and every cell links to a file. \
         **A cell is never blank** — a blank reads as agreement, and most \
         of the holes in a cross-implementation matrix are not \
         agreements. The words are:\n\n\
         | word | what it means |\n|---|---|\n\
         | `bytes` | the system ran and these are the octets it produced |\n\
         | `same` | it read those octets back and got the case's own sample |\n\
         | `different` | it read them back and got something else, which is a defect wherever it appears |\n\
         | `refused` | it ran and would not take the type or the value; the link carries its own sentence |\n\
         | `unwritten` | nothing to read, because the write direction produced nothing |\n\
         | `=` | this row's run *is* the linked encoding's run: a foreign `--encoding` selects the encoding **version**, and the framing follows the type's extensibility |\n\
         | `no xcdr2` | the system has no encoding version 2 at all — Fast CDR 1.0.24 has none and CORBA CDR predates XTypes |\n\
         | `one order` | the system writes one byte order and this is the other one |\n\
         | `no form` | the construct has no form in this system's type model, so its front end never saw the case |\n\
         | `no probe` | the toolchain exists and no probe in this tree drives it |\n\
         | `not measured` | expressible, a harness in this tree produces it, and no run is recorded |\n\n\
         A cell that carries `w` and a number is one whose **front end \
         said something** about the type — that many distinct warnings, \
         linking to the file that holds them. It is a column of its own \
         and not a note beside a refusal, because the row it matters \
         most in is the one where nothing went wrong. \
         [`WARNINGS.md`](WARNINGS.md) has every warning text, its case \
         count, what it means, and which of them changes what a row \
         below says.\n\n\
         Columns 3 and 4 link to the case's own IDL and sample; the twelve \
         after them to that system's result; then what differs, and the \
         setting that reproduces it. `SYSTEMS.md` says what each column \
         is and which of them a machine without a licensed toolchain can \
         reach.\n\n",
        direction.title(),
        rows,
        SYSTEMS.len()
    );
    let _ = write!(out, "| № | what it tests | IDL | values |");
    for system in &SYSTEMS {
        let _ = write!(out, " {} |", system.label);
    }
    out.push_str(" what differs | what reproduces it |\n|---:|---|---|---|");
    for _ in &SYSTEMS {
        out.push_str("---|");
    }
    out.push_str("---|---|\n");
    out
}

fn row(
    direction: Direction,
    number: u32,
    case: &Case,
    first: &Entry,
    entries: &[&Entry],
    sweep: Option<&CaseSweep>,
) -> String {
    let mut out = format!(
        "| {number} | {} `{}` {}/{} | [idl](../interop-corpus/{}/type.idl) | [json](../interop-corpus/{}/values.json) |",
        case.description, first.case, first.encoding, first.endian, first.case, first.case
    );
    for system in &SYSTEMS {
        // `assemble::build` pushes one entry per system per row, in this
        // order. A row that is short is a defect in the assembler and
        // says so rather than being rendered a column narrower, which
        // would shift every cell after it under the wrong heading.
        match entries.iter().find(|entry| entry.system == system.id) {
            Some(entry) => {
                out.push(' ');
                out.push_str(&cell(direction, entry));
                out.push_str(" |");
            }
            None => out.push_str(" MISSING CELL |"),
        }
    }
    let (mut difference, mitigation) = analysis(direction, entries, sweep);
    // A row where every system agreed and one of them warned is not a
    // row where every system agreed silently, and the diff column is
    // where a reader looks to find out whether a row has anything in
    // it.
    let warned: Vec<&str> = entries
        .iter()
        .filter(|entry| entry.warnings > 0)
        .map(|entry| entry.system)
        .collect();
    if !warned.is_empty() {
        if !difference.is_empty() {
            difference.push_str("; ");
        }
        let _ = write!(difference, "{} warned about the type", names(&warned));
    }
    let _ = writeln!(out, " {difference} | {mitigation} |");
    out
}

fn cell(direction: Direction, entry: &Entry) -> String {
    let body = cell_outcome(direction, entry);
    if entry.warnings == 0 {
        return body;
    }
    // The marker is on the cell and not only in the diff column,
    // because the row it matters most in is the one whose diff column
    // is empty: a system whose bytes agree while its front end warned
    // about the type is not the same as one that agreed silently.
    format!(
        "{body} [w{}]({})",
        entry.warnings,
        tree::warnings_path(&entry.case, entry.system)
    )
}

fn cell_outcome(direction: Direction, entry: &Entry) -> String {
    let outcome = match direction {
        Direction::Write => &entry.write,
        Direction::Read => &entry.read,
    };
    match (direction, outcome) {
        (Direction::Write, Outcome::Bytes(hex)) => {
            format!("[{}B]({})", hex.len() / 2, tree::bin_path(entry))
        }
        (Direction::Write, Outcome::VersionAlias(canonical)) => format!(
            "[= {canonical}]({}/{}/{canonical}.{}.bin)",
            entry.case, entry.system, entry.endian
        ),
        (Direction::Read, Outcome::VersionAlias(canonical)) => {
            format!(
                "[= {canonical}]({})",
                tree::read_path(&entry.case, entry.system)
            )
        }
        (Direction::Read, _) => format!(
            "[{}]({})",
            outcome.word(),
            tree::read_path(&entry.case, entry.system)
        ),
        (Direction::Write, _) => format!(
            "[{}]({})",
            outcome.word(),
            tree::status_path(&entry.case, entry.system)
        ),
    }
}

/// The last two columns: what differs on this row, and the setting that
/// reproduces each group that is not this project's default.
///
/// Public because [`crate::page`] renders the same two sentences and
/// deriving them a second time would let two derivations of one
/// measurement disagree.
#[must_use]
pub fn analysis(
    direction: Direction,
    entries: &[&Entry],
    sweep: Option<&CaseSweep>,
) -> (String, String) {
    if direction == Direction::Read {
        return read_analysis(entries);
    }
    let mut groups: BTreeMap<&str, Vec<&str>> = BTreeMap::new();
    let mut refusals: Vec<&str> = Vec::new();
    for entry in entries {
        match &entry.write {
            Outcome::Bytes(hex) => groups.entry(hex).or_default().push(entry.system),
            Outcome::Refused(_) => refusals.push(entry.system),
            _ => {}
        }
    }
    if groups.len() < 2 {
        // One byte string, or none. A refusal beside bytes is a
        // difference in kind and is worth a word; a row where nothing
        // ran at all is not.
        if groups.len() == 1 && !refusals.is_empty() {
            return (
                format!(
                    "{} produced bytes, {} refused",
                    names(&groups.values().next().cloned().unwrap_or_default()),
                    names(&refusals)
                ),
                String::new(),
            );
        }
        return (String::new(), String::new());
    }

    // The group ZeroDDS's default is in is the one the others are
    // described against: the tables are this project's, and a reader
    // asking what to set is asking what to set here.
    let ours = groups
        .iter()
        .find(|(_, systems)| systems.contains(&"zerodds-rust"))
        .map(|(hex, _)| *hex);
    let mut difference = String::new();
    let mut mitigation = String::new();
    let first = ours.unwrap_or_else(|| groups.keys().next().copied().unwrap_or_default());
    let entry = entries[0];
    // The reference group is printed first, whatever order the byte
    // strings sort in: the rest of the sentence describes the others
    // against it, and a description that came before the thing it
    // described read as one run of nonsense.
    if let Some(systems) = groups.get(first) {
        let _ = write!(difference, "{} `{}B`", names(systems), first.len() / 2);
    }
    for (hex, systems) in &groups {
        if *hex == first {
            continue;
        }
        let _ = write!(
            difference,
            "; {} `{}B`{}",
            names(systems),
            hex.len() / 2,
            divergence(first, hex)
        );
        let flag = sweep
            .and_then(|sweep| rust_column::reproduced_by(sweep, entry.encoding, entry.endian, hex))
            .map_or_else(
                || "none".to_string(),
                |configuration| format!("`{}`", configuration.flag),
            );
        if !mitigation.is_empty() {
            mitigation.push_str("; ");
        }
        let _ = write!(mitigation, "{} → {flag}", names(systems));
    }
    if !refusals.is_empty() {
        let _ = write!(difference, "; {} refused", names(&refusals));
    }
    (difference, mitigation)
}

/// The read direction's last two columns.
///
/// A read verdict is not a byte string, so there is nothing to group:
/// what matters is whether any system that was asked got something
/// other than the sample back, which is a defect wherever it appears.
fn read_analysis(entries: &[&Entry]) -> (String, String) {
    let mut different: Vec<&str> = Vec::new();
    let mut refused: Vec<&str> = Vec::new();
    let mut same = 0_usize;
    for entry in entries {
        match &entry.read {
            Outcome::Same => same += 1,
            Outcome::Different(_) => different.push(entry.system),
            Outcome::Refused(_) => refused.push(entry.system),
            _ => {}
        }
    }
    if different.is_empty() && refused.is_empty() {
        return (String::new(), String::new());
    }
    let mut difference = String::new();
    if !different.is_empty() {
        let _ = write!(
            difference,
            "{} read back a value the sample does not carry",
            names(&different)
        );
    }
    if !refused.is_empty() {
        if !difference.is_empty() {
            difference.push_str("; ");
        }
        let _ = write!(difference, "{} would not read them", names(&refused));
    }
    if same > 0 {
        let _ = write!(difference, "; {same} read the sample back");
    }
    // A read defect is not a dialect question: no setting makes a
    // decoder that lost a value find it again.
    (difference, String::new())
}

/// Where two byte strings first differ, and by how much.
fn divergence(ours: &str, theirs: &str) -> String {
    let first = ours
        .as_bytes()
        .iter()
        .zip(theirs.as_bytes())
        .position(|(a, b)| a != b)
        .map(|nibble| nibble / 2);
    match first {
        None if theirs.len() > ours.len() => format!(
            ", {} more octets at the end",
            (theirs.len() - ours.len()) / 2
        ),
        None => format!(
            ", {} fewer octets at the end",
            (ours.len() - theirs.len()) / 2
        ),
        Some(octet) => format!(", first differing octet {octet}"),
    }
}

fn names(systems: &[&str]) -> String {
    systems
        .iter()
        .map(|id| crate::systems::system(id).map_or(*id, |system| system.label))
        .collect::<Vec<_>>()
        .join("/")
}

/// The file each table is written to.
#[must_use]
pub const fn file(direction: Direction) -> &'static str {
    direction.file()
}

/// Why the three ORB columns carry 416, 198 and 194 cells.
///
/// All three are XCDR1 and payload only and all three are offered the
/// same cases, so a reader who finds one of them twice the size of the
/// other two is owed a reason. The reason is two reasons, and only one
/// of them is about what the ORBs accept:
///
///  * **the byte-order width.** omniORB writes both orders and TAO and
///    JacORB one each, so the same 218 cases are 436 cells for omniORB
///    and 218 for each of the others. That accounts for the factor of
///    two and for nothing else;
///  * **the cases each one refused**, which is 10, 20 and 24 and is the
///    only part of the difference that says anything about the ORBs.
///
/// Generated out of the ledger rather than written, because a figure
/// in a paragraph that nobody recomputes is a figure that goes stale
/// the next time a case is added.
fn orb_arithmetic(ledger: &Ledger) -> String {
    let mut out = String::from(
        "\n## Why the three ORB columns are not the same size\n\n\
         All three are XCDR1 and payload only — CORBA CDR *is* XCDR1, CORBA 3.3 part 2 \u{a7}9.3 \
         — and all three are offered the same cases, so the difference between them is worth \
         the arithmetic. It is two things, and only the second is about the ORBs:\n\n\
         | column | cases with a CORBA form | orders it writes | cells offered | cells with bytes | cases it refused |\n\
         |---|---:|---:|---:|---:|---:|\n",
    );
    let mut rows: Vec<(&str, usize, usize, usize, usize, usize)> = Vec::new();
    for system in SYSTEMS
        .iter()
        .filter(|system| system.kind == crate::systems::Kind::Orb)
    {
        let mut offered = 0;
        let mut with_bytes = 0;
        let mut form: BTreeMap<&str, bool> = BTreeMap::new();
        let mut refused: BTreeMap<&str, bool> = BTreeMap::new();
        for entry in &ledger.entries {
            if entry.system != system.id || entry.encoding != "plain-cdr1" {
                continue;
            }
            let has_form = !matches!(entry.write, Outcome::NoForm(_));
            *form.entry(entry.case.as_str()).or_insert(false) |= has_form;
            if !has_form || !system.writes_orders.contains(&entry.endian) {
                continue;
            }
            offered += 1;
            match entry.write {
                Outcome::Bytes(_) => with_bytes += 1,
                _ => {
                    refused.insert(entry.case.as_str(), true);
                }
            }
        }
        let cases = form.values().filter(|had| **had).count();
        rows.push((
            system.id,
            cases,
            system.writes_orders.len(),
            offered,
            with_bytes,
            refused.len(),
        ));
    }
    for (id, cases, orders, offered, with_bytes, refused) in &rows {
        let _ = writeln!(
            out,
            "| `{id}` | {cases} | {orders} | {offered} | {with_bytes} | {refused} |"
        );
    }
    out.push_str(
        "\nThe `cells offered` column is `cases with a CORBA form` times `orders it writes`, \
         and it is where the factor of two lives: `ACE_OutputCDR::write_4` swaps only when \
         libACE was built with `ACE_ENABLE_SWAP_ON_WRITE` and this build was not, and \
         `org.jacorb.orb.CDROutputStream` has no `setLittleEndian` at all — only \
         `CDRInputStream` does. Neither is a result; both are recorded once here and cited by \
         every `one order` cell.\n\n\
         What the last column holds is the part that is a result, and \
         [`write.md`](write.md) carries each refusal with the ORB's own sentence. Two of them \
         belong to every ORB and to none of them: `primitive-char-above-latin1` and \
         `primitive-wchar-above-bmp` are refused by this project's **fill**, before any ORB \
         front end runs, because the OMG IDL-to-C++ and IDL-to-Java mappings give `char` and \
         `wchar` no room for the value.\n",
    );
    out
}

/// A row of the case-by-case table, keyed by the cell it counts: the
/// system id, the case name, the direction (`write` or `read`), the
/// verdict token and the tool's own reason line. The reason is a `String`
/// because it is the product's text, not one of our tokens.
type PerCaseKey<'a> = (&'a str, &'a str, &'static str, &'static str, String);

/// The same key without the case. A structural verdict belongs to the
/// product or the machine rather than to any one case, so it is counted
/// once per (system, direction, verdict) instead of being repeated across
/// every case it covers.
type StructuralKey<'a> = (&'a str, &'static str, &'static str, String);

/// `SYSTEMS.md`: one section per column, and the arithmetic of what a
/// machine without a licensed toolchain reaches.
#[must_use]
/// `REFUSALS.md`: every cell without a byte sequence, case by case.
///
/// One row per (system, case, direction, verdict, reason): the ledger
/// repeats a verdict once per slot, and a reader asking "what did RTI
/// say to this case" wants the sentence once with the slot count. The
/// structural verdicts — a byte order the product cannot write, an
/// encoding that is an alias of another, a toolchain this machine does
/// not carry — are folded to one row per (system, verdict), because
/// their reason is a property of the product or the machine and not of
/// any case. Where a sweep archived the tool's complete output, the row
/// points at it: `sources/toolchain-logs/<system>/<case>.log`.
pub fn refusals_document(ledger: &Ledger, results_root: &std::path::Path) -> String {
    // Per-case verdicts: the run happened, or was refused, for this case.
    let per_case = |outcome: &Outcome| {
        matches!(
            outcome,
            Outcome::Refused(_)
                | Outcome::NoForm(_)
                | Outcome::GeneratorDefect(_)
                | Outcome::MappingDivergence(_)
                | Outcome::HarnessGap(_)
                | Outcome::OutOfProfile(_)
        )
    };
    // Structural verdicts: the reason is the product's or the machine's.
    let structural = |outcome: &Outcome| {
        matches!(
            outcome,
            Outcome::NotMeasured(_)
                | Outcome::NoProbe
                | Outcome::NoVersion2
                | Outcome::OneOrderOnly
                | Outcome::VersionAlias(_)
        )
    };
    let mut rows: BTreeMap<PerCaseKey<'_>, usize> = BTreeMap::new();
    let mut folded: BTreeMap<StructuralKey<'_>, usize> = BTreeMap::new();
    for entry in &ledger.entries {
        for (direction, outcome) in [("write", &entry.write), ("read", &entry.read)] {
            if per_case(outcome) {
                *rows
                    .entry((
                        entry.system,
                        &entry.case,
                        direction,
                        outcome.token(),
                        outcome.detail(),
                    ))
                    .or_default() += 1;
            } else if structural(outcome) {
                *folded
                    .entry((entry.system, direction, outcome.token(), outcome.detail()))
                    .or_default() += 1;
            }
        }
    }
    let mut out = String::from(
        "<!-- generated by tools/interop-results; do not edit -->\n\
         # Every cell without a byte sequence, case by case\n\n\
         One row per (case, direction, verdict, reason) with the number \
         of slots it covers; the reason is the tool's own line. Where \
         the sweep archived the tool's complete output — stdout and \
         stderr — the last column names the file that holds it. \
         Structural verdicts close each section: their reason belongs \
         to the product or the machine, not to a case.\n",
    );
    for system in &SYSTEMS {
        let mine: Vec<(&PerCaseKey<'_>, &usize)> = rows
            .iter()
            .filter(|((id, ..), _)| *id == system.id)
            .collect();
        let mine_folded: Vec<(&StructuralKey<'_>, &usize)> = folded
            .iter()
            .filter(|((id, ..), _)| *id == system.id)
            .collect();
        if mine.is_empty() && mine_folded.is_empty() {
            continue;
        }
        let cases: std::collections::BTreeSet<&str> =
            mine.iter().map(|((_, case, ..), _)| *case).collect();
        let _ = write!(
            out,
            "\n## `{}` — {} case(s) answered without bytes\n\n",
            system.id,
            cases.len()
        );
        if !mine.is_empty() {
            out.push_str(
                "| case | direction | verdict | slots | the tool's own words | full output |\n\
                 |---|---|---|---:|---|---|\n",
            );
            for ((_, case, direction, word, detail), slots) in mine {
                let log = format!("sources/toolchain-logs/{}/{case}.log", system.id);
                let full = if results_root.join(&log).is_file() {
                    format!("`{log}`")
                } else {
                    String::from("—")
                };
                let _ = writeln!(
                    out,
                    "| `{case}` | {direction} | {word} | {slots} | {} | {full} |",
                    detail.replace('|', "\\|")
                );
            }
        }
        if !mine_folded.is_empty() {
            out.push_str(
                "\n| direction | verdict | slots | why, for every one of them |\n\
                 |---|---|---:|---|\n",
            );
            for ((_, direction, word, detail), slots) in mine_folded {
                let why = if detail.is_empty() {
                    // The wordless structural verdicts carry their
                    // reason in `SYSTEMS.md`'s note for the column.
                    "a structural limit of the product; SYSTEMS.md carries it"
                } else {
                    detail.as_str()
                };
                let _ = writeln!(
                    out,
                    "| {direction} | {word} | {slots} | {} |",
                    why.replace('|', "\\|")
                );
            }
        }
    }
    out
}

/// The columns document: what each system in the ledger is, what
/// produces its rows, and how many of those rows carry bytes.
///
/// Renders one table over `SYSTEMS`, then the ORB arithmetic, then a
/// section per system. The split by `reachable_without_licence` states
/// how much of the matrix a machine without a licensed toolchain can
/// reproduce — the same matrix with its rows named, not a smaller one.
pub fn systems_document(ledger: &Ledger) -> String {
    let mut counts: BTreeMap<&str, (usize, usize)> = BTreeMap::new();
    for entry in &ledger.entries {
        let row = counts.entry(entry.system).or_default();
        row.1 += 1;
        if matches!(entry.write, Outcome::Bytes(_)) {
            row.0 += 1;
        }
    }
    let mut out = String::from(
        "<!-- generated by tools/interop-results; do not edit -->\n\
         # The twelve columns\n\n\
         What each column is, what produces it, and what it cannot be \
         asked by construction. A structural limit is recorded here once \
         and cited by every cell it explains, because it is a property of \
         the implementation and not a result of any run.\n\n\
         | column | product | rows with bytes | of | regenerated by |\n\
         |---|---|---:|---:|---|\n",
    );
    for system in &SYSTEMS {
        let (bytes, total) = counts.get(system.id).copied().unwrap_or((0, 0));
        let _ = writeln!(
            out,
            "| `{}` | {} | {bytes} | {total} | `{}` |",
            system.id, system.version, system.producer
        );
    }
    out.push_str(&orb_arithmetic(ledger));
    out.push_str("\n## What a machine without a licensed toolchain reaches\n\n");
    let mut reachable = 0_usize;
    let mut unreachable = 0_usize;
    for system in &SYSTEMS {
        let (bytes, _) = counts.get(system.id).copied().unwrap_or((0, 0));
        if system.reachable_without_licence {
            reachable += bytes;
        } else {
            unreachable += bytes;
        }
    }
    let _ = writeln!(
        out,
        "{reachable} of the {} rows that carry bytes come from a product such a machine can \
         install; {unreachable} do not. The second number is not a smaller matrix — it is the \
         same matrix with the rows named, one system at a time, below.\n",
        reachable + unreachable
    );
    for system in &SYSTEMS {
        let (bytes, total) = counts.get(system.id).copied().unwrap_or((0, 0));
        let _ = writeln!(
            out,
            "### `{}` — {}\n\n{}\n\n- {bytes} of {total} rows carry bytes.\n\
             - Regenerated by `{}`.\n- Reachable without a licensed toolchain: {}.\n",
            system.id,
            system.version,
            system.note,
            system.producer,
            if system.reachable_without_licence {
                "yes"
            } else {
                "no"
            }
        );
    }
    out
}
