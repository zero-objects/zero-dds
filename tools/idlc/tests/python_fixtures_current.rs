//! The Python fixtures `crates/py/python/tests/_generated/*_gen.py` are
//! `generate --lang python` output, committed for the Python tests. Each
//! names its IDL source, encoding and byte order in its first line. This
//! regenerates every one with the binary under test and compares, so a
//! generator change that leaves a fixture behind fails here, not in a
//! Python run that exercises code the generator no longer writes.

#![allow(clippy::expect_used, clippy::unwrap_used, clippy::panic)]

use std::path::{Path, PathBuf};
use std::process::Command;

fn workspace_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(Path::parent)
        .map(Path::to_path_buf)
        .expect("workspace root")
}

/// The IDL path, `--encoding` and `--endian` a fixture's first line names:
/// ``# Generated by `idlc generate` from <idl>, python (<encoding>, <endian>). Do not edit.``
fn provenance(first_line: &str) -> (&str, &'static str, &'static str) {
    let rest = first_line
        .strip_prefix("# Generated by `idlc generate` from ")
        .unwrap_or_else(|| panic!("not a generated header: {first_line}"));
    let (idl, rest) = rest.split_once(", python (").expect("the language");
    let (encoding, rest) = rest.split_once(", ").expect("the encoding");
    let (endian, _) = rest.split_once(')').expect("the byte order");
    let encoding = match encoding {
        "PlainCdr1" => "xcdr1",
        "PlainCdr2" => "xcdr2",
        other => panic!("encoding {other}"),
    };
    let endian = match endian {
        "Little" => "le",
        "Big" => "be",
        other => panic!("byte order {other}"),
    };
    (idl, encoding, endian)
}

#[test]
fn every_python_fixture_is_what_the_generator_writes_today() {
    let root = workspace_root();
    let dir = root.join("crates/py/python/tests/_generated");
    let mut fixtures: Vec<PathBuf> = std::fs::read_dir(&dir)
        .unwrap()
        .map(|entry| entry.unwrap().path())
        .filter(|path| {
            path.file_name()
                .and_then(|name| name.to_str())
                .is_some_and(|name| name.ends_with("_gen.py"))
        })
        .collect();
    fixtures.sort();
    assert!(fixtures.len() >= 20, "{fixtures:?}");
    let mut stale = Vec::new();
    for fixture in &fixtures {
        let committed = std::fs::read_to_string(fixture).unwrap();
        let (idl, encoding, endian) = provenance(committed.lines().next().unwrap_or(""));
        let name = fixture.file_stem().unwrap().to_string_lossy().into_owned();
        let out = Path::new(env!("CARGO_TARGET_TMPDIR"))
            .join("python-fixtures")
            .join(&name);
        let _ = std::fs::remove_dir_all(&out);
        let run = Command::new(env!("CARGO_BIN_EXE_zerodds-idlc"))
            .current_dir(&root)
            .args(["generate", "--lang", "python", "--encoding", encoding])
            .args(["--endian", endian, "--out"])
            .arg(&out)
            .arg(idl)
            .output()
            .unwrap();
        assert!(
            run.status.success(),
            "{name}: {}",
            String::from_utf8_lossy(&run.stderr)
        );
        let generated: Vec<PathBuf> = std::fs::read_dir(&out)
            .unwrap()
            .map(|entry| entry.unwrap().path())
            .filter(|path| path.extension().is_some_and(|ext| ext == "py"))
            .collect();
        assert_eq!(generated.len(), 1, "{name}: {generated:?}");
        if std::fs::read_to_string(&generated[0]).unwrap() != committed {
            stale.push(name);
        }
    }
    assert!(
        stale.is_empty(),
        "fixtures behind the generator, regenerate them with \
         `zerodds-idlc generate --lang python`: {stale:?}"
    );
}
