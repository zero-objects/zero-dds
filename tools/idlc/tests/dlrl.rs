// -- the pragma-name collision with OpenDDS -------------------------------

/// The same two pragmas OpenDDS's devguide defines, with no
/// `DCPS_DLRL_RELATION` anywhere — the "this could be either dialect"
/// case. `idlc dlrl` reads them as DDS 1.2 §8's regardless of what
/// `idlc check`/`generate` would read them as: which subcommand ran is
/// what disambiguates, not a guess about the author's intent.
const OPENDDS_SHAPED_PRAGMAS: &str = "struct Sensor { long id; double value; };\n\
#pragma DCPS_DATA_TYPE \"Sensor\"\n\
#pragma DCPS_DATA_KEY \"Sensor id\"\n";

#[test]
fn dlrl_reads_the_opendds_shaped_pragmas_as_dlrl_regardless_of_intent() {
    let dir = scratch("dlrl-collision-opendds-shaped");
    std::fs::write(dir.join("sensor.idl"), OPENDDS_SHAPED_PRAGMAS).unwrap();
    let status = idlc()
        .args(["dlrl", "--lang", "cpp", "--out"])
        .arg(dir.join("out"))
        .arg(dir.join("sensor.idl"))
        .status()
        .unwrap();
    assert!(status.success());
    let text = std::fs::read_to_string(dir.join("out/sensor_dlrl.hpp")).unwrap();
    assert!(
        text.contains("class Sensor : public DLRL::ObjectRoot"),
        "{text}"
    );
}

/// The same file through `check`: the two pragmas are read as OpenDDS's,
/// not silently, and the diagnostic says the other reading exists rather
/// than reading as though OpenDDS were the pragma's only meaning.
#[test]
fn check_reads_the_same_file_as_opendds_and_names_the_other_reading() {
    let dir = scratch("dlrl-collision-check-opendds-shaped");
    std::fs::write(dir.join("sensor.idl"), OPENDDS_SHAPED_PRAGMAS).unwrap();
    let output = idlc()
        .args(["check"])
        .arg(dir.join("sensor.idl"))
        .output()
        .unwrap();
    assert!(output.status.success(), "a warning does not fail check");
    let stdout = String::from_utf8_lossy(&output.stdout);
    assert!(
        stdout.contains("DCPS_DATA_TYPE") && stdout.contains("OpenDDS"),
        "{stdout}"
    );
    assert!(
        stdout.contains("DLRL") && stdout.contains("zerodds-idlc dlrl"),
        "the OpenDDS reading's diagnostic should name the other one: {stdout}"
    );
}

/// The fixture that actually exercises both dialects in one file: DDS 1.2
/// §8's `DCPS_DLRL_RELATION`, which OpenDDS never defined, beside the two
/// pragmas OpenDDS repurposed. `check` reads the first two as OpenDDS's
/// and reports the third by name (not the generic "not a directive this
/// front end interprets" message); `dlrl` reads all three as DLRL's and
/// generates the relation.
#[test]
fn both_dialects_in_one_file_are_each_read_by_their_own_subcommand() {
    let dir = scratch("dlrl-collision-both-in-one-file");
    std::fs::write(dir.join("trade.idl"), TRADE_LEG_DLRL).unwrap();

    let check = idlc()
        .args(["check"])
        .arg(dir.join("trade.idl"))
        .output()
        .unwrap();
    assert!(check.status.success());
    let stdout = String::from_utf8_lossy(&check.stdout);
    assert!(
        stdout.contains("DCPS_DLRL_RELATION") && stdout.contains("zerodds-idlc dlrl"),
        "{stdout}"
    );
    assert!(
        !stdout.contains("not a directive this front end interprets"),
        "DCPS_DLRL_RELATION is named specifically, not folded into the generic message: {stdout}"
    );

    let generate = idlc()
        .args(["dlrl", "--lang", "cpp", "--out"])
        .arg(dir.join("out"))
        .arg(dir.join("trade.idl"))
        .status()
        .unwrap();
    assert!(generate.success());
    let text = std::fs::read_to_string(dir.join("out/trade_dlrl.hpp")).unwrap();
    assert!(
        text.contains("legs_"),
        "the relation reached the generated file: {text}"
    );
}

