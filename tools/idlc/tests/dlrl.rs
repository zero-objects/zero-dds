/// A key whose type has no DLRL key mapping, and a key the structure has
/// no member for, fail the run and write nothing.
#[test]
fn a_key_without_a_mapping_or_a_member_fails_the_run() {
    for (tag, idl) in [
        (
            "sequence",
            "struct T { sequence<long> ids; };\n\
             #pragma DCPS_DATA_TYPE \"T\"\n#pragma DCPS_DATA_KEY \"T ids\"\n",
        ),
        (
            "missing",
            "struct T { long id; };\n\
             #pragma DCPS_DATA_TYPE \"T\"\n#pragma DCPS_DATA_KEY \"T nope\"\n",
        ),
    ] {
        let dir = scratch(&format!("dlrl-key-refused-{tag}"));
        std::fs::write(dir.join("t.idl"), idl).unwrap();
        let out = idlc()
            .args(["dlrl", "--lang", "typescript", "--out"])
            .arg(dir.join("out"))
            .arg(dir.join("t.idl"))
            .output()
            .unwrap();
        let said = format!(
            "{}{}",
            String::from_utf8_lossy(&out.stdout),
            String::from_utf8_lossy(&out.stderr)
        );
        assert!(!out.status.success(), "{tag}: {said}");
        // The key's own name, in `idlc dlrl`'s refusal or — for a member
        // that does not exist — in the front end's IDL0010.
        assert!(
            said.contains(if tag == "missing" {
                "nope"
            } else {
                "DLRL key `ids`"
            }),
            "{tag}: {said}"
        );
        assert!(!dir.join("out/t_dlrl.ts").exists(), "{tag}");
    }
}

/// Every member that is neither a key nor a relation is a mono-valued
/// attribute of the object class (DDS 1.2 §8.1.4.3, set through the object
/// in §8.2.3.5), with a getter and a setter. `price` did not appear in any
