//! `idlc dlrl` — DDS 1.2 §8 DLRL object and home classes, and the
//! pragma-name collision with OpenDDS's own `DCPS_DATA_TYPE`/
//! `DCPS_DATA_KEY` dialect (`crates/idl-lower/tests/dialects.rs` covers
//! that collision from `idl-lower`'s side; this file covers it from
//! `dlrl`'s).

#![allow(clippy::expect_used, clippy::unwrap_used, clippy::panic)]

use std::path::Path;
use std::process::Command;

fn idlc() -> Command {
    Command::new(env!("CARGO_BIN_EXE_zerodds-idlc"))
}

fn scratch(name: &str) -> std::path::PathBuf {
    let dir = Path::new(env!("CARGO_TARGET_TMPDIR")).join(name);
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    dir
}

/// A fixture carrying all three DLRL pragmas: two types, a key apiece,
/// and a relation between them.
const TRADE_LEG_DLRL: &str = "struct Trade { long id; string venue; };\n\
struct Leg { long id; };\n\
#pragma DCPS_DATA_TYPE \"Trade\"\n\
#pragma DCPS_DATA_KEY \"Trade id\"\n\
#pragma DCPS_DATA_KEY \"Trade venue\"\n\
#pragma DCPS_DLRL_RELATION \"Trade legs Leg\"\n\
#pragma DCPS_DATA_TYPE \"Leg\"\n\
#pragma DCPS_DATA_KEY \"Leg id\"\n";

// -- generation, one language at a time -----------------------------------

#[test]
fn cpp_writes_one_bundled_header_with_both_classes_and_the_relation() {
    let dir = scratch("dlrl-cpp");
    std::fs::write(dir.join("trade.idl"), TRADE_LEG_DLRL).unwrap();
    let status = idlc()
        .args(["dlrl", "--lang", "cpp", "--out"])
        .arg(dir.join("out"))
        .arg(dir.join("trade.idl"))
        .status()
        .unwrap();
    assert!(status.success());
    let text = std::fs::read_to_string(dir.join("out/trade_dlrl.hpp")).unwrap();
    assert!(text.starts_with("#pragma once\n"), "{text}");
    assert!(text.contains("Generated by `idlc dlrl`"), "{text}");
    assert!(text.contains("ZeroDDS ships no C++ DLRL runtime"), "{text}");
    assert!(
        text.contains("class Trade : public DLRL::ObjectRoot"),
        "{text}"
    );
    assert!(
        text.contains("class TradeHome : public DLRL::ObjectHome"),
        "{text}"
    );
    assert!(
        text.contains("class Leg : public DLRL::ObjectRoot"),
        "{text}"
    );
    assert!(
        text.contains("DLRL::RefList< Leg* > legs_"),
        "the relation is missing: {text}"
    );
    // Both keys, in pragma order — `venue` is the second `DCPS_DATA_KEY`.
    let id_at = text.find("id_").expect("the id key");
    let venue_at = text.find("venue_").expect("the venue key");
    assert!(id_at < venue_at, "{text}");
}

