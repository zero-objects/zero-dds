/// JLS §7.6: one `public` top-level type per compilation unit, and both
/// the object class and its home are `public` — the same rule
/// `crate::generate::files`'s `ZdTypes.java`/`ZdCodec.java` split is
/// under, applied per DLRL type rather than once per run.
#[test]
fn java_writes_one_object_file_and_one_home_file_per_type() {
    let dir = scratch("dlrl-java");
    std::fs::write(dir.join("trade.idl"), TRADE_LEG_DLRL).unwrap();
    let status = idlc()
        .args(["dlrl", "--lang", "java", "--out"])
        .arg(dir.join("out"))
        .arg(dir.join("trade.idl"))
        .status()
        .unwrap();
    assert!(status.success());
    let mut names: Vec<String> = std::fs::read_dir(dir.join("out"))
        .unwrap()
        .map(|entry| entry.unwrap().file_name().into_string().unwrap())
        .filter(|name| name != "trade.idl")
        .collect();
    names.sort();
    assert_eq!(
        names,
        vec![
            "Leg.java".to_string(),
            "LegHome.java".to_string(),
            "Trade.java".to_string(),
            "TradeHome.java".to_string(),
        ]
    );
    let trade = std::fs::read_to_string(dir.join("out/Trade.java")).unwrap();
    assert!(
        trade.contains("extends org.omg.dds.dlrl.ObjectRoot"),
        "{trade}"
    );
    assert_eq!(trade.matches("public class ").count(), 1, "{trade}");
    let home = std::fs::read_to_string(dir.join("out/TradeHome.java")).unwrap();
    assert!(
        home.contains("extends org.omg.dds.dlrl.ObjectHome"),
        "{home}"
    );
    assert_eq!(home.matches("public class ").count(), 1, "{home}");
}

